#include <cstddef>
#include <cstdint>
#include <utility>
#include <vector>

namespace oxymp::server {

/// Сколько байт разрешено связке снимков.
///
/// Предел от транспорта, а не от протокола. Посылку длиннее MTU ENet режет на
/// куски, и ненадёжными куски бывают только у пакетов с особым признаком —
/// нашего неупорядоченного канала это не касается, его куски идут надёжными: с
/// подтверждениями, переотправкой и ожиданием потерянного.
///
/// Для снимков это худшее, что может случиться. Устаревший снимок приходит
/// заново вместо того, чтобы уступить место свежему, а потерянный кусок
/// задерживает всю связку.
///
/// Тысяча двести взята с запасом от обычных для ENet тысячи четырёхсот: из них
/// вычитается его собственный заголовок, заголовок команды и заголовок UDP, а
/// сама величина ещё и обсуждается сторонами при соединении и вправе оказаться
/// меньше нашей. Запас дешевле: лишняя посылка стоит сорок байт заголовков, а
/// нарезка — надёжности всего канала.
inline constexpr std::size_t kMaxBundleBytes = 1200;

/// Складывает готовые снимки в связки и не даёт связке перерасти посылку.
///
/// Годится для любой связки снимков, а не только для игроков: номер сообщения
/// говорится при начале связки. Правило у всех связок одно — длина одним
/// байтом, снимки подряд, — и заводить второй такой же класс ради второго
/// номера значило бы завести и второе место, где это правило можно нарушить.
///
/// Заведено отдельно от рассылки по двум причинам. Первая — правило здесь
/// одно, а поводов ошибиться в нём три: число снимков не помещается в байт
/// длины, байты не помещаются в посылку, и остаток обязан уехать, а не
/// потеряться. Второе — так его можно проверить, не поднимая сокета.
///
/// Снимки принимаются уже записанными в байты: собирает их рассылка один раз за
/// такт на всех получателей сразу, а сюда они попадают копией.
///
/// Отправитель — довод, а не поле: связка собирается на каждого игрока в такте,
/// и хранить в ней замыкание значило бы заводить его тысячу раз в секунду.
class StateBundler {
public:
    /// Начинает пустую связку. Зовётся перед каждым получателем.
    void reset(shared::MessageId id) {
        id_ = id;

        bytes_.clear();
        bytes_.push_back(static_cast<std::uint8_t>(id_));

        // Место под число снимков: сколько их окажется, станет известно только
        // тогда, когда связка кончится.
        bytes_.push_back(0);

        count_ = 0;
    }

    /// Кладёт в связку готовые байты одного снимка.
    ///
    /// Переполнившаяся связка уходит немедленно, и снимок начинает следующую.
    template<typename Sink>
    void add(shared::ByteView snapshot, Sink&& send) {
        const bool full = count_ == shared::kMaxStatesInBundle ||
                          bytes_.size() + snapshot.size() > kMaxBundleBytes;

        if (full) {
            finish(send);

            // Тем же номером: переполнившаяся связка продолжается следующей, а
            // не превращается в связку другого рода.
            reset(id_);
        }

        bytes_.insert(bytes_.end(), snapshot.begin(), snapshot.end());
        ++count_;
    }

    /// Отдаёт накопленное. Пустая связка не отправляется: получателю нечего
    /// сказать, а посылка всё равно стоила бы сорока байт заголовков.
    template<typename Sink>
    void finish(Sink&& send) {
        if (count_ == 0) {
            return;
        }

        bytes_[1] = count_;
        std::forward<Sink>(send)(shared::ByteView{bytes_});

        count_ = 0;
    }

private:
    /// Номер сообщения нынешней связки.
    ///
    /// Помнится затем, что переполнившаяся связка продолжается следующей — и
    /// продолжаться обязана тем же номером. Довод сюда не передать: переполнение
    /// случается внутри add, а номер называют один раз при начале.
    shared::MessageId id_ = shared::MessageId::PlayerStates;

    /// Буфер живёт между связками: рассылка зовёт это тысячи раз в секунду, и
    /// заводить его заново значило бы выделять память в самом горячем месте.
    std::vector<std::uint8_t> bytes_;

    std::uint8_t count_ = 0;
};

} // namespace oxymp::server
