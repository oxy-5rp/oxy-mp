#pragma once

#include <atomic>
#include <memory>
#include <mutex>
#include <string>
#include <string_view>
#include <thread>
#include <vector>

namespace oxymp::server {

/// Строки, которые хозяин сервера набирает в его окне.
///
/// Своим потоком, а не чтением на такте, и обойти это нельзя: чтение строки со
/// стандартного ввода блокирует до перевода строки, а такт сервера ждать не
/// может — на нём стоят снимки, рассылка и скрипты. Поток читает и складывает,
/// такт забирает накопленное и не ждёт ничего.
///
/// Сам сервер набранным не распоряжается: команд у голого сервера нет и не
/// будет, как нет их и у клиента. Строка уходит скриптам событием
/// `consoleCommand`, а что с ней делать, решает режим. Так же устроено и у
/// alt:V.
///
/// **Консоли у сервера может не быть вовсе** — его запускают службой, из-под
/// другого процесса, с перенаправленным вводом. Тогда чтение отвечает концом
/// потока сразу же, поток тихо заканчивается, и сервер работает как прежде.
/// Жаловаться на это нельзя: отсутствие консоли — обычное дело, а не поломка.
class Console {
public:
    Console();
    ~Console();

    Console(const Console&) = delete;
    Console& operator=(const Console&) = delete;

    /// Забирает накопленные строки и очищает список.
    ///
    /// Забирает, а не показывает: обработчик волен набрать что-нибудь ещё, и
    /// строка, оставленная в списке, ушла бы скриптам дважды.
    [[nodiscard]] std::vector<std::string> take();

private:
    /// Всё, чем поток и такт пользуются вдвоём.
    ///
    /// Отдельной кучкой под общим владением, а не полями самого Console, и это
    /// не украшение. Дождаться читающего потока нельзя — он стоит внутри чтения
    /// строки, и прервать это ожидание стандартными средствами нечем, — значит
    /// он вправе пережить Console. Держи он `this`, и первая же строка, пришедшая
    /// после конца сервера, легла бы в мёртвую память: признака «меня больше
    /// нет» для этого мало — между его проверкой и захватом замка Console успел
    /// бы разрушиться.
    ///
    /// С общим владением такого мгновения не существует: пока жив поток, жива и
    /// эта кучка, а Console от неё просто отвязывается.
    struct Shared {
        std::mutex guard;
        std::vector<std::string> lines;

        /// Нужны ли ещё кому-нибудь набранные строки. false — Console кончился,
        /// и складывать их незачем.
        std::atomic_bool wanted{true};
    };

    static void read(std::shared_ptr<Shared> shared);

    std::shared_ptr<Shared> shared_;
    std::thread reader_;
};

/// Разбирает набранную строку на имя команды и её доводы.
///
/// По пробелам, без кавычек и без экранирования — ровно так же, как alt:V. Имя
/// первым, остальное доводами; пустая строка даёт пустой список, и такую строку
/// объявлять незачем.
///
/// Живёт снаружи класса, потому что проверяется без всякого потока и ввода: это
/// разбор строки, а не чтение консоли.
[[nodiscard]] std::vector<std::string> splitCommand(std::string_view line);

} // namespace oxymp::server
