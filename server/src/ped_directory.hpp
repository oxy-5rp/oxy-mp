#pragma once

#include <oxymp/script/dimension.hpp>
#include <oxymp/shared/protocol/messages.hpp>

#include <cstddef>
#include <unordered_map>

namespace oxymp::server {

/// Прохожие сессии: куклы, которых ставит сервер.
///
/// Устроены как предметы, а не как машины, и это решение. У машины есть ведущий
/// — клиент, считающий её физику, — потому что машина едет и мнётся. Прохожий
/// здесь стоит там, где его поставили: он не ходит, не убегает от выстрелов и не
/// садится за руль. Выдай мы ему ведущего, пришлось бы повторить всё устройство
/// машин вместе с его ценой — ради куклы, которая стоит за прилавком.
///
/// Отличие от предмета одно, и оно в составе: у прохожего есть здоровье, броня и
/// оружие. Меняются они по ходу игры, и потому состояние здесь правится целиком
/// и целиком же уходит клиенту — тем же приёмом, что и у метки на карте.
///
/// Понадобится ходящий прохожий — это будет отдельная работа с отдельным
/// решением: ему нужен ведущий, снимки и задачи. Заводить это заранее, «на
/// будущее», не стоит: ведущий у неподвижной куклы будет ошибкой, которую
/// придётся объяснять.
class PedDirectory {
public:
    /// Прохожий, каким его знает сервер.
    struct Ped {
        shared::PedState state;

        /// В каком слое мира он стоит. См. script/dimension.hpp.
        std::int32_t dimension = script::kDefaultDimension;
    };

    /// Ставит прохожего и выдаёт ему номер.
    ///
    /// limit — сколько их разрешено в сессии. kInvalidPedId означает отказ:
    /// либо предел исчерпан, либо модель негодная.
    ///
    /// Номер в переданном состоянии не читается: его назначает сервер.
    [[nodiscard]] shared::PedId add(shared::PedState state, std::size_t limit);

    /// Правит прохожего целиком. false — такого номера нет.
    ///
    /// Целиком, а не по полю, по той же причине, что и у метки: ресурс правит
    /// куклу редко и сразу помногу — вылечил, одел, вооружил, — а поле за полем
    /// означало бы по сообщению на каждое.
    bool update(shared::PedId id, shared::PedState state);

    /// Переставляет прохожего в другой слой мира. false — его уже нет.
    bool setDimension(shared::PedId id, std::int32_t dimension);

    /// Убирает прохожего. false — прохожего с таким номером не было.
    bool remove(shared::PedId id);

    [[nodiscard]] const Ped* find(shared::PedId id) const;

    [[nodiscard]] const std::unordered_map<shared::PedId, Ped>& all() const noexcept {
        return peds_;
    }

    [[nodiscard]] std::size_t size() const noexcept { return peds_.size(); }

private:
    std::unordered_map<shared::PedId, Ped> peds_;

    /// Счётчик выданных номеров. Растёт и не сбрасывается: номер убранного
    /// прохожего не выдаётся повторно, иначе отставшее сообщение о нём попало бы
    /// в другого, успевшего занять его номер.
    shared::PedId nextId_ = 0;
};

} // namespace oxymp::server
