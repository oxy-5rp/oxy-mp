#include <cstdint>
#include <filesystem>
#include <string>
#include <vector>

namespace oxymp::server {

/// Настройки сервера.
///
/// Отдельным заголовком, а не внутри server.hpp, и это не мелочь. Настройки —
/// значения без поведения: они никого не слушают, ничего не рассылают и о сети
/// не знают. Лежа рядом с сервером, они тянули бы за собой его заголовки —
/// сокеты, соединения, реестры, — и разбор конфигурационного файла оказался бы
/// зависим от ENet, хотя ему нужны три числа и строка.

struct Config {
    std::uint16_t port = shared::kDefaultServerPort;

    /// Сколько игроков пускать разом.
    ///
    /// Сто двадцать восемь — столько же, сколько по умолчанию у alt:V, и число
    /// это не потолок: потолок кладёт транспорт, и он равен 4095 (net::kMaxPeers).
    /// Прежде здесь стояло тридцать два, и стояло без причины — просто число,
    /// написанное тогда, когда игроков не бывало и двух.
    ///
    /// Само по себе оно ничего не решает: цена наплыва лежит в рассылке снимков,
    /// и держится она не пределом, а тем, что снимок пишется раз за такт и
    /// уходит только соседям.
    std::size_t maxPlayers = 128;
    std::string name = "oxyMP";

    /// Пароль, без которого в сессию не пускают.
    ///
    /// Пусто — значит пускают всех, и это значение по умолчанию. Хранится и
    /// сверяется как есть, открытой строкой: пароль здесь — не тайна, а замок
    /// от случайного гостя, и городить вокруг него хранение хешей значило бы
    /// обещать защиту, которой нет — по сети он всё равно идёт открытым.
    std::string password;

    /// Кому позволено распоряжаться из админ-меню.
    ///
    /// По умолчанию — нулевому месту, то есть тому, кто вошёл первым. Обычно это
    /// хозяин сервера, который его и запустил.
    ///
    /// Проверка здесь не от взломщиков: пакет умеет собрать кто угодно. Она от
    /// обычного случая — чтобы гость, зашедший в сессию, не мог собрать к себе
    /// всех остальных.
    std::vector<shared::PlayerId> admins{0};

    /// С чего игрок начинает.
    ///
    /// Своя сумма, к настоящему GTA Online отношения не имеющая. Не ноль, чтобы
    /// в сессии было что тратить с первой минуты.
    std::int64_t startingMoney = 100'000;

    /// Сколько машин разрешено в сессии одновременно.
    ///
    /// Предел не от жадности, хотя со стримингом он и перестал быть жёстким:
    /// клиент заводит у себя не все машины сессии, а только те, что рядом.
    /// Игра всё же держит на свете ограниченное их число, и разом съехавшиеся в
    /// одну точку триста машин уронят её независимо от того, сколько их всего.
    std::size_t maxVehicles = 512;

    /// Сколько предметов разрешено в сессии одновременно.
    ///
    /// Больше, чем машин: предмет не едет, физику ему считать некому, и стоит он
    /// игре дешевле — но не даром, и совсем без предела оставлять его нельзя.
    std::size_t maxObjects = 1024;

    /// Сколько меток на карте разрешено в сессии одновременно.
    ///
    /// Больше, чем предметов: метка не существует в мире вовсе — она нарисована
    /// на карте, и стоит игре только строчки в списке. Предел всё же нужен:
    /// ресурс с ошибкой в цикле поставит их миллион, и карта станет сплошной.
    std::size_t maxBlips = 2048;

    /// Сколько маркеров и контрольных точек разрешено в сессии одновременно.
    ///
    /// Меньше, чем меток, и это не осторожность ради осторожности: метку игра
    /// рисует на карте, а эти двое стоят в мире и перерисовываются каждый кадр.
    /// Сотня фигур под ногами — это сотня вызовов игре на каждый кадр у каждого
    /// игрока, и заметно это станет раньше, чем кончится память.
    std::size_t maxMarkers = 512;
    std::size_t maxCheckpoints = 512;

    /// Сколько урона сервер готов принять за один доклад о попадании.
    ///
    /// Проверка не от взломщика — пакет соберёт кто угодно, — а от испорченного
    /// или ошибочного числа: доклад о тысяче единиц урона убил бы игрока с любым
    /// здоровьем, и разбираться, отчего он умер, было бы не по чему.
    std::uint16_t maxDamagePerHit = 150;

    /// На каком расстоянии клиент узнаёт о происходящем, в метрах.
    ///
    /// Так же устроено в RAGE MP, и число то же самое — там оно называется
    /// stream-distance и лежит в conf.json. Смысл его прост: рассказывать
    /// каждому обо всём — значит слать сотню снимков в секунду о машинах на
    /// другом конце карты, которых он всё равно не увидит.
    ///
    /// Граница не бесплатна: у неё машины и игроки появляются и пропадают, и
    /// делать её слишком тесной нельзя — игрок увидит, как мир возникает у него
    /// перед носом. Пятьсот метров заметно дальше, чем игра успевает прорисовать
    /// что бы то ни было.
    float streamDistance = 500.0F;

    /// С какой погоды начинается сессия, в нумерации игры.
    std::string weather = "EXTRASUNNY";

    /// С какого времени суток начинается сессия.
    std::uint8_t startingHour = 12;
    std::uint8_t startingMinute = 0;

    /// Где игрок появляется в мире.
    ///
    /// Здесь, а не в клиенте, и это перемена: точка появления — свойство
    /// сессии, а не сборки клиента. Хозяин сервера вправе посадить игроков куда
    /// угодно, не пересобирая ничего.
    shared::Vec3 spawnPosition{-1037.7F, -2738.0F, 20.2F};
    float spawnHeading = 328.0F;

    /// Описание меню паузы, которое клиент накладывает поверх игрового.
    ///
    /// Пустой путь означает «не трогать»: игра покажет своё обычное меню, и это
    /// нормальное положение вещей, а не недоделка.
    std::filesystem::path pausemenuPath;

    /// Откуда брать игровые файлы, которые сервер раздаёт клиентам.
    ///
    /// Это готовые `.rpf` — машина, одежда, карта, — а не скрипты. Путь
    /// относительный: сервер запускают из его каталога, и требовать от хозяина
    /// полный путь незачем.
    std::filesystem::path gameFilesDirectory = "resources/dlcpacks";

    /// Где лежат скриптовые ресурсы: каталог на ресурс.
    std::filesystem::path resourceDirectory = "resources";

    /// Какие из них поднимать, по именам каталогов.
    ///
    /// Перечнем, а не «всё, что лежит в каталоге», и это устроено так же, как у
    /// alt:V. Причина не в подражании: ресурс, лежащий рядом, но выключенный, —
    /// обычное дело, а единственный способ выключить его при обходе каталога это
    /// унести его куда-нибудь. Перечень заодно задаёт порядок запуска, а он
    /// значим: подписавшийся первым первым и получит возможность отменить
    /// реплику.
    std::vector<std::string> resources;
};

} // namespace oxymp::server
