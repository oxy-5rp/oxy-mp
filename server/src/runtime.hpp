#pragma once

#include "resource_catalog.hpp"

#include <string>
#include <string_view>

namespace oxymp::server {

/// Скриптовая машина: то, чем ресурс запускается.
///
/// За интерфейсом, и не ради второго языка. Ради проверяемости и ради того,
/// чтобы запуск ресурса выглядел одинаково независимо от того, что внутри:
/// сервер перечисляет ресурсы, находит подходящую машину и говорит ей «подними».
/// Что при этом происходит — её дело.
///
/// Здесь же проходит граница знания. Каталог знает про файлы на диске, машина —
/// про то, как из этих файлов получается работающий ресурс. Поле `main` толкует
/// она: для одного языка это путь к файлу, для другого — имя точки входа, и
/// свести это к одному правилу нельзя, не соврав об одном из двух.
///
/// Машин у сервера может не быть ни одной, и это не поломка, а обычное состояние
/// голого сервера: без них он раздаёт чат и появление, а всякий перечисленный
/// ресурс встречает честной жалобой «машины для такого типа здесь нет».
class Runtime {
public:
    virtual ~Runtime() = default;

    Runtime(const Runtime&) = delete;
    Runtime& operator=(const Runtime&) = delete;

    /// Ресурсы какого типа она поднимает.
    [[nodiscard]] virtual std::string_view type() const noexcept = 0;

    /// Поднимает ресурс. false — с объяснением в error.
    virtual bool start(const ScriptResource& resource, std::string& error) = 0;

    /// Останавливает. Молча, если он и не поднимался.
    ///
    /// Отвечает, было ли что останавливать: строка о остановке уходит в журнал,
    /// а написанная о ресурсе, который и не работал, она врёт.
    virtual bool stop(const ScriptResource& resource) = 0;

protected:
    Runtime() = default;
};

} // namespace oxymp::server
