#pragma once

#include <cstdint>
#include <filesystem>
#include <span>
#include <string>
#include <unordered_map>
#include <vector>

namespace oxymp::server {

/// Ресурсы сервера: то, что он раздаёт клиентам вдобавок к самой игре.
///
/// Хозяин сервера кладёт в `resources/dlcpacks` обычные файлы игры — `amgone.rpf`
/// с машиной, например. Сервер при запуске зашифровывает каждый и держит
/// готовым к раздаче.
///
/// Имя, под которым ресурс раздаётся, — это отпечаток его содержимого, а не
/// исходное имя. Так по ссылке не видно, что за ней лежит, и так же решается
/// вопрос обновления: изменил файл — сменился отпечаток, клиент скачал заново;
/// не менял — клиент не тронулся с места.
class ResourceStore {
public:
    /// Ресурс, каким его видит клиент.
    struct Item {
        /// Исходное имя — для журнала и для человека. Клиенту оно тоже уходит:
        /// по нему он понимает, что скачал, а разбираться в отпечатках незачем.
        std::string name;

        /// Отпечаток содержимого. Он же имя файла при раздаче.
        std::string hash;

        /// Размер уже зашифрованного, в байтах.
        std::uint64_t size = 0;
    };

    /// Собирает и шифрует всё, что лежит в каталоге.
    ///
    /// Отсутствие каталога — не ошибка: сервер без ресурсов совершенно
    /// работоспособен, и требовать пустую папку было бы придиркой.
    void load(const std::filesystem::path& directory);

    /// Добавляет один файл под указанным именем.
    ///
    /// Этим путём уходит клиентская половина скриптовых ресурсов. Отдельной
    /// дороги для неё не заводится намеренно: шифрование, отпечаток, кеш у
    /// клиента и проверка скачанного — всё это ей нужно ровно в том же виде, в
    /// каком нужно игровым файлам. Разница только в имени: у ресурса оно
    /// составное, вида `freeroam/html/hud.html`, чтобы одинаково названные файлы
    /// разных ресурсов не сошлись в одно.
    ///
    /// false — файла нет или он пуст.
    bool add(const std::filesystem::path& path, std::string name);

    /// Складывает файлы ресурса в один свёрток и держит его готовым к раздаче.
    ///
    /// Свёрток раздаётся по отпечатку, как и всё остальное, но **в списке не
    /// показывается**: клиенту его называют сами файлы — каждый знает, в каком
    /// свёртке лежит. Отдельной строкой в списке он был бы лишним, а в счётчике
    /// «сколько качать» — двойным.
    ///
    /// Ради этого свёрток и заведён: клиент кладёт его в кеш целиком и не
    /// раскладывает на диск, а значит исходный код режима не лежит у игрока
    /// обычным текстом. Так же делает alt:V.
    ///
    /// Пустая строка — складывать было нечего.
    [[nodiscard]] std::string addBundle(const std::filesystem::path& root,
                                        std::span<const std::string> files);

    [[nodiscard]] const std::vector<Item>& items() const noexcept { return items_; }

    /// Зашифрованное содержимое по отпечатку. Пусто — такого у нас нет.
    [[nodiscard]] const std::vector<std::uint8_t>* find(const std::string& hash) const;

    /// Нечего ли раздавать вовсе.
    ///
    /// Считается и по свёрткам, а не только по отдельным файлам: ресурс, у
    /// которого весь клиентский код уехал в свёрток, не оставляет в списке ни
    /// одной записи — и раздача по HTTP не поднималась вовсе, а клиент получал
    /// «сервер не ответил» на единственный нужный ему файл.
    [[nodiscard]] bool empty() const noexcept { return items_.empty() && packed_.empty(); }

private:
    std::vector<Item> items_;
    std::unordered_map<std::string, std::vector<std::uint8_t>> packed_;
};

} // namespace oxymp::server
