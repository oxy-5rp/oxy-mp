namespace oxymp::server {

/// Машины сессии. Сервер владеет ими целиком.
///
/// Так было не всегда, и то, как было, объясняет, почему стало иначе. Раньше
/// машины принадлежали клиентам: номер выдавал тот, кто машину создал, а сервер
/// лишь пересылал снимки и проверял право отправителя. Из этого следовали три
/// беды, и все три неустранимы внутри той схемы.
///
/// Брошенная машина исчезала. Пока в ней кто-то сидел, снимки шли; стоило
/// водителю выйти — рассылать её становилось некому, и через несколько секунд
/// молчания её убирали у себя все, включая сервер.
///
/// Вошедший позже видел пустой город. Рассказать ему о машинах было некому:
/// сервер их не знал, а знавшие клиенты рассказывать не умели.
///
/// И машину нельзя было передать. Ведущего вычисляли на месте по правилу «кто
/// занял младшее место», и правило работало ровно до тех пор, пока в машине
/// кто-то сидел.
///
/// Теперь список ведёт сервер. Он выдаёт номера, помнит последнее состояние
/// каждой машины и назначает каждой ведущего — клиента, который считает её
/// физику и рассылает снимки. Машина живёт, пока её не уберут, а не пока о ней
/// говорят; ведущий у неё меняется по ходу игры, и смена эта — обычное дело.
///
/// Физику сервер не считает. Это осознанный предел: считать её пришлось бы
/// заново и по своим правилам, а совпасть с игрой они не могут — значит машина
/// у сервера и машина у игрока разъезжались бы тем сильнее, чем быстрее едут.
/// Поэтому физика живёт там, где живёт игра, — у ведущего, — а сервер держит
/// список, права и последнее известное состояние.
class VehicleDirectory {
public:
    using Clock = std::chrono::steady_clock;

    /// Где стоит игрок — всё, что нужно знать о нём, чтобы назначать ведущих.
    ///
    /// Отдельной структурой, а не ссылкой на список игроков: реестру машин нет
    /// дела ни до имён, ни до денег, ни до соединений, и знать о них он не
    /// должен.
    struct PlayerPlacement {
        shared::PlayerId id = shared::kInvalidPlayerId;
        shared::Vec3 position;

        /// В каком слое мира стоит игрок. См. script/dimension.hpp.
        ///
        /// Нужно затем, что одна точка карты бывает занята много раз: назначать
        /// ведущим того, кто стоит вплотную к машине, но в другом измерении, —
        /// значит назначать того, кто её физически не видит и никогда не
        /// пришлёт по ней ни одного снимка. Машина при этом простаивала бы
        /// замороженной у всех, кто её действительно видит, а ближайший
        /// пересмотр не спохватился бы: сервер считал бы, что ведущий у неё уже
        /// есть.
        std::int32_t dimension = script::kDefaultDimension;
    };

    /// Машина, какой её знает сервер.
    struct Vehicle {
        /// Последнее известное состояние.
        ///
        /// Им сервер отвечает вошедшим и им же оживляет машину, у которой нет
        /// ведущего: пока её никто не считает, она стоит ровно так, как её
        /// оставили.
        shared::VehicleState state;

        /// Кто её ведёт. kInvalidPlayerId — никто.
        shared::PlayerId owner = shared::kInvalidPlayerId;

        /// Кому её назначили скриптом. kInvalidPlayerId — никому.
        shared::PlayerId pinned = shared::kInvalidPlayerId;

        /// Держится ли назначение дальше первой же раздачи.
        bool pinnedSticky = false;

        /// Последняя объявленная внешность. Пусто — её ещё не объявляли.
        std::optional<shared::VehicleAppearance> appearance;

        /// Как она заперта. Значение shared::VehicleLock.
        ///
        /// Помнится сервером и пересказывается вошедшим позже — как и внешность:
        /// запертая машина обязана быть запертой и для того, кто подошёл к ней
        /// через час.
        std::uint8_t lockState = 0;

        /// Какие стёкла опущены, по биту на каждое.
        ///
        /// Помнится сервером по той же причине, что и замок, но причина эта
        /// сильнее: у игры на стёкла есть только «опусти» и «подними», а
        /// вопроса нет вовсе. Не помни их сервер — узнать их было бы неоткуда
        /// ни ему, ни вошедшему позже.
        std::uint8_t windowsOpen = 0;

        /// Говорил ли сервер о стёклах хоть раз. Ноль в самом поле законен и
        /// означает «все подняты», а не «не говорили».
        bool windowsTold = false;

        /// Назначена ли внешность сервером.
        ///
        /// Назначенную объявления ведущего больше не перебивают — см.
        /// setAppearance. Признаком, а не сравнением с заводской: машину можно
        /// назначить и заводской нарочно, и отличить это от «никто ничего не
        /// говорил» иначе нечем.
        bool appearanceFromServer = false;

        /// Когда состояние машины последний раз изменилось.
        ///
        /// Изменилось, а не «пришёл снимок», и разница здесь существенная. Её
        /// ведущий шлёт снимок и тогда, когда машина стоит: не чаще, чем раз в
        /// четверть секунды, но шлёт — иначе он сойдёт за пропавшего. Пересылать
        /// такой снимок незачем: у получателя машина и так стоит там же.
        ///
        /// По этому времени и решает рассылка, кого пересылать в этот такт (см.
        /// Server::broadcastVehicleStates). Стоящая машина не стоит ей ничего.
        Clock::time_point stateAt{};

        /// В каком слое мира она стоит. См. script/dimension.hpp.
        std::int32_t dimension = script::kDefaultDimension;
    };

    /// Где сидит игрок.
    struct Seat {
        shared::VehicleId vehicle = shared::kInvalidVehicleId;
        std::int8_t index = shared::kNoSeat;
    };

    /// Смена ведущего, о которой нужно рассказать всем.
    struct OwnerChange {
        shared::VehicleId id = shared::kInvalidVehicleId;
        shared::PlayerId owner = shared::kInvalidPlayerId;

        /// Кто вёл её до этого. Недействительный — не вёл никто.
        ///
        /// Понадобился скриптам: у alt:V `netOwnerChange` называет обоих, и
        /// режим, снимающий права с прежнего ведущего, без него не знал бы, с
        /// кого снимать.
        shared::PlayerId was = shared::kInvalidPlayerId;
    };

    /// Насколько близко нужно быть к машине, чтобы её вести, в метрах.
    ///
    /// Ведущий обязан видеть машину по-настоящему: он считает её физику силами
    /// самой игры, а игра считает физику только тому, что у неё загружено.
    /// Назначить ведущим того, кто за километр, — значит получить машину,
    /// которая никуда не едет и ни на что не отзывается.
    static constexpr float kOwnershipRange = 300.0F;

    /// Насколько ведущий должен оказаться дальше соперника, чтобы машину у него
    /// забрали, в метрах.
    ///
    /// Без этого запаса двое, стоящие от машины на одинаковом расстоянии,
    /// отбирали бы её друг у друга каждый пересмотр — а каждая смена ведущего
    /// это рассылка всем и рывок машины на экране.
    static constexpr float kHandoverMargin = 50.0F;

    /// Заводит машину и выдаёт ей номер.
    ///
    /// limit — сколько машин разрешено в сессии. Возвращает kInvalidVehicleId,
    /// если предел исчерпан: отказ здесь лучше, чем сессия, в которой у всех по
    /// сотне машин и ни у кого не идёт игра.
    [[nodiscard]] shared::VehicleId add(std::uint32_t model, const shared::Vec3& position,
                                        float heading, shared::PlayerId owner, std::size_t limit);

    /// Запирает машину или отпирает её. false — машины уже нет.
    bool setLockState(shared::VehicleId id, std::uint8_t lockState);

    /// Опускает и поднимает стёкла. false — машины уже нет.
    bool setWindows(shared::VehicleId id, std::uint8_t windowsOpen);

    /// Ставит дверь под нужной степенью в состоянии у себя. false — машины нет.
    ///
    /// У себя — то есть в том состоянии, которым сервер отвечает вошедшим.
    /// Ведущему это не указ: у него машина живёт в игре, и распоряжение о двери
    /// он получает отдельно.
    bool setDoorLevel(shared::VehicleId id, int door, std::uint32_t level);

    /// Переставляет машину в другой слой мира. false — машины уже нет.
    bool setDimension(shared::VehicleId id, std::int32_t dimension);

    /// Назначает машине ведущего, перебивая обычный выбор.
    ///
    /// `sticky` — держать ли назначенного и дальше. Без него назначение
    /// одноразовое: ведущий встанет ближайшей раздачей, а следующая пойдёт
    /// обычным порядком. Назначенный и не сидящий за рулём всё равно уступает
    /// водителю: за рулём и считает поездку должен быть один и тот же человек,
    /// иначе они разъедутся мгновенно.
    ///
    /// `kInvalidPlayerId` снимает назначение. false — машины уже нет.
    bool pinOwner(shared::VehicleId id, shared::PlayerId owner, bool sticky);

    /// Ставит машину в точку у себя.
    ///
    /// У себя — то есть в том состоянии, которым сервер отвечает вошедшим и
    /// оживляет машину без ведущего. Ведущему это не указ: у него машина живёт
    /// в игре, и просьбу переставить её он получает отдельно.
    ///
    /// false — машины уже нет.
    bool place(shared::VehicleId id, const shared::Vec3& position, float heading);

    /// Возвращает машине полные прочности и целые стёкла, двери и колёса.
    ///
    /// Тоже у себя и с той же оговоркой. Вмятины сюда не входят — их форма
    /// нативами не читается и не задаётся вовсе, и хранить её серверу негде.
    ///
    /// false — машины уже нет.
    bool repair(shared::VehicleId id);

    /// Убирает машину. false — машины с таким номером не было.
    bool remove(shared::VehicleId id);

    /// Сидит ли игрок в этой машине.
    ///
    /// Нужно для права убрать её: избавиться от машины вправе тот, кто в ней
    /// сидит, — иначе заказавший её не смог бы от неё отделаться.
    [[nodiscard]] bool isSeatedIn(shared::PlayerId player, shared::VehicleId vehicle) const;

    /// Где игрок сидит. Пустая машина в ответе — идёт пешком.
    ///
    /// Место хранится здесь и больше нигде, и заводить ему второе хранилище у
    /// игрока нельзя: два списка одного и того же расходятся в первый же день.
    /// Оттого спрашивать приходится реестр машин, даже когда речь об игроке.
    [[nodiscard]] Seat seatOf(shared::PlayerId player) const;

    /// Кто сидит в этой машине: место и номер игрока.
    ///
    /// Перебором по списку сидящих, а не отдельной картой «машина — пассажиры».
    /// Вторая карта означала бы второй источник правды о том же самом, и
    /// разошлись бы они на первой же пересадке; сидящих же в сессии редко
    /// больше нескольких десятков, а спрашивают это не в каждом такте.
    [[nodiscard]] std::vector<std::pair<std::int8_t, shared::PlayerId>> seatedIn(
        shared::VehicleId vehicle) const;

    [[nodiscard]] const Vehicle* find(shared::VehicleId id) const;

    /// Принимает снимок от ведущего.
    ///
    /// false означает, что снимок пришёл не от ведущего, и его следует
    /// отбросить целиком. Проверка не от взломщика — пакет соберёт кто угодно, —
    /// а от обычного расхождения: клиент, у которого машину только что забрали,
    /// успевает прислать ещё один снимок по старому праву, и принятый, тот
    /// дёрнул бы машину назад.
    bool applyState(shared::PlayerId sender, const shared::VehicleState& state);

    /// Запоминает внешность, объявленную ведущим.
    ///
    /// false — объявление отброшено: пришло не от ведущего либо внешность этой
    /// машины уже назначена сервером.
    bool applyAppearance(shared::PlayerId sender, const shared::VehicleAppearance& appearance);

    /// Назначает внешность машины от имени сервера.
    ///
    /// С этого мгновения внешность машины принадлежит серверу: объявления
    /// ведущего о ней отбрасываются. Причина — в порядке событий, а не в
    /// недоверии: ведущий снимает внешность со своей игры и присылает её
    /// раз в пару секунд, и снятое им до того, как назначенное дошло, вернуло бы
    /// машину к прежнему виду.
    ///
    /// false — машины уже нет.
    bool setAppearance(shared::VehicleId id, const shared::VehicleAppearance& appearance);

    /// Запоминает, в какой машине и на каком месте сидит игрок.
    ///
    /// Отсюда берётся преимущество водителя при назначении ведущего: машину
    /// считает тот, кто ею правит, и никто другой.
    ///
    /// Возвращает true, если игрок пересел. Это повод пересмотреть ведущих
    /// немедленно: пока пересмотр не прошёл, машина под севшим за руль остаётся
    /// чужой — то есть замороженной, — и полсекунды неподвижного руля игрок
    /// принимает за поломку.
    bool setSeat(shared::PlayerId player, shared::VehicleId vehicle, std::int8_t seat);

    /// Забывает ушедшего игрока.
    ///
    /// Его машины остаются: в них могли остаться пассажиры, и убрать машину
    /// вместе с ушедшим значило бы высадить их посреди дороги. Ведущим он быть
    /// перестаёт — нового назначит ближайший пересмотр.
    void forgetPlayer(shared::PlayerId player);

    /// Пересматривает, кто какую машину ведёт.
    ///
    /// Возвращает только изменения: рассылать всем полный список ведущих
    /// несколько раз в секунду незачем, а сменяются они редко.
    [[nodiscard]] std::vector<OwnerChange> reassign(std::span<const PlayerPlacement> players);

    /// Все машины — для того, кто только что вошёл.
    [[nodiscard]] const std::unordered_map<shared::VehicleId, Vehicle>& all() const noexcept {
        return vehicles_;
    }

    [[nodiscard]] std::size_t size() const noexcept { return vehicles_.size(); }

private:
    /// Кого назначить ведущим этой машины.
    ///
    /// Порядок предпочтения задан здесь и больше нигде, чтобы правило было
    /// видно целиком в одном месте.
    [[nodiscard]] shared::PlayerId chooseOwner(const Vehicle& vehicle,
                                               std::span<const PlayerPlacement> players) const;

    /// Кто сидит за рулём этой машины. kInvalidPlayerId — никто.
    [[nodiscard]] shared::PlayerId driverOf(shared::VehicleId vehicle) const;

    std::unordered_map<shared::VehicleId, Vehicle> vehicles_;

    /// Кто где сидит по последнему снимку игрока.
    std::unordered_map<shared::PlayerId, Seat> seats_;

    /// Счётчик выданных номеров.
    ///
    /// Растёт и никогда не сбрасывается: номер убранной машины не выдаётся
    /// повторно. Иначе снимок, отставший от своей машины на пару кадров, попал
    /// бы в другую, успевшую занять её номер.
    shared::VehicleId nextId_ = 0;
};

} // namespace oxymp::server
