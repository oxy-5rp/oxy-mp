#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace oxymp::server {

/// Один файл, извлечённый из архива `.rpf`.
struct RpfEntry {
    std::string path;               ///< Путь внутри архива, косыми чертами.
    std::vector<std::uint8_t> data; ///< Распакованное содержимое.
};

/// Распаковывает архив RPF7 с незашифрованным оглавлением (метка `OPEN`).
///
/// Игра чужие архивы своими средствами не читает: оглавление она оставляет
/// зашифрованным, а метку `OPEN` не принимает вовсе (см. память
/// [[custom-rpf-load-via-open-parse]] и `packfiles.cpp`). Но моды CodeWalker
/// собираются именно с `OPEN`, где оглавление лежит открытым текстом и ключ не
/// нужен: разобрать его и достать файлы можно самим. Записи бывают сжаты сырым
/// deflate — их распаковывает miniz. Формат снят с `RagePackfile7` CitizenFX
/// (`vfs-core/VFSRagePackfile7.cpp`): заголовок 16 байт, записи по 16, затем
/// таблица имён; каталог опознаётся полем смещения `0x7FFFFF`, у файла смещение
/// в блоках по 512 байт, сжат — когда сжатый размер ненулевой.
///
/// Распаковка идёт на сервере, а не на клиенте, сознательно: сервер и так
/// собирает и раздаёт файлы ресурса, а клиент стримит их уже рабочим путём
/// (`RegisterRawFile`), не трогая ни крипту игры, ни её файловое устройство.
///
/// Пусто с заполненным `error` — не тот формат, зашифрованное оглавление либо
/// битый архив. Половины при ошибке не отдаётся: разница между «этой модели в
/// архиве нет» и «архив битый» изнутри режима не видна, а неполный разбор увёл
/// бы игру по мусорным индексам (то же правило, что и у `tools/gamedata`).
[[nodiscard]] std::vector<RpfEntry> unpackOpenRpf7(const std::uint8_t* bytes, std::size_t size,
                                                   std::string& error);

} // namespace oxymp::server
