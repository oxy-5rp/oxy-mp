#pragma once

#include <filesystem>
#include <string>
#include <unordered_map>
#include <vector>

namespace oxymp::server {

/// Ресурс сервера — единица загрузки.
///
/// Каталог с описанием `resource.cfg` или `resource.toml`, устроенный так же,
/// как у alt:V и RAGE MP: в нём лежит и то, что исполняется на сервере, и то,
/// что уходит клиенту. Единицей взят именно каталог, а не файл, потому что игровой режим —
/// это не один файл: у него есть страницы для интерфейса, картинки и клиентская
/// половина, и включаться и выключаться они обязаны разом.
struct ScriptResource {
    /// Имя каталога. Оно же имя ресурса в перечне и в журнале.
    std::string name;

    /// Где он лежит.
    std::filesystem::path root;

    /// Чем его запускать: `native` — вкомпилировано в сервер, `js` — скрипт.
    std::string type;

    /// Что запускать. Для `native` это имя вкомпилированного ресурса, для `js` —
    /// путь к файлу от корня ресурса.
    ///
    /// Толкует это поле машина, а не каталог: что считать «главным», знает
    /// только тот, кто умеет это запустить.
    std::string main;

    /// С чего начинается клиентская половина. Пусто — её нет.
    std::string clientMain;

    /// Что уходит клиенту, путями от корня ресурса.
    ///
    /// Раздаются они той же дорогой, что и игровые файлы: сервер шифрует их и
    /// отдаёт по отпечатку, клиент кладёт в кеш. Отдельного пути для скриптов
    /// заводить незачем — он был бы точно таким же.
    std::vector<std::string> clientFiles;

    /// Какие из раздаваемых файлов игра обязана прочесть описанием и каким.
    ///
    /// Путь от корня ресурса — имя вида у игры: `stream/vehicles.meta` —
    /// `VEHICLE_METADATA_FILE`. Читается из раздела `[meta]`, как у alt:V.
    ///
    /// Сказанное сервером важнее догадки клиента, и в этом весь смысл. Клиент
    /// умеет узнавать четыре знакомых имени — `handling.meta` и соседей, — а
    /// карты состоят из `.ymap`, `.ytyp` и `.ybn`, и по имени вид у них не
    /// угадывается никак: одно и то же расширение бывает и картой, и её
    /// содержимым. Знает это только тот, кто ресурс собирал.
    std::unordered_map<std::string, std::string> dataFiles;

    /// Исполняется ли ресурс вообще.
    ///
    /// Ложь у ресурсов, которые только раздают файлы: `type = "dlc"` у alt:V —
    /// это машины, карты и звуки, и запускать там нечего. Машину для такого
    /// искать незачем, а не найдя, сервер отказал бы ресурсу целиком — что и
    /// случалось.
    bool executes = true;

    /// Ресурсы, без которых этот не работает.
    ///
    /// Читается из `deps` — так это поле называется у alt:V. Пока только
    /// читается: порядок запуска по нему ещё не выстраивается, и сказано об этом
    /// в docs/scripting.md, в разделе незакрытого. Прочитать его всё же нужно —
    /// иначе описание чужого режима встречало бы жалобой на непонятную настройку
    /// в первой же строке.
    std::vector<std::string> dependencies;
};

/// Перечень ресурсов, прочитанный с диска.
///
/// Читает описания и проверяет то, что можно проверить, не запуская: есть ли
/// каталог, есть ли описание, на месте ли файлы, не уводит ли путь наружу.
/// Годится ли ресурс к запуску по существу — вопрос к скриптовой машине: что
/// значит «главный файл», знает только она.
///
/// Жалобы возвращаются списком, а не останавливают загрузку. Сервер, не
/// поднявшийся из-за опечатки в одном ресурсе, — худшее из возможных поведений:
/// хозяин теряет сессию целиком там, где мог потерять одну её часть.
class ResourceCatalog {
public:
    /// Читает описания перечисленных ресурсов. Возвращает жалобы.
    [[nodiscard]] std::vector<std::string> load(const std::filesystem::path& directory,
                                                const std::vector<std::string>& names);

    [[nodiscard]] const std::vector<ScriptResource>& all() const noexcept { return resources_; }

    [[nodiscard]] bool empty() const noexcept { return resources_.empty(); }

private:
    std::vector<ScriptResource> resources_;
};

} // namespace oxymp::server
