#pragma once

#include <oxymp/shared/protocol/messages.hpp>

#include <chrono>
#include <cstdint>
#include <string>

namespace oxymp::server {

/// Погода и часы сессии.
///
/// Принадлежат серверу целиком, и иначе быть не может. У себя их ставит каждый
/// клиент сам, и предоставленные себе они разойдутся за минуты: у одного полдень
/// и ясно, у другого ночь и гроза. Расходятся при этом не только виды — ночью
/// дальше вытянутой руки не видно, а в дождь машину несёт юзом, и один игрок
/// объясняет другому происходящее у себя как чужую неисправность.
///
/// Часы идут здесь и рассылаются готовым значением. Отдать клиентам «время
/// начала сессии» и позволить им считать самим было бы дешевле на пару байт и
/// неверно: у каждого свой ход кадров, свои паузы на подгрузку и своя минута
/// простоя в меню, и через час они разъедутся на эту минуту.
class WorldClock {
public:
    using Clock = std::chrono::steady_clock;

    /// Сколько игровых минут проходит за настоящую секунду.
    ///
    /// Полминуты — темп самой игры в одиночном режиме: игровая минута за две
    /// настоящие секунды. Держать свой темп незачем, а совпадение с привычным
    /// избавляет от вопроса, почему здесь сутки короче.
    static constexpr double kGameMinutesPerSecond = 0.5;

    /// Как часто время уходит клиентам.
    ///
    /// Две секунды — ровно одна игровая минута при обычном темпе. Чаще незачем:
    /// игровые часы всё равно тикают минутами, и рассылка внутри минуты
    /// повторяла бы уже сказанное.
    static constexpr auto kBroadcastInterval = std::chrono::seconds{2};

    /// Заводит часы на указанном времени суток.
    explicit WorldClock(std::string weather, std::uint8_t hour, std::uint8_t minute);

    /// Продвигает часы. Возвращает true, если время пора разослать.
    ///
    /// Одним вызовом, а не двумя, намеренно: «сколько прошло» считается один
    /// раз, и решение о рассылке принимается по тому же счёту. Разнеси их — и
    /// они разойдутся при первом же изменении темпа.
    bool advance();

    /// Ставит погоду. Возвращает false, если название негодное.
    ///
    /// Проверяется только длина и состав: годится ли такая погода игре, сервер
    /// судить не может — игровых файлов у него нет. Негодное название игра
    /// пропустит мимо, и это худшее, что случится.
    bool setWeather(std::string weather);

    /// Ставит время суток. Возвращает false, если время невозможное.
    bool setTime(std::uint8_t hour, std::uint8_t minute, std::uint8_t second);

    /// Что рассылать клиентам.
    [[nodiscard]] shared::WorldState snapshot() const;

private:
    /// Сколько игровых секунд прошло с полуночи.
    double secondsOfDay_ = 0.0;

    std::string weather_;

    Clock::time_point advancedAt_;
    Clock::time_point broadcastAt_;
};

} // namespace oxymp::server
