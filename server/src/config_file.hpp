#pragma once

#include "config.hpp"

#include <filesystem>
#include <string>
#include <unordered_map>
#include <vector>

namespace oxymp::server {

/// Настройки сервера, прочитанные из файла.
///
/// Файла долго не было намеренно: четырёх параметров он не оправдывал. Теперь
/// их два десятка — точка появления, дальность видимости, погода, список
/// раздаваемого, — и держать их в командной строке стало нельзя: строка запуска
/// перестала помещаться в голове, а хозяин сервера не должен помнить порядок
/// ключей, чтобы поменять погоду.
///
/// Формат простой и намеренно свой, без внешних зависимостей: строка на настройку,
/// «ключ: значение», решётка начинает примечание. Так же выглядит server.cfg у
/// alt:V, и это не подражание — просто такой файл читается человеком без
/// объяснений, в отличие от JSON с его кавычками и запятыми.
///
/// Разбор отделён от применения намеренно: первое — работа с текстом, второе —
/// знание о том, какие у сервера настройки бывают. Смешанные, они превращаются в
/// одну длинную функцию, которую нельзя проверить, не заведя файла на диске.
namespace config_file {

/// Разобранный файл: настройка — её значение, как оно записано.
using Entries = std::unordered_map<std::string, std::string>;

/// Разбирает текст файла.
///
/// Ошибкой считается только то, что нельзя истолковать однозначно: строка без
/// разделителя. Незнакомые ключи ошибкой не считаются и остаются в разборе —
/// судить о том, какие ключи бывают, здесь не по чему.
[[nodiscard]] bool parse(std::string_view text, Entries& entries, std::string& error);

/// Читает файл и разбирает его.
///
/// false означает, что файла нет или он непонятен, и различить это можно по
/// сообщению: у пропавшего файла оно своё. Разделено с applied намеренно —
/// описание ресурса читается тем же разбором, а настроек сервера в нём нет.
[[nodiscard]] bool read(const std::filesystem::path& path, Entries& entries, std::string& error);

/// Разбивает значение по запятым, обрезая пробелы.
///
/// Наружу — потому что списком записываются не только настройки сервера: у
/// ресурса тем же образом перечислены файлы, раздаваемые клиенту.
[[nodiscard]] std::vector<std::string> split(std::string_view value);

/// Прикладывает разобранное к настройкам.
///
/// Возвращает жалобы готовыми предложениями — их место в журнале, слово в слово.
/// Отвергать из-за них файл незачем: сервер поднимется и будет работать, просто
/// не так, как хотел хозяин, — а вот промолчать нельзя, опечатка в имени ключа
/// самая частая беда таких файлов.
[[nodiscard]] std::vector<std::string> apply(const Entries& entries, Config& config);

/// Читает файл и прикладывает его к настройкам.
///
/// Отсутствие файла ошибкой не считается: сервер, запущенный без него, работает
/// на значениях по умолчанию — ровно так же, как работал до его появления.
[[nodiscard]] bool load(const std::filesystem::path& path, Config& config, std::string& error);

} // namespace config_file
} // namespace oxymp::server
