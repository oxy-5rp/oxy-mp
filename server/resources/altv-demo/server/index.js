// Серверная половина показательного режима.
//
// Написана так, как её написали бы под alt:V: ни одной строки, которую пришлось
// бы менять при переносе туда.

'use strict';

const alt = require('alt-server');

alt.log('показательный режим поднят');

alt.on('playerConnect', (player) => {
    alt.log(`вошёл ${player.name}`);

    // Метаданные игрока — из тех, что видит и клиент.
    player.setSyncedMeta('вошёл', new Date().toLocaleTimeString('ru-RU'));

    // Приветствие уходит клиентской половине, а та показывает его страницей.
    alt.emitClient(player, 'демо:привет', player.name, alt.hash('adder'));
});

// Клиент рассказывает, что у него получилось, — сервер это записывает.
alt.onClient('демо:доклад', (player, строки) => {
    for (const строка of строки) {
        alt.log(`[клиент ${player.name}] ${строка}`);
    }
});

// Метаданные сессии: их видит и клиент.
alt.setSyncedMeta('погода', 'ясно');
alt.setSyncedMeta('режим', 'показательный');

// --- Сущности ---------------------------------------------------------------

// Машина у точки появления — чтобы клиенту было что найти в `alt.Vehicle.all`.
// Заводится одна и при подъёме режима: пустой список ничего не проверяет.
const машина = alt.createVehicle('adder', new alt.Vector3(-1030.0, -2735.0, 20.2));

машина.setSyncedMeta('владелец', 'никто');

// Обвесы и покраска — от сервера. Заводскую внешность машина объявляет и сама,
// а места тюнинга заводскими не бывают: их назначает только сервер, и по ним
// видно, дошло ли назначенное.
машина.primaryColor = 12;
машина.secondaryColor = 12;
машина.numberPlateText = 'OXYMP';

машина.setMod(11, 3); // двигатель
машина.setMod(12, 2); // тормоза
машина.setMod(18, 1); // турбина — место-переключатель, а не выбор из списка

машина.neon = { left: true, right: true, front: false, back: false };
машина.neonColor = new alt.RGBA(0, 160, 255, 255);

alt.log(`машина ${машина.id} заведена у точки появления: цвет ${машина.primaryColor}, ` +
        `двигатель ${машина.getMod(11)}, турбина ${машина.getMod(18)}, ` +
        `номер «${машина.numberPlateText}»`);

// Привязка: ящик на крыше машины. Держится он не сервером, а игрой у каждого
// игрока, и по нему видно сразу двоё — что привязка дошла и что она пережила
// появление машины из-за горизонта.
const ящик = new alt.Object('prop_box_wood02a', машина.pos, new alt.Vector3(0, 0, 0));

ящик.attachTo(машина, -1, -1, new alt.Vector3(0, 0, 1.2), new alt.Vector3(0, 0, 0), false, false);

alt.log(`предмет ${ящик.id} привязан к машине ${машина.id}`);

// Клиент сверяет то, что увидел вокруг себя, с тем, что знает сервер.
alt.onClient('демо:вокруг', (player, игроки, машины) => {
    alt.log(`[клиент ${player.name}] видит игроков ${игроки}, машин ${машины}; ` +
            `сервер знает ${alt.Player.all.length} и ${alt.Vehicle.all.length}`);
});

// --- Нарисованное в мире ------------------------------------------------------
//
// Маркер и контрольная точка ставятся сервером, а рисует их игра у игрока. По
// ним и видно, дошло ли: обе стоят у точки появления, в двух шагах друг от
// друга.

const маркер = new alt.Marker(alt.MarkerType.MarkerCylinder,
                              new alt.Vector3(-1029.7, -2738.0, 20.2),
                              new alt.RGBA(0, 160, 255, 160));

// Цилиндр шире и ниже обычного: фигура ростом с человека под ногами не видна.
маркер.scale = new alt.Vector3(2, 2, 1);
маркер.update();

alt.log(`маркер ${маркер.id} поставлен у точки появления`);

// Точка — она же зона: вход и выход в неё сервер считает сам, и это работает
// независимо от того, нарисовалась она у игрока или нет.
// Стоит она в двенадцати метрах к востоку от точки появления, и это не
// случайное место: ровно по этому кругу ходит botclient. Так вход в зону
// проверяется без запуска игры.
const точка = new alt.Checkpoint(0, new alt.Vector3(-1025.7, -2738.0, 20.2), 3.0, 2.0,
                                 new alt.RGBA(255, 180, 0, 160), 0);

точка.nextPos = маркер.pos;
точка.update();

/// Цвета, которыми перекрашивается машина при каждом входе в точку.
///
/// Перекраска здесь не украшение, а проверка второго пути: при входе внешность
/// уходит клиентам живой рассылкой, а не вместе с самой машиной, как вошедшему.
/// Пути два, и сломаться они могут порознь.
const цвета = [12, 27, 38, 89, 111];
let цвет = 0;

/// Где сейчас висит ящик: на игроке или на крыше машины.
let наигроке = false;

alt.on('enterColshape', (зона, player) => {
    if (зона === точка) {
        player.tell('вы в контрольной точке');

        // Движение по слову сервера: его видит и сам игрок, и все, кто рядом.
        player.playAnimation('amb@world_human_hang_out_street@male_c@base', 'base',
                             8, 8, -1, 1);

        цвет = (цвет + 1) % цвета.length;
        машина.primaryColor = цвета[цвет];

        // Ящик перевешивается с крыши на игрока и обратно: так проверяется, что
        // привязка меняется на живом клиенте, а не только доезжает при входе.
        наигроке = !наигроке;

        ящик.attachTo(наигроке ? player : машина, -1, -1,
                      new alt.Vector3(0, 0, наигроке ? 1.0 : 1.2),
                      new alt.Vector3(0, 0, 0), false, false);
    }
});

alt.on('leaveColshape', (зона, player) => {
    if (зона === точка) {
        player.clearTasks();
    }
});

alt.onClient('демо:нажали', (player, что) => {
    alt.log(`${player.name} нажал на странице: ${что}`);
    player.tell(`страница ответила серверу: ${что}`);
});
