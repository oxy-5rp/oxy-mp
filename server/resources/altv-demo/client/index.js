// Клиентская половина показательного режима.
//
// Написана так, как её написали бы под alt:V. Делает три вещи, и каждая из них —
// проверка отдельного куска:
//
//   1. зовёт нативы игры — значит работает таблица хешей и перевод доводов;
//   2. открывает свою страницу поверх кадра — значит работают схема
//      http://resource, слой интерфейса и мостик к нему;
//   3. говорит с сервером в обе стороны — значит работает мостик событий.

'use strict';

const alt = require('alt-client');
const natives = require('natives');

alt.log('клиентская половина поднята');

/// Что удалось выяснить у игры. Уходит и на страницу, и в журнал сервера.
const доклад = [];

function записать(строка) {
    доклад.push(строка);
    alt.log(строка);
}

// --- Нативы -----------------------------------------------------------------

записать(`время игры: ${natives.getGameTimer()}`);

const персонаж = natives.playerPedId();
записать(`персонаж: ${персонаж}`);

if (персонаж !== 0) {
    const где = natives.getEntityCoords(персонаж, true);
    записать(`координаты: ${где.x.toFixed(1)}, ${где.y.toFixed(1)}, ${где.z.toFixed(1)}`);

    записать(`здоровье: ${natives.getEntityHealth(персонаж)}`);
    записать(`модель: ${natives.getEntityModel(персонаж)}`);
}

// Натив с выходными доводами: разрешение экрана возвращается двумя числами
// через указатели, и оба должны дойти обратно.
const [ширина, высота] = natives.getScreenResolution(0, 0);
записать(`экран: ${ширина}x${высота}`);

// --- Общая часть ------------------------------------------------------------

записать(`hash('adder') = 0x${alt.hash('adder').toString(16).toUpperCase()}`);
записать(`длина вектора (3,4,0) = ${new alt.Vector3(3, 4, 0).length}`);
записать(`KeyCode.E = ${alt.KeyCode.E}`);

// --- Страница ---------------------------------------------------------------

// Адрес — тот же, каким его пишет alt:V: имя узла означает «мой ресурс».
const окно = new alt.WebView('http://resource/client/ui/index.html');

записать(`окно ${окно.id} открыто`);

// Страница нажала на кнопку — говорим серверу.
окно.on('нажали', (что) => {
    alt.log(`страница сказала: ${что}`);
    alt.emitServer('демо:нажали', что);
});

// --- Свой персонаж ----------------------------------------------------------

// `alt.Player.local` — так его зовут все ресурсы alt:V.
const я = alt.Player.local;

записать(`имя: ${я.name}, здоровье: ${я.health}, броня: ${я.armour}`);
записать(`я стою в ${я.pos}`);

// --- Метка и маркер ---------------------------------------------------------

// Метка ставится там же, где стоит игрок, — её видно на карте и радаре.
const метка = new alt.PointBlip(я.pos);

метка.sprite = alt.BlipSprite.Centre;
метка.color = alt.BlipColor.Blue;
метка.scale = 0.9;
метка.shortRange = false;
метка.name = 'Точка появления';

записать(`метка ${метка.scriptID} поставлена`);

// Маркер рисуется каждый кадр — за этим следит сам слой.
const маркер = new alt.Marker(alt.MarkerType.MarkerCylinder,
                              я.pos.add(0, 0, -1),
                              new alt.RGBA(124, 198, 255, 140));

маркер.scale = new alt.Vector3(2, 2, 1);

записать('маркер поставлен под ногами');

// --- Сущности вокруг --------------------------------------------------------

// То, ради чего заводился переводчик между номерами сессии и дескрипторами игры.
// Раньше здесь был бы список из одного — себя, — и пустой список машин.
//
// Считается не сразу: и люди, и машины появляются по мере подгрузки моделей, и
// спрошенный в первую секунду список говорит лишь о том, как быстро грузится
// диск. Полторы секунды — это уже про сессию.
alt.setTimeout(() => {
    записать(`игроков в сессии: ${alt.Player.all.length}, ` +
             `рядом: ${alt.Player.streamedIn.length}`);

    for (const кто of alt.Player.all) {
        const свой = кто === alt.Player.local ? ' (это я)' : '';

        // Метаданные чужого игрока — то, что раньше отказывало вслух.
        записать(`  ${кто.id}: ${кто.name}, тело ${кто.scriptID}, ` +
                 `вошёл ${кто.getSyncedMeta('вошёл')}${свой}`);
    }

    записать(`машин в сессии: ${alt.Vehicle.all.length}, ` +
             `рядом: ${alt.Vehicle.streamedIn.length}`);

    for (const что of alt.Vehicle.all) {
        записать(`  машина ${что.id}: тело ${что.scriptID}, ` +
                 `владелец ${что.getSyncedMeta('владелец')}`);
    }

    // Обратный перевод: от дескриптора игры — обратно к номеру сессии.
    const я_же = alt.fromScriptID(natives.playerPedId());
    записать(`себя по дескриптору нашли: ${я_же === alt.Player.local}`);

    alt.emitServer('демо:вокруг', alt.Player.all.length, alt.Vehicle.all.length);
}, 1500);

// --- Разговор с сервером ----------------------------------------------------

alt.onServer('демо:привет', (имя, хеш) => {
    записать(`сервер поздоровался с «${имя}», прислал 0x${хеш.toString(16).toUpperCase()}`);

    записать(`погода из метаданных: ${alt.getSyncedMeta('погода')}`);

    // Страница ждёт готового: разбирать что-либо она не должна.
    окно.emit('состояние', { имя, строки: доклад });
});

// Метаданные, присланные сервером. Доводы — как в alt:V: у сущности первым идёт
// она сама, у общих сущности нет вовсе.
alt.on('syncedMetaChange', (кто, ключ, что, было) => {
    записать(`метаданные ${кто} — ${ключ} = ${что} (было ${было})`);
});

alt.on('globalSyncedMetaChange', (ключ, что, было) => {
    записать(`общие метаданные — ${ключ} = ${что} (было ${было})`);
});

// Доклад уходит серверу — чтобы его было видно и в журнале сервера тоже.
//
// Позже, чем считаются сущности: доклад отправленный раньше, не досчитался бы
// как раз того, ради чего его и читают.
alt.setTimeout(() => alt.emitServer('демо:доклад', доклад), 2000);

// --- Клавиши ----------------------------------------------------------------

alt.on('keydown', (код) => {
    if (код === alt.KeyCode.F2) {
        окно.isVisible = !окно.isVisible;
        alt.log(`страница ${окно.isVisible ? 'показана' : 'скрыта'}`);
        return;
    }

    // F4 берёт в руки то, что выдал сервер. Выданное оружие в руки не идёт само
    // и не должно: подменять человеку ствол посреди перестрелки оттого, что
    // сервер прислал список, — издевательство. А посмотреть на насадки иначе
    // нечем: в кармане их не видно.
    if (код === alt.KeyCode.F4) {
        natives.setCurrentPedWeapon(alt.Player.local.scriptID,
                                    alt.hash('WEAPON_CARBINERIFLE'), true);
        alt.log('карабин взят в руки');
    }
});
