namespace oxymp::client {

/// Всё, что клиент показывает поверх игры.
///
/// Раньше это ходило через разделяемую память: интерфейс жил отдельным
/// процессом, и другого пути к нему не было. Теперь он живёт внутри игры, в том
/// же процессе, — и гонять состояние через страницу памяти, чтобы прочитать
/// собственную запись, стало незачем.
///
/// Пишут сюда трое: сетевой поток (состояние сервера и чат), игровой (ввод,
/// консоль) и журнал (все сообщения клиента). Читает один — тот, что рисует
/// кадр. Отсюда и блокировка: она коротка и никем не оспаривается.
///
/// Список того, что сюда попадает, короток намеренно: чат, консоль и признаки,
/// по которым решается, показывать ли их. Ни денег, ни списка игроков, ни хода
/// подключения здесь нет: первое показывал уголок интерфейса, а он вырезан —
/// что показывать игроку в сессии, решает игровой режим на сервере; второе
/// рассказывает меню alt:V своей страницей.
class UiFeed {
public:
    /// Строка ленты.
    struct Line {
        /// ChatKind для чата, уровень важности spdlog для консоли.
        unsigned int kind = 0;
        std::string text;
    };

    /// На какой стадии вход в мир.
    ///
    /// Спрашивает сетевой поток и пересказывает меню: у страницы alt:V есть своя
    /// полоса «входим в игру», и заполнять её больше нечем — ход входа в мир
    /// виден только изнутри игры.
    void setStage(shared::LoadStage stage);
    [[nodiscard]] shared::LoadStage stage() const;

    /// Игрок появился в мире и стоит на земле.
    ///
    /// Не то же самое, что уход экрана загрузки, и разделены они намеренно.
    /// Появление в мире — это отметка для сети: с него начинается подключение к
    /// серверу. Экран загрузки после этого держится ещё сколько-то — ровно
    /// столько, сколько идёт подключение, — и уходит по setReady.
    ///
    /// Слитые в один признак, они запирали друг друга: сеть ждала ухода экрана,
    /// а экран ждал сети.
    void setWorldReady();

    /// Экран загрузки может уходить: игрок в мире, а с сервером всё решилось —
    /// либо соединение есть, либо ждать его дольше незачем.
    void setReady();

    /// Ушёл ли экран загрузки.
    ///
    /// Спрашивает слой интерфейса, чтобы убрать меню: страница держит себя
    /// открытой, пока считает себя неподключённой, и узнать обратное ей неоткуда
    /// — своей сети у неё нет.
    [[nodiscard]] bool ready() const;

    /// Появился ли игрок в мире.
    ///
    /// Спрашивает сетевой поток, а отвечает игровой — через ту же общую запись,
    /// что и всё остальное здесь. По этому признаку сеть решает, пора ли вообще
    /// подключаться: до появления игрока отправлять нечего, а числиться в сессии
    /// не за кем.
    [[nodiscard]] bool playerInWorld() const;

    /// Отметка о том, что игровой кадр отработал.
    ///
    /// Ею интерфейс узнаёт, что игра жива. Узнать это иначе он не может, а знать
    /// обязан: пока открыто меню паузы, скриптовый тик не идёт вовсе — и чат,
    /// нарисованный поверх меню, застыл бы на последнем состоянии. По давности
    /// последней отметки видно, что игра остановилась, и он убирается сам.
    void beat();

    void pushChat(shared::ChatKind kind, std::string text);

    /// Строка журнала для консоли.
    ///
    /// Консоль живёт на странице меню, а не на своей: она у alt:V есть, умеет
    /// больше нашей и открывается той же клавишей. Своя была вырезана вместе с
    /// экраном загрузки — две консоли по одной клавише выбирали бы, кому
    /// открыться.
    ///
    /// Строки поэтому не рисуются здесь, а забираются takeConsole и уходят
    /// странице меню.
    void pushConsole(unsigned int level, std::string text);

    /// Забирает накопленные строки журнала.
    [[nodiscard]] std::vector<Line> takeConsole();

    /// Строка ввода: открыта ли и что в ней набрано.
    ///
    /// Подписи здесь нет и не нужно: просит строку один только чат, и набранное
    /// показывается там же, где его набирают.
    void setInput(bool active, std::string text);

    /// Открыто ли меню поверх игры.
    ///
    /// Пишет слой интерфейса, читают двое, и обоим это нужно по-разному. Свой
    /// слой по этому признаку прячется целиком: чат, нарисованный поверх меню,
    /// — второй разговор поверх первого. Игровая сессия по нему отбирает у игры
    /// ввод: щелчок по кнопке меню иначе доходит и до персонажа, и тот бьёт по
    /// воздуху. Съеденных сообщений окна для этого мало — мышь и клавиатуру GTA
    /// читает напрямую, мимо них.
    void setMenuOpen(bool open);
    [[nodiscard]] bool menuOpen() const;

    /// Открыто ли меню самой игры — то, что выходит по Escape.
    ///
    /// Свой слой прячется и под ним. Прежде это выводилось из давности
    /// последнего кадра — меню паузы останавливает мир, а с ним и наш тик, — но
    /// вывод оказался неверным: тик идёт, чат остаётся на экране и лежит поверх
    /// игрового меню. Спрашивать надо саму игру, что и делает игровая сессия.
    void setGameMenuOpen(bool open);

    /// Собирает для страницы всё, что изменилось с прошлого раза.
    ///
    /// Ленты отдаются приростом, а не целиком: строки не меняются, меняется их
    /// число, и пересылать всю историю двадцать раз в секунду незачем.
    [[nodiscard]] std::string takeUpdate();

private:
    /// Сколько строк хранится, пока их не забрали.
    ///
    /// Ограничение на случай, когда страница ещё не поднялась, а журнал уже
    /// пишет: без него первые секунды запуска копились бы в памяти целиком.
    static constexpr std::size_t kPending = 400;

    static void trim(std::vector<Line>& lines);

    mutable std::mutex mutex_;

    std::vector<Line> chat_;
    std::vector<Line> console_;

    bool inputActive_ = false;
    std::string inputText_;

    bool menuOpen_ = false;
    bool gameMenuOpen_ = false;

    shared::LoadStage stage_ = shared::LoadStage::Booting;
    bool worldReady_ = false;
    bool ready_ = false;

    /// Когда игровой кадр отработал в последний раз.
    std::chrono::steady_clock::time_point beatAt_{};
};

} // namespace oxymp::client
