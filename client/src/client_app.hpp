#pragma once

namespace oxymp::client {

/// Жизненный цикл модуля внутри процесса игры.
///
/// Единственный владелец всего, что живёт в игре: журнал, настройки и
/// соединение создаются им и живут ровно столько же, сколько он сам.
///
/// Вся работа идёт в отдельном потоке. Точка входа модуля выполняется под
/// блокировкой загрузчика, где почти ничего делать нельзя, поэтому она только
/// просит начать или закончить.
class ClientApp {
public:
    /// Заводит рабочий поток. Возвращает управление немедленно.
    static void requestStart();

    /// Просит поток завершиться.
    ///
    /// Дожидаться его здесь нельзя: выгрузка модуля идёт под блокировкой
    /// загрузчика, и ожидание потока, которому та же блокировка нужна для
    /// завершения, обернётся взаимной блокировкой.
    static void requestStop();
};

} // namespace oxymp::client
