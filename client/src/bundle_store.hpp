#pragma once

#include <oxymp/shared/resource/bundle.hpp>

#include <chrono>
#include <cstdint>
#include <filesystem>
#include <mutex>
#include <span>
#include <string>
#include <string_view>
#include <unordered_map>
#include <vector>

namespace oxymp::client {

/// Свёртки ресурсов, лежащие в кеше нераспакованными.
///
/// Ради этого свёрток и заводился. Прежде клиент, скачав свёрток, раскладывал
/// его на диск деревом под настоящими именами — и исходники режима лежали у
/// игрока обычным текстом, открывались блокнотом и уносились целиком. Разница со
/// старым порядком была только в числе запросов к серверу, а не в том, что
/// оказывалось на диске.
///
/// Теперь свёрток кладётся в кеш как есть и не распаковывается никогда. Файлы из
/// него читаются по требованию — по одному, с того места, где он лежит, — и
/// наружу выходят только в памяти того, кто спросил.
///
/// **Читается с середины, и на этом всё держится.** Формат свёртка выбран так,
/// чтобы кусок расшифровывался, зная лишь своё смещение (см. `Bundle`): иначе
/// пришлось бы держать в памяти весь свёрток целиком, а он бывает в сотни
/// мегабайт.
///
/// Спрашивают отсюда двое, и спрашивают из разных потоков: скриптовая машина —
/// из кадра игры, а страницы интерфейса — из потока ввода-вывода Chromium.
/// Поэтому здесь замок, и он не перестраховка: без него два чтения делили бы
/// один дескриптор файла и один указатель чтения в нём.
class BundleStore {
public:
    /// Заводит хранилище в указанном каталоге. Каталог создаётся при надобности.
    explicit BundleStore(std::filesystem::path directory);

    BundleStore(const BundleStore&) = delete;
    BundleStore& operator=(const BundleStore&) = delete;

    /// Где лежит свёрток с таким отпечатком.
    [[nodiscard]] std::filesystem::path pathOf(const std::string& hash) const;

    /// Лежит ли такой свёрток здесь уже.
    ///
    /// Отвечает по существованию файла и его заголовку, а не по описи: файл
    /// могли стереть мимо нас, и опись, поверившая себе, отправила бы клиента
    /// читать пустоту.
    [[nodiscard]] bool has(const std::string& hash) const;

    /// Кладёт скачанный свёрток на диск под его отпечатком.
    ///
    /// Имя — отпечаток, как и у прочего в кеше: содержимое сменилось — сменилось
    /// имя, и старый свёрток не выдаёт себя за новый.
    [[nodiscard]] bool keep(const std::string& hash, std::span<const std::uint8_t> packed);

    /// Привязывает ресурс к свёртку: с этого мгновения файлы ресурса читаются
    /// отсюда.
    ///
    /// Оглавление разбирается один раз, при привязке, и остаётся в памяти: в нём
    /// тысячи записей, и разбирать его на каждое чтение значило бы расшифровывать
    /// сотню килобайт ради восьми.
    [[nodiscard]] bool bind(std::string resource, const std::string& hash,
                            std::span<const std::uint8_t> key);

    /// Читает файл ресурса из свёртка. false — такого файла в нём нет.
    ///
    /// `file` — путь от корня ресурса, тот самый, которым его назвал автор:
    /// `client/index.js`, `html/hud.html`. Обратные косые черты принимаются
    /// наравне с прямыми — путь мог прийти от Windows.
    [[nodiscard]] bool read(std::string_view resource, std::string_view file,
                            std::vector<std::uint8_t>& contents) const;

    /// Есть ли у нас свёрток этого ресурса.
    [[nodiscard]] bool knows(std::string_view resource) const;

    /// Все пути внутри свёртка ресурса. Пусто — такого ресурса здесь нет.
    ///
    /// Нужен разбору: по нему видно, что именно приехало, а «файл не найден» без
    /// этого списка не отличить от «свёрток не приехал вовсе».
    [[nodiscard]] std::vector<std::string> list(std::string_view resource) const;

    /// Убирает свёртки, которыми давно не пользовались.
    ///
    /// Нужно затем, что иначе кеш растёт без конца. Свёрток называется своим
    /// отпечатком, а отпечаток меняется от всякой правки режима: обновил хозяин
    /// сервера одну строку — и рядом со старым свёртком ложится новый, а старый
    /// не заменяется, потому что зовётся иначе. У большого режима это сотня
    /// мегабайт на каждое обновление.
    ///
    /// Возраст считается по последней записи, а пользование её обновляет (см.
    /// `bind`). Поэтому свёрток, к которому ходят, не стареет, а брошенный
    /// уходит сам. Свёртки этого входа не трогаются вовсе, даже если они старые:
    /// стереть то, что понадобится через мгновение, значило бы качать его
    /// заново.
    void prune(std::chrono::hours maxAge) const;

private:
    /// Один свёрток, готовый к чтению.
    struct Opened {
        std::filesystem::path file;
        shared::Bundle::Header header;

        /// Путь внутри свёртка в его место в теле.
        std::unordered_map<std::string, shared::Bundle::Entry> index;
    };

    /// Приводит путь к тому виду, в котором он лежит в оглавлении.
    [[nodiscard]] static std::string normalize(std::string_view file);

    std::filesystem::path directory_;

    /// Ключ, которым открываются свёртки. Один на все: он один на сборку.
    std::vector<std::uint8_t> key_;

    /// Ресурс в его свёрток.
    std::unordered_map<std::string, Opened> bundles_;

    /// Замок на чтение: спрашивают из двух потоков сразу.
    mutable std::mutex lock_;
};

} // namespace oxymp::client
