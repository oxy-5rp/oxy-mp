#pragma once

#include <cstdint>

namespace oxymp::client {

/// Отпечаток этой машины одним числом.
///
/// Считается по тому, что у Windows не меняется от запуска к запуску и не
/// совпадает у двух разных установок: `MachineGuid` из реестра и серийный номер
/// тома, на котором стоит система. Ни то ни другое не является тайной и никуда
/// больше не уходит — число нужно только затем, чтобы сервер мог отличить
/// одного игрока от другого.
///
/// Доверять ему нельзя, и alt:V не доверяет тоже: считает его чужая машина, и
/// подделать его она вольна. Годится оно ровно на то, на что его используют
/// режимы, — отличить одного от другого, пока он этим не занялся.
///
/// Ноль означает «не вышло»: ни реестр, ни том не обязаны отвечать.
[[nodiscard]] std::uint64_t machineFingerprint() noexcept;

} // namespace oxymp::client
