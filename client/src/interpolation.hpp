#pragma once

#include <oxymp/shared/math/vec3.hpp>

#include <chrono>

namespace oxymp::client {

/// Как считается состояние между снимками.
///
/// Снимки приходят реже кадров и с неровными промежутками. Показывать последний
/// пришедший нельзя: между снимками показывать станет нечего, и движение
/// превратится в рывки. Поэтому чужие показываются с небольшим отставанием от
/// настоящего времени — ровно таким, чтобы в запасе почти всегда была пара
/// снимков, между которыми есть что считать.
///
/// Здесь лежит только счёт. Что именно считается — положение, поворот, скорость,
/// — решают те, кто сюда обращается: и у игрока, и у машины счёт один и тот же, а
/// набор полей разный.
namespace interpolation {

using Clock = std::chrono::steady_clock;

/// На сколько чужие показываются позади настоящего времени.
///
/// Плата за плавность: примерно два промежутка между отправками — этого хватает,
/// чтобы пережить одиночную потерю пакета, не начав достраивать движение
/// вслепую.
inline constexpr auto kDelay = std::chrono::milliseconds{100};

/// Насколько далеко разрешено достраивать движение за последним снимком.
///
/// Без ограничения потерянная связь уводила бы чужого игрока в бесконечность.
inline constexpr auto kMaxExtrapolation = std::chrono::milliseconds{250};

/// Где между двумя снимками мы находимся на это мгновение.
struct Blend {
    /// Доля пути от предыдущего снимка к последнему, от нуля до единицы.
    float progress = 1.0F;

    /// Сколько секунд прошло после последнего снимка. Ноль, пока мы между
    /// снимками; больше нуля — значит свежих снимков нет и движение приходится
    /// достраивать по скорости.
    float ahead = 0.0F;
};

/// Считает долю пути на текущее мгновение.
///
/// Длина промежутка берётся по часам отправителя, а ход времени — по своим, и
/// это разделение здесь главное.
///
/// Раньше и то и другое считалось по времени прихода снимков, и оттого движение
/// дрожало. Снимки уходят ровно двадцать раз в секунду, а приходят как придётся:
/// то через сорок миллисекунд, то через семьдесят. Взяв разницу прихода за длину
/// промежутка, получатель растягивал и сжимал само движение — чужая машина то
/// замедлялась, то дёргалась вперёд, хотя ехала ровно. Отправитель же знает
/// точно, сколько прошло между двумя его снимками, и говорит об этом отметкой
/// времени.
///
/// span — промежуток между снимками по часам отправителя.
/// since — сколько прошло у нас с прихода последнего снимка.
[[nodiscard]] Blend blend(std::chrono::milliseconds span, std::chrono::nanoseconds since) noexcept;

/// Какую долю расхождения закрыть за этот кадр.
///
/// Расхождение между тем, где тело стоит, и тем, где ему положено быть,
/// закрывается не разом, а понемногу: разом — значит отнять у тела физику и
/// получить скользящую по земле коробку.
///
/// Понемногу — это «доля за секунду», а не «доля за кадр», и разница
/// принципиальная. Доля за кадр означает, что расхождение съедается вдвое
/// быстрее при шестидесяти кадрах в секунду, чем при тридцати: у двух зрителей
/// одна и та же машина едет по-разному, и виноват в этом не сеть, а частота
/// кадров. В этом проекте такую ошибку уже ловили — на повороте чужого
/// персонажа, который доходил до нужного угла тогда, когда хозяин смотрел уже в
/// другую сторону.
///
/// rate — во сколько раз расхождение сокращается за секунду, в показателе
/// экспоненты: чем больше, тем резче. seconds — сколько длился кадр.
[[nodiscard]] float catchUp(float rate, float seconds) noexcept;

[[nodiscard]] shared::Vec3 mix(const shared::Vec3& from, const shared::Vec3& to,
                               float progress) noexcept;

/// Достраивает положение по скорости на указанное время вперёд.
[[nodiscard]] shared::Vec3 advance(const shared::Vec3& position, const shared::Vec3& velocity,
                                   float seconds) noexcept;

/// Смешивает два угла по кратчайшей дуге, в градусах.
///
/// Без этого поворот с 350 градусов на 10 выглядел бы как разворот на 340
/// градусов в обратную сторону вместо шага на двадцать — а поворот персонажа
/// через ноль случается каждый раз, когда он оглядывается.
[[nodiscard]] float mixAngle(float from, float to, float progress) noexcept;

/// То же для тройки углов: поворот машины задан тремя.
[[nodiscard]] shared::Vec3 mixAngles(const shared::Vec3& from, const shared::Vec3& to,
                                     float progress) noexcept;

/// Доворачивает углы по угловой скорости, заданной в радианах в секунду.
[[nodiscard]] shared::Vec3 advanceAngles(const shared::Vec3& angles,
                                         const shared::Vec3& angularVelocity,
                                         float seconds) noexcept;

} // namespace interpolation
} // namespace oxymp::client
