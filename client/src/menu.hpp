#pragma once

#include <atomic>
#include <filesystem>
#include <functional>
#include <memory>
#include <string>
#include <string_view>

namespace oxymp::cefui {
class Browser;
}

namespace oxymp::client {

/// Меню внутри игры и весь разговор с ним.
///
/// Страница — altv-ui, взятая у alt:V как есть. Говорит она на своём языке:
/// `alt.emit(имя, ...доводы)` наружу, `alt.on(имя, обработчик)` внутрь. Здесь
/// живёт вторая половина этого разговора — та, что знает, что значит каждое имя.
///
/// Своих правил игры меню не заводит и не может: всё, о чём оно просит, —
/// подключиться, отключиться и выйти. Настройки оно правит в файле, который и
/// без него правится блокнотом.
///
/// Страница живёт в потоке CEF, и оттуда же приходят её события. Всё, что этот
/// класс отдаёт наружу, — либо неизменяемое, либо счётчики: разбирать блокировки
/// в потоке отрисовки игры незачем.
class Menu {
public:
    /// То, что меню просит сделать у того, кто им владеет.
    ///
    /// Обработчики зовутся из потока CEF. Делать в них долгую работу нельзя:
    /// пока они не вернутся, страница не отвечает на мышь.
    struct Actions {
        /// Подключиться. address — `узел:порт`, как его набрал игрок.
        std::function<void(const std::string& address, const std::string& password)> connect;

        /// Отключиться от сервера или бросить попытку подключения.
        std::function<void()> disconnect;

        /// Выйти из игры.
        std::function<void()> quit;

        /// Показать журнал клиента. Страница просит об этом из своей консоли.
        std::function<void()> openLog;

        /// Сказать в чат. Строку набирают в консоли страницы.
        ///
        /// В чат, а не «выполнить команду»: своих правил игры у клиента нет, а
        /// команды разбирают ресурсы сервера — и приходят они к нему чатом.
        /// Ничего сверх того, что игрок может набрать сам, консоль не даёт.
        std::function<void(std::string text)> say;
    };

    /// Заводит меню на уже созданной странице.
    ///
    /// directory — каталог клиента: рядом с ним лежат `oxymp.toml` и `skin.bin`.
    /// Страница при этом ещё не загружена; загружает её сам Menu, потому что
    /// подписаться на её события нужно раньше, чем она успеет что-либо послать.
    [[nodiscard]] static std::unique_ptr<Menu> create(cefui::Browser& browser,
                                                      std::filesystem::path directory,
                                                      Actions actions);

    ~Menu();

    Menu(const Menu&) = delete;
    Menu& operator=(const Menu&) = delete;

    /// Открыто ли меню.
    ///
    /// Пока открыто, мышь и клавиатура принадлежат ему, а не игре. Решает это
    /// сама страница и сообщает событием `ui:open`: она одна знает, открыт ли
    /// поверх неё ещё и разговор о разрешениях.
    [[nodiscard]] bool opened() const noexcept;

    /// Имя, которым назвался игрок. Берётся из настроек.
    [[nodiscard]] std::string playerName() const;

    /// Готова ли страница принимать события.
    ///
    /// Спрашивает тот, кто отдаёт ей журнал: обработчики она заводит, пока
    /// строит свои хранилища, и присланное раньше уходит в никуда. Без этой
    /// проверки первые восемь десятков строк — опознание движка, перечень
    /// модулей, все правки запуска — в консоли не появлялись вовсе.
    [[nodiscard]] bool pageReady() const noexcept;

    /// Открыта ли консоль страницы.
    ///
    /// Спрашивает перехват ввода: пока она открыта, клавиатура и мышь
    /// принадлежат странице, даже если само меню закрыто. Открытая консоль —
    /// это набор текста, и нажатия при этом не должны заодно вести машину.
    [[nodiscard]] bool consoleOpen() const noexcept;

    /// Просит страницу спросить игрока, точно ли он хочет выйти.
    ///
    /// Не выход, а вопрос: у alt:V по Alt+F4 выходит не игра, а её же окно
    /// подтверждения — то самое, что открывается кнопкой в углу меню. Ответит на
    /// него страница обратно тем же словом `exit`, и вот тогда мы выйдем.
    ///
    /// Страница при этом показывает себя сама, даже если меню было закрыто:
    /// открытый разговор она считает поводом появиться.
    void askExit();

    /// Открывает консоль страницы, если она закрыта, и наоборот.
    ///
    /// Своей консоли у клиента больше нет: у страницы alt:V она есть, умеет
    /// больше — раскраску, поиск, повтор команд — и открывается той же клавишей.
    /// Две консоли по одному F8 выбирали бы, кому открыться.
    void toggleConsole();

    /// Отдаёт консоли строку журнала. level — уровень важности spdlog.
    void pushLog(unsigned int level, std::string_view text);

    /// Открывает меню, если оно закрыто, и наоборот.
    ///
    /// Просьбой странице, а не своим счётчиком: открыто ли меню, решает она — у
    /// неё поверх может быть разговор о разрешениях или ввод имени, и закрывать
    /// его чужой волей нельзя. Она же ответит обратно событием `ui:open`.
    void toggle();

    /// Показывает странице ход подключения.
    ///
    /// Имена состояний — те же, что у alt:V, и страница знает их наизусть:
    /// переименовать их нельзя, не поправив её. Каждое она показывает своей
    /// строкой на своём языке, и придумывать к ним подписи не нужно.
    ///
    /// Порядок наш, но из её же слов, и он полон — ровно как у alt:V:
    /// подключаемся к серверу — сверяем ресурсы — забираем недостающие —
    /// запускаем их — грузим игру — входим в мир — вошли. Прежде говорилось
    /// только первое и предпоследнее, и игрок минутами смотрел на одну строку,
    /// не понимая, идёт ли вообще что-нибудь.
    ///
    /// name — имя сервера, а не адрес: страница ждёт строку и показывает её как
    /// есть. Пока сервер не назвал себя, это адрес, каким его набрал игрок.
    void connecting(std::string_view name);

    /// Имя сервера, названное им самим. Приходит в приветствии, позже адреса.
    void nameServer(std::string_view name);

    /// Сверка того, что уже лежит в кеше, с тем, что предлагает сервер.
    void validatingResources(std::size_t done, std::size_t total);

    /// Закачка недостающего.
    void downloadingResources(std::size_t done, std::size_t total);

    /// Ресурсы разложены, сервер их запускает.
    void loadingResources();

    /// Игра грузит мир. Самая долгая часть: минуты.
    void startingGame(unsigned int stage, unsigned int stages);

    /// Мир загружен, идёт появление в нём.
    void joining();

    void connected();
    void disconnected(std::string_view reason);
    void failed(std::string_view reason);

private:
    Menu() = default;

    struct State;
    std::unique_ptr<State> state_;
};

} // namespace oxymp::client
