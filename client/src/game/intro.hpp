#pragma once

#include "engine_addresses.hpp"

namespace oxymp::client::game {

/// Проматывает юридические экраны, которые игра показывает при запуске.
///
/// Длительность их показа — обычное число в данных, и обнулить его безопасно:
/// ни одна инструкция при этом не меняется. На целевой сборке там 15 секунд.
///
/// Нативами этого не сделать: скриптовый тик, единственная точка, где нативы
/// доступны, доходит до клиента через минуту после запуска — когда заставка
/// давно позади. Поэтому работа идёт с памятью напрямую, сразу после опознания
/// движка, на третьей секунде жизни игры.
///
/// Вступительное видео с логотипами Rockstar здесь не трогается, и это выяснено
/// дорого — двумя сломанными запусками. Функция его загрузки перехватывается
/// легко, но оба способа ею воспользоваться игра не переживает:
///
///  - вернуть ноль: вызывающий проверяет результат и обходит показ, но загрузка
///    дальше не идёт вовсе — таблица нативов не заполняется за три минуты,
///    стартовые скрипты не запускаются, экран остаётся чёрным;
///  - подменить имя ролика на несуществующее: таблица нативов заполняется, но
///    игра завершается через шесть секунд после внедрения, не нарисовав ни
///    одного кадра.
///
/// Вывод: ролик — не отдельная мелочь, а часть загрузочной последовательности,
/// и убирать его нужно вместе с ней, через конечный автомат загрузки игры. До
/// тех пор заставка остаётся.
void skipLegalScreens(const EngineAddresses& addresses);

} // namespace oxymp::client::game
