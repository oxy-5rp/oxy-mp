#pragma once

#include "engine_addresses.hpp"

#include <string>

namespace oxymp::client::game {

/// Проматывает юридические экраны, которые игра показывает при запуске.
///
/// Длительность их показа — обычное число в данных, и обнулить его безопасно:
/// ни одна инструкция при этом не меняется. На целевой сборке там 15 секунд.
///
/// Нативами этого не сделать: скриптовый тик, единственная точка, где нативы
/// доступны, доходит до клиента через минуту после запуска — когда заставка
/// давно позади. Поэтому работа идёт с памятью напрямую, сразу после опознания
/// движка, на третьей секунде жизни игры.
///
void skipLegalScreens(const EngineAddresses& addresses);

// Убирания вступительного ролика Rockstar здесь нет, и это проверено дорого —
// тремя способами и дюжиной запусков. Все три игра не переживает:
//
//  - перехватить загрузку ролика и вернуть ноль: вызывающий обходит показ, но
//    загрузка дальше не идёт вовсе — таблица нативов не заполняется за три
//    минуты, стартовые скрипты не запускаются, экран остаётся чёрным;
//  - подменить имя ролика на несуществующее: таблица нативов заполняется, но
//    игра завершается через шесть секунд, не нарисовав ни одного кадра;
//  - обнулить довод «показывать ролик» (`mov cl, 1` → `mov cl, 0`) прямо в месте
//    вызова: игра идёт дальше и выглядит живой — рисует кадры, заполняет нативы,
//    поднимает меню, — но **раскрутка застревает на состоянии 5** («ждём
//    страницу выбора режима») и не сдвигается никогда. Мир не грузится.
//
// Третий способ и был здесь до сих пор, и беда его в том, что она видна не
// сразу: всё остальное работает, а мир просто не приходит. Двенадцать запусков
// подряд без единого входа в мир; сняли — вошли с первого.
//
// Вывод общий: ролик — не украшение, а часть раскрутки, и обойти его, не
// заменив собой, нельзя. У alt:V и CitizenFX загрузочный экран забран целиком,
// вместе с их собственной машиной состояний; наш путь туда же, но это работа
// иного размера. Пока ролик остаётся.

/// Заглушает музыку загрузки.
///
/// Ту самую, что играет на чёрном экране, пока игра поднимается. У alt:V её нет,
/// и правильно: пока висит меню, играть ей не над чем — мир ещё не грузится, а
/// поверх меню она звучит как чужая.
///
/// Делается тем же способом, что и у CitizenFX: функция, заводящая музыку,
/// заменяется на немедленный возврат. Ничего, кроме музыки, она не делает.
bool muteLoadingMusic(const EngineAddresses& addresses, std::string& error);

} // namespace oxymp::client::game
