namespace oxymp::client::game {

/// Движения персонажа: и те, что он отыгрывает сам, и те, что велел сервер.
///
/// Двум разным потребителям, и это не совмещение ради экономии. Оба делают одно
/// и то же — просят у игры набор движений и проигрывают из него движение, — и
/// оба должны знать, загрузился ли набор. Разводить это по двум классам значило
/// бы дважды написать одно ожидание.
///
/// Первый потребитель — куклы чужих игроков. Здесь класс зеркальная половина
/// PedActivity: та читает признаки у настоящего игрока, эта отвечает на них
/// движениями у его изображения.
///
/// Второй — распоряжения сервера (`player.playAnimation` у alt:V). Они приходят
/// и про своего персонажа, и про чужих, а имя движения называет ресурс.
///
/// Признаки делятся надвое, и обходятся эти половины по-разному.
///
/// Одни игра отыгрывает сама, стоит ей сказать, в каком состоянии персонаж:
/// присед — это положение тела, а не движение, и заказывается он один раз.
/// Другим движения нет вовсе: лазание, перемахивание и падение персонаж
/// изобразит сам, если его к этому вынудить, а вынуждает его положение, которое
/// мы и так задаём каждый кадр.
///
/// Третьи — короткие: удар длится доли секунды и не попадает ни в одно
/// состояние. Их приходится проигрывать движением из набора игры, и это
/// единственное место в клиенте, где движения названы по имени: имена всех
/// прочих движений приходят от сервера.
///
/// Вызывать можно только изнутри скриптового тика.
class PedAnimation {
public:
    explicit PedAnimation(const NativeTable& table) noexcept;

    /// Приводит позу персонажа в соответствие с признаками.
    ///
    /// previous нужен, чтобы отличить переход от состояния: заказанное заново
    /// каждый кадр, положение тела сбрасывается до того, как успевает начаться.
    void applyPosture(int ped, std::uint32_t flags, std::uint32_t previous) const;

    /// Проигрывает короткое движение.
    ///
    /// Возвращает false, если движение ещё не готово — набор движений
    /// подгружается, и первый удар может прийтись на то мгновение, когда его
    /// ещё нет. Вызывающему это знать полезно: неудавшийся удар стоит попробовать
    /// в следующем кадре, а не считать показанным.
    [[nodiscard]] bool play(int ped, shared::PedAction action);

    /// Проигрывает движение, названное сервером.
    ///
    /// Отличается от play не только источником имени, но и тем, что признаки
    /// проигрывания задаёт не клиент, а ресурс: у alt:V это доводы
    /// `player.playAnimation`, и подставлять вместо них свои значило бы решать
    /// за режим, как выглядит его отыгрыш.
    ///
    /// Возвращает false, если набор ещё не загрузился. Вызывающему это знать
    /// полезно: движение стоит попробовать в следующем кадре.
    [[nodiscard]] bool playNamed(int ped, const shared::PlayerAnimation& animation);

    /// Снимает с персонажа все задачи, включая начатое движение.
    void clearTasks(int ped) const;

private:
    /// Хеш, одинаковый для строки и для взгляда на неё.
    ///
    /// Нужен затем, что ключи здесь — строки, а спрашивают по ним взглядом:
    /// имя набора приходит то литералом клиента, то полем сообщения. Без
    /// `is_transparent` каждый такой вопрос заводил бы временную строку — то
    /// есть выделял бы память на каждый кадр каждой куклы.
    struct StringHash {
        using is_transparent = void;

        [[nodiscard]] std::size_t operator()(std::string_view value) const noexcept {
            return std::hash<std::string_view>{}(value);
        }
    };

    /// Одно движение из набора игры.
    struct Clip {
        std::string_view dictionary;
        std::string_view name;
    };

    /// Какое движение отвечает какому действию.
    [[nodiscard]] static Clip clipFor(shared::PedAction action);

    /// Заказывает набор движений и говорит, готов ли он.
    ///
    /// О ненайденном наборе жалуется один раз: имя набора либо верное, либо нет,
    /// и повторять это тридцать раз в секунду незачем.
    [[nodiscard]] bool ready(std::string_view dictionary);

    NativeHandler requestDict_ = nullptr;
    NativeHandler hasDict_ = nullptr;
    NativeHandler playAnim_ = nullptr;
    NativeHandler stealthMovement_ = nullptr;
    NativeHandler gameTimer_ = nullptr;
    NativeHandler clearTasks_ = nullptr;

    /// Наборы, о которых уже сказано в журнал, что они не загружаются.
    ///
    /// Ключом строка, а не взгляд на неё, и это не мелочь. Прежде здесь лежали
    /// одни литералы клиента, и взгляд на них жил вечно. Теперь имя набора
    /// называет ресурс сервера, и оно приходит в сообщении, которое кончится
    /// раньше, чем эта запись, — взгляд указал бы в никуда.
    std::unordered_set<std::string, StringHash, std::equal_to<>> complained_;

    /// Когда набор заказан впервые. По этому времени видно, что он не грузится.
    std::unordered_map<std::string, std::int32_t, StringHash, std::equal_to<>> requestedAt_;
};

} // namespace oxymp::client::game
