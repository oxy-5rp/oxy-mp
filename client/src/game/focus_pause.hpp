#pragma once

#include "engine_addresses.hpp"

#include <string>

namespace oxymp::client::game {

/// Оставляет игру идти, когда её окно свёрнуто или ушло за чужое.
///
/// Игра ставит себя на паузу, теряя фокус, и в одиночной игре это верно. В
/// сетевой — обман: персонаж остаётся в мире, его видят остальные, а игрок в это
/// время смотрит на другое окно. Вдобавок пауза не снимается сама — вернувшись,
/// игрок дважды жмёт Escape, прежде чем игра отмирает.
///
/// Правка убирает запись признака и обнуляет сам признак. Обнулять обязательно:
/// признак мог быть выставлен раньше, чем мы до него добрались, — и тогда одной
/// убранной записи мало.
///
/// Не снимается: пауза не нужна ни в какой миг сетевой игры, а возвращать байты
/// при выгрузке некому — клиент уходит вместе с игрой.
[[nodiscard]] bool keepRunningUnfocused(const EngineAddresses& addresses, std::string& error);

} // namespace oxymp::client::game
