#pragma once

#include <oxymp/shared/protocol/messages.hpp>

#include <cstdint>

namespace oxymp::client::game {

/// Кто в этом кадре распоряжается телом чужого игрока.
///
/// Вынесено из RemotePlayers::sync отдельно и без единого вызова натива, и это
/// не наведение порядка. Решение здесь одно из самых запутанных в клиенте —
/// шесть признаков, и почти каждый отменяет соседа, — а проверить его в живой
/// сессии нельзя: понадобилось бы двое игроков, машина, обрыв и чужой ресурс с
/// движением. Отделённое от нативов, оно проверяется списком случаев
/// (`client/tests/puppet_duty_tests.cpp`).
///
/// Цена ошибки здесь высока и своеобразна: почти всякая обращается не в
/// уродство, а в **замирание**. Кукла, у которой мы отняли и задачи, и
/// подведение положения, просто стоит столбом до конца сессии — и понять по
/// такому зрелищу, какой из шести признаков залип, нельзя ничем.
enum class PuppetBody : std::uint8_t {
    /// Физика: тело обмякло, и трогать его нельзя. Только рывок, и только если
    /// оно уехало совсем далеко.
    Physics,

    /// Движение, которое велел сервер. Всякая наша задача отменила бы его.
    Scripted,

    /// Своя задача входа в машину или выхода из неё: она ведёт персонажа к
    /// двери и обратно сама.
    Boarding,

    /// Машина. Она везёт, а нам остаётся показать, куда седок смотрит или
    /// целится.
    Riding,

    /// Мы сами.
    Ours,
};

/// Что решено о кукле на этот кадр.
struct PuppetDuty {
    PuppetBody body = PuppetBody::Ours;

    /// Можно ли задавать позу — присед, плавание, прыжок, укрытие.
    bool posture = false;

    /// Ведём ли мы куклу задачами: походкой, поворотом, прицелом, взглядом.
    ///
    /// Значимо только при Ours. Положение при Ours подводится всегда — тело
    /// обязано оказаться там, где хозяин, — а вот задачи выдаются не всегда:
    /// выданная поверх прыжка задача ходьбы отменяет прыжок.
    bool tasks = false;

    /// Летит ли персонаж вниз без опоры.
    ///
    /// Значимо только при Ours: на переходе в это состояние с куклы снимают
    /// задачу ходьбы, иначе она перебирает ногами в воздухе.
    bool falling = false;

    /// Можно ли показать короткое движение — удар.
    bool action = false;
};

/// Всё, из чего решение складывается.
///
/// Три поля здесь — не признаки снимка, а ответы игры, и потому приходят
/// доводами, а не читаются из flags. limp спрашивается у самой игры (упасть
/// кукла могла и помимо хозяина), scripted — тоже (у движения бывает и повтор
/// без конца, и досрочный конец), а leaving и carried знает только тот, кто
/// ведёт списки машин.
struct PuppetSituation {
    /// Признаки из снимка хозяина.
    std::uint32_t flags = 0;

    /// Скорость по вертикали из того же снимка, метры в секунду.
    float verticalSpeed = 0.0F;

    /// Обмякло ли тело прямо сейчас — по ответу игры, а не по признаку.
    bool limp = false;

    /// Идёт ли движение, которое велел сервер.
    bool scripted = false;

    /// Выдана ли кукле задача вылезти из машины и идёт ли она.
    bool leaving = false;

    /// Сидит ли он в машине, которая у нас есть.
    ///
    /// Именно «которая есть»: модель машины грузится не мгновенно, и седок
    /// машины, которой у нас ещё нет, — это человек, стоящий посреди дороги.
    /// Вести его положением приходится нам.
    bool carried = false;
};

/// Быстрее какого падения вниз человек уже не оступился, а летит, в метрах в
/// секунду.
///
/// Порог отличает полёт с крыши от шага с бордюра: признак падения игра
/// выставляет и там и там. Шесть, а не четыре, и число это взято из прыжка:
/// прыжок поднимает человека метра на полтора, и к концу спуска он набирает те
/// самые четыре с небольшим — на четырёх мы срезали бы приземление у каждого
/// прыжка.
inline constexpr float kFreeFallSpeed = -6.0F;

/// Занят ли персонаж собственным движением, которое отменит задача ходьбы.
///
/// Ровно те признаки, которым отвечает задача. Плавания и погружения здесь нет
/// намеренно: это состояние движения, а не задача, и плывущего вести к цели
/// по-прежнему нужно — иначе он поплывёт на месте.
[[nodiscard]] constexpr bool ownMovement(std::uint32_t flags) noexcept {
    return shared::has(flags, shared::PlayerFlag::Jumping) ||
           shared::has(flags, shared::PlayerFlag::Climbing) ||
           shared::has(flags, shared::PlayerFlag::Vaulting) ||
           shared::has(flags, shared::PlayerFlag::InCover) ||
           shared::has(flags, shared::PlayerFlag::Parachuting) ||
           shared::has(flags, shared::PlayerFlag::GettingUp);
}

/// Решает, кто распоряжается телом и что ему в этом кадре можно.
[[nodiscard]] PuppetDuty dutyFor(const PuppetSituation& situation) noexcept;

} // namespace oxymp::client::game
