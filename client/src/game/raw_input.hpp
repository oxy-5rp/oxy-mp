#pragma once

#include <memory>
#include <string>

namespace oxymp::client::game {

/// Возвращает Windows её горячие клавиши, отобранные игрой.
///
/// Клавиатуру игра берёт через сырой ввод и просит его признаком
/// `RIDEV_NOHOTKEYS`. Признак этот означает «пока моё окно впереди, системных
/// сочетаний не разбирать» — и Windows перестаёт разбирать их все разом, вместе
/// со сменой раскладки. Оттого при запущенной игре Alt+Shift и Win+Пробел не
/// делают ничего: указатель языка не меняется, и в чат нельзя написать ни слова
/// кириллицей.
///
/// Игре этот признак нужен ради одного — чтобы клавиша Windows не сворачивала её
/// посреди перестрелки. Цена же ему — вся раскладка целиком, и цена эта чужая:
/// платит её игрок, которому нужно написать по-русски.
///
/// Поэтому признак снимается: просьба игры перехватывается и доходит до Windows
/// без него. Всё остальное в ней остаётся как было — какие устройства, какое
/// окно, какие ещё признаки.
///
/// Перехват ставится до того, как игра успевает попроситься: она делает это
/// однажды, заводя ввод, и опоздавшая правка не изменила бы ничего.
class RawInput {
public:
    [[nodiscard]] static std::unique_ptr<RawInput> install(std::string& error);

    ~RawInput();

    RawInput(const RawInput&) = delete;
    RawInput& operator=(const RawInput&) = delete;

private:
    RawInput() = default;

    struct State;
    std::unique_ptr<State> state_;

    static State* active_;
};

} // namespace oxymp::client::game
