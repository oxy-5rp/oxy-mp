#pragma once

#include "engine_addresses.hpp"

#include <memory>
#include <string>

namespace oxymp::client::game {

/// Удержание мира: игра не грузится, пока игрок не выбрал сервер.
///
/// Так устроен запуск у alt:V, и до сих пор это была единственная невыполненная
/// строка раздела «Запуск игры» в docs/altv-parity.md.
///
/// Устройство важно понимать целиком, потому что первое побуждение здесь
/// неверно, и это выяснено дорого — дважды.
///
/// **Первая ошибка — чем держать.** У игры своя машина состояний запуска, и
/// заглушить инструкцию, которая толкает её вперёд, достаточно, чтобы мир не
/// грузился. Но отпустить после этого нечем: место игра проходит однажды, поток
/// уходит дальше и назад не возвращается. Поэтому держать нужно не запись, а сам
/// поток — так же, как у CitizenFX (`BlockLoadSetters.cpp`, `WaitForInitLoop`):
/// вместо записи состояния игра зовёт нас, и **её собственный поток остаётся
/// внутри нашего цикла**. Отпустить — значит просто дать циклу закончиться:
/// поток возвращается ровно туда, откуда пришёл, и идёт дальше сам, ничего не
/// зная о задержке.
///
/// **Вторая ошибка — где держать.** Подходящих на вид записей состояния в игре
/// две, в соседних функциях, и обе пишут девятку. Взята была не та: она
/// разрешалась однозначно, выглядела правильно — и не звалась ни разу. Метка в
/// журнале это и показала: удержание стояло, а поток игры к нему не приходил.
/// Верное место — то, что в цикле ожидания раскрутки; туда игру уводит наша же
/// правка страницы выбора режима.
///
/// Цена такого удержания — кадр. Пока поток игры у нас, крутить его больше
/// некому, поэтому цикл каждый оборот зовёт то же, что позвала бы игра:
/// `look_alive` и `critical_system_servicing`. Без них вышла бы не придержанная
/// игра, а повисшее окно.
class WorldHold {
public:
    /// Ставит удержание. Отказ означает, что мир будет грузиться как прежде.
    ///
    /// Ставить нужно рано, в первые секунды жизни игры: до ожидания она доходит
    /// быстро, и опоздавшее удержание держать будет уже нечего.
    [[nodiscard]] static std::unique_ptr<WorldHold> install(const EngineAddresses& addresses,
                                                            std::string& error);

    ~WorldHold();

    WorldHold(const WorldHold&) = delete;
    WorldHold& operator=(const WorldHold&) = delete;

    /// Отпускает мир: игра грузится дальше сама.
    ///
    /// Зовётся из любого потока и повторно безвредно. Возвращает управление, не
    /// дожидаясь загрузки: она занимает минуты, и ждать её тому, кто позвал,
    /// незачем.
    void release() noexcept;

private:
    WorldHold() = default;

    struct State;

    /// То, что игра зовёт вместо записи состояния. Отсюда её поток и не выходит,
    /// пока мир держат.
    static void gameThreadHold();

    /// Единственное удержание на процесс.
    ///
    /// Статическим полем, а не как-нибудь иначе: игра зовёт наш цикл обычным
    /// `call`, без доводов, и передать ему что-либо другим путём нечем.
    static State* active_;

    std::unique_ptr<State> state_;
};

} // namespace oxymp::client::game
