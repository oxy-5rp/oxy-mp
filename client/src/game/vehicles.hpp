namespace oxymp::client::game {

/// Машины сессии в игровом мире.
///
/// Список машин ведёт сервер, и это здесь главное. Раньше его не вёл никто:
/// машину заводил клиент, сам выдавал ей номер и сам же о ней рассказывал, пока
/// в ней сидел. Стоило выйти — и о машине становилось нечего сказать, а через
/// несколько секунд молчания её убирали у себя все. Вошедший позже не узнавал о
/// ней вовсе.
///
/// Теперь всё наоборот: клиент машин не заводит и номеров им не выдаёт. Он
/// получает от сервера список того, что в сессии есть, и приводит мир в
/// соответствие — заводит недостающее, убирает лишнее. Молчание о машине больше
/// ничего не значит: пропала она или нет, говорит сервер, и только он.
///
/// У каждой машины есть ведущий — один клиент, у которого она живёт
/// по-настоящему: игра считает её физику, крутит колёса и мнёт кузов. У
/// остальных та же машина — кукла, которую переставляют по приходящим снимкам.
/// Кто ведущий, решает сервер, и меняется это по ходу игры.
///
/// Отсюда три разных обращения с машиной, и различать их обязательно:
///
/// Наша — не трогаем вовсе. Её ведёт игра, а мы лишь снимаем с неё снимки и
/// отправляем. Наложить на неё пришедшее состояние значило бы бороться с
/// собственной физикой.
///
/// Чужая ведомая — двигаем по снимкам, как раньше.
///
/// Ничья — замораживаем. Машина, брошенная вдали от всех, стоит там, где её
/// оставили: считать её физику некому, а отпущенная без присмотра она сползёт
/// по уклону или провалится сквозь землю при подгрузке мира.
///
/// Вызывать можно только изнутри скриптового тика.
class Vehicles {
public:
    explicit Vehicles(const NativeTable& table) noexcept;
    ~Vehicles();

    Vehicles(const Vehicles&) = delete;
    Vehicles& operator=(const Vehicles&) = delete;

    [[nodiscard]] bool ready() const noexcept;

    /// Машина сессии, какой её описал сервер.
    struct View {
        /// Состояние на текущее мгновение: у ведомой оно уже посчитано
        /// интерполяцией, у ничьей это последнее, что о ней известно.
        shared::VehicleState state;

        /// Кто её ведёт. kInvalidPlayerId — никто.
        shared::PlayerId owner = shared::kInvalidPlayerId;
    };

    /// Где сидит персонаж.
    struct Seat {
        /// Номер машины в игре.
        int vehicle = 0;

        /// Место: -1 водитель, 0 и дальше — пассажирские.
        std::int8_t index = shared::kDriverSeat;
    };

    /// В какой машине и на каком месте сидит персонаж. Пусто — идёт пешком.
    [[nodiscard]] std::optional<Seat> seatOf(int ped) const;

    /// Куда сообщать о попадании по чужой машине.
    using DamageSink = std::function<void(shared::VehicleId vehicle,
                                          const shared::VehicleHarm& harm,
                                          std::uint32_t weapon)>;

    /// Куда отправлять замеченные попадания. Без этого они просто не считаются.
    void reportDamageTo(DamageSink sink) { onDamage_ = std::move(sink); }

    /// Чем игрок держит в руках прямо сейчас.
    ///
    /// Нужно ради одного — назвать оружие в сообщении о попадании по машине.
    /// Разбирать причину урона игра наружу не отдаёт, и ствол в руках здесь
    /// ближе всего к правде.
    [[nodiscard]] std::uint32_t weaponInHand(int localPed) const;

    /// Отнимает у машины прочность по распоряжению сервера.
    ///
    /// Только у той, которую ведём мы: прочность живёт в игре у ведущего, и
    /// отнять её может только он. Остальным о новой прочности расскажет его же
    /// снимок.
    void harm(shared::VehicleId id, const shared::VehicleHarm& harm) const;

    /// Заводит недостающие машины и обновляет уже показанные. Раз в кадр.
    ///
    /// Убирать лишние — забота sweep, и разделение это не формальное. Машины
    /// появляются раньше людей: чужого игрока некуда сажать, пока его машины
    /// нет. А убираются позже них — по той же причине, зеркально: машина,
    /// убранная раньше сидящего в ней, оставляет его в удалённой сущности, и
    /// дальше он живёт указателем в никуда.
    ///
    /// self — наш номер на сервере: по нему машина отличается от чужой.
    ///
    /// localPed нужен, чтобы отличить наши попадания по чужой машине от чужих:
    /// сообщать серверу о попадании, которого мы не наносили, — значит отнимать
    /// у машины прочность дважды.
    /// Запирает машину по слову сервера. Ничего не делает, если такой машины
    /// здесь нет: замок запомнится сервером и приедет с самой машиной.
    void lock(const shared::VehicleControl& control);

    /// Ставит двери машины так, как велел сервер.
    ///
    /// Приходит только ведущему: дверь — часть состояния машины, а состояние
    /// живёт в его игре. Он же расскажет о новом положении остальным своим
    /// обычным снимком.
    void openDoors(const shared::VehicleDoors& doors);

    void sync(const std::vector<View>& vehicles, shared::PlayerId self, int localPed);

    /// Убирает машины, которых в последнем присланном списке не было.
    ///
    /// Вызывать после того, как расставлены люди, и только тогда. Порядок
    /// обязателен: пока в машине кто-то сидит, убирать её нельзя.
    ///
    /// Своего персонажа отдельно проверять не нужно: он занимает место наравне
    /// со всеми, и машина из-под него не уйдёт по той же причине, что и из-под
    /// чужого.
    void sweep();

    /// Снимки машин, которые ведём мы, — для отправки на сервер.
    ///
    /// localPed нужен, чтобы отличить машину, за рулём которой мы сидим, от
    /// прочих ведомых нами: руль, газ и тормоз есть только у водителя, они
    /// читаются из его ввода. Объявлять наши нажатия за поворот руля машины,
    /// стоящей через дорогу, было бы ложью.
    [[nodiscard]] std::vector<shared::VehicleState> describeOwned(int localPed) const;

    /// Внешности наших машин, которые стоит объявить серверу.
    ///
    /// Снятие внешности стоит полусотни вызовов нативов на машину, а машин у нас
    /// бывает десяток. Поэтому снимается она не со всех и не каждый кадр, а по
    /// двум поводам, и других не бывает.
    ///
    /// Машина только что стала нашей — её внешность мы ещё не объявляли, и
    /// объявить обязаны: сервер перескажет её тем, кто войдёт позже.
    ///
    /// Машина под нами — её внешность игрок мог изменить, и изменить он мог её
    /// только сидя за рулём. За этим и нужен resample: вызывающий поднимает его
    /// изредка, зная, сколько времени прошло.
    ///
    /// За раз снимается не больше пары машин: разом объявить весь двор значило бы
    /// сотню вызовов нативов в одном кадре, то есть заметный глазу рывок.
    [[nodiscard]] std::vector<shared::VehicleAppearance> describeOwnedAppearances(int localPed,
                                                                                 bool resample);

    /// Запоминает и накладывает пришедшую внешность машины.
    ///
    /// Внешность может прийти раньше самой машины — и приходит: сервер
    /// пересказывает её вошедшему сразу за появлением машины, а завести машину
    /// клиент успевает не в тот же кадр, если модель ещё грузится. Поэтому она
    /// запоминается независимо от того, есть ли, к чему её приложить.
    void applyAppearance(const shared::VehicleAppearance& appearance);

    /// Ставит машину, которую мы ведём, в назначенную сервером точку.
    ///
    /// Только ведомую нами: чужую переставит её собственный ведущий, получив то
    /// же распоряжение. false — такой машины здесь нет.
    bool place(shared::VehicleId id, const shared::Vec3& position, float heading);

    /// Сажает персонажа в машину по номеру сессии.
    ///
    /// Мгновенно, без подхода к двери: подойти и сесть игрок умеет сам, а
    /// распоряжением сервера его сажают тогда, когда нужно именно посадить.
    ///
    /// false — такой машины здесь нет: она могла не дойти до нас вовсе или
    /// уехать за горизонт между отправкой распоряжения и его приходом.
    bool seat(int ped, shared::VehicleId id, std::int8_t place);

    /// Чинит машину, которую мы ведём: кузов, двигатель, стёкла, двери, колёса
    /// и вмятины.
    ///
    /// Вмятины — то, чего сервер не хранит и хранить не может: их форма
    /// нативами не читается вовсе. Снять их может только игра, и снимает она их
    /// здесь, заодно со всем остальным.
    bool repair(shared::VehicleId id);

    /// Номер в игре у машины с этим номером в сессии.
    ///
    /// Ноль означает «ещё нет»: модель могла не успеть загрузиться. Сажать
    /// персонажа в этом кадре некуда, и это нормально — сядет в следующем.
    [[nodiscard]] int handleFor(shared::VehicleId id) const;

    /// Номер в сессии у машины с этим номером в игре.
    ///
    /// Нужен тому, кто садится: игрок называет машину, в которую сел, а знает о
    /// ней только игровой номер.
    [[nodiscard]] shared::VehicleId idOf(int vehicle) const;

    /// Убирает все машины. Нужно при выходе.
    void clear();

    [[nodiscard]] std::size_t shown() const noexcept { return vehicles_.size(); }

private:
    /// Куда уходят замеченные попадания по чужим машинам.
    DamageSink onDamage_;

    /// Машина сессии и всё, что мы о ней помним.
    struct Entry {
        int vehicle = 0;
        std::uint32_t model = 0;

        /// Кто её ведёт по последнему слову сервера.
        shared::PlayerId owner = shared::kInvalidPlayerId;

        /// Ведём ли её мы. Не выводится из owner на месте намеренно: наш
        /// собственный номер приходит извне, а запись живёт дольше кадра.
        bool ours = false;

        /// Прошлое наложенное состояние. По разнице с новым видно, что
        /// изменилось, — а повреждения накладываются только на изменение:
        /// разбить стекло можно один раз, но приказывать разбивать его каждый
        /// кадр игра будет исправно.
        shared::VehicleState applied;

        /// Наложена ли уже известная внешность.
        bool dressed = false;

        /// Объявляли ли мы её внешность, пока машина наша.
        ///
        /// Сбрасывается вместе со сменой ведущего: пока машину вёл другой, он
        /// мог её перекрасить, и наше прошлое объявление больше не описывает её.
        bool described = false;

        /// До каких степеней доводить двери и до какого мгновения этим
        /// заниматься.
        ///
        /// Дверь не ставится одним вызовом: `SET_VEHICLE_DOOR_CONTROL` ведёт и
        /// держит её, только пока его зовут каждый кадр. Одиночный вызов
        /// сдвигает её на шесть сотых и бросает — со стороны это неотличимо от
        /// «натив не работает», и разобрались в этом только удержанием натива в
        /// живой игре.
        std::uint32_t wantedDoors = 0;

        /// До какого мгновения ждать, что дверь сдвинется.
        ///
        /// Срок нужен не для того, чтобы бросить работу, а чтобы отличить
        /// дверь, которой у модели нет вовсе, от той, что ещё едет: у `adder`
        /// нет багажника, и объявленную ему степень вели бы до конца сессии.
        /// Опустевший означает «уже разобрались».
        std::chrono::steady_clock::time_point doorsUntil{};

        /// Каким замком её просил запереть сервер. Ноль — не просил.
        std::uint8_t wantedLock = 0;

        /// Как машина заперта у нас сейчас. Значение shared::VehicleLock.
        ///
        /// Помнится, чтобы не приказывать игре одно и то же каждый кадр, и
        /// сбрасывается вместе с прочим наложенным при починке: `SET_VEHICLE_FIXED`
        /// возвращает машину заводской, а заводская — незапертая.
        std::uint8_t lockState = 0;

        /// Заморожена ли машина сейчас.
        ///
        /// Помнится, чтобы не приказывать игре одно и то же каждый кадр:
        /// заморозка это переключатель, а не состояние, которое нужно
        /// поддерживать.
        bool frozen = false;

        /// Ушла ли машина из сессии или из виду.
        ///
        /// Помечается при разборе списка, а убирается позже — после того, как
        /// расставлены люди. Между этими двумя мгновениями машина ещё стоит в
        /// мире, и это верно: из неё в этот самый миг выходят её седоки.
        bool doomed = false;

        /// Приводили ли машину в вид, положенный её ведущему, хоть раз.
        ///
        /// Без этого признака только что заведённая ничья машина осталась бы
        /// уязвимой: ведущий у неё не менялся — его не было и нет, — а значит
        /// «сменился ли ведущий» ответило бы «нет», и неуязвимость не выставили
        /// бы никогда.
        bool answered = false;
    };

    /// Заводит машину по её состоянию. Ноль, если модель ещё не загрузилась.
    [[nodiscard]] int spawn(const shared::VehicleState& state);

    void remove(int vehicle) const;

    /// Приводит машину в вид, положенный её нынешнему ведущему.
    ///
    /// Заморозка и неуязвимость зависят от того, чья машина, и меняются вместе
    /// со сменой ведущего — то есть редко. Поэтому они здесь, а не в общем
    /// наложении состояния: звать их каждый кадр незачем.
    /// Приводит машину в то состояние, какого требует её принадлежность.
    ///
    /// towed означает «сцеплена с тягачом»: такую нельзя замораживать, даже
    /// если ведущего у неё нет, — её ведёт тягач.
    void answerTo(Entry& entry, shared::PlayerId owner, bool ours, bool towed) const;

    /// Одевает машину, если для неё известна внешность.
    void dress(shared::VehicleId id, Entry& entry);

    /// Запоминает объявленные сервером степени дверей и защёлкивает те, что
    /// велено закрыть: закрытие даётся игре с первого раза, открытие — нет.
    void wantDoors(Entry& entry, std::uint32_t levels);

    /// Ведёт двери к объявленным степеням. Зовётся каждый кадр у своей машины:
    /// натив держит дверь, только пока его зовут.
    void driveDoors(Entry& entry);

    /// Сидит ли в машине хоть кто-нибудь.
    ///
    /// Спрашивается перед уборкой: игра, у которой убирают машину вместе с её
    /// седоками, остаётся с персонажами, ссылающимися в никуда, и падает — не
    /// сразу, а на ближайшей отрисовке.
    [[nodiscard]] bool occupied(int vehicle) const;

    VehicleSnapshot snapshot_;

    /// Модели, о которых уже сказано, что они не загружаются.
    ///
    /// По хешу и по одному разу: машина заказывается каждый кадр, и без этого
    /// журнал забился бы одной строкой за секунду.
    std::unordered_set<std::uint32_t> complained_;

    /// Номера машин, которые сейчас сцеплены с чьим-нибудь тягачом.
    ///
    /// Собирается заново каждый кадр, до наложения снимков: прицепленную машину
    /// ведёт тягач, а не снимки, и узнать об этом можно только из снимка
    /// тягача — который в списке вполне может стоять и после самого прицепа.
    ///
    /// Живёт между кадрами не ради памяти, а ради того, чтобы не выделять её
    /// заново тридцать раз в секунду.
    std::unordered_set<shared::VehicleId> towed_;

    /// Когда модель заказали впервые. По этому времени и видно, что она не
    /// придёт: у загруженной срок короткий, у отсутствующей его нет вовсе.
    std::unordered_map<std::uint32_t, std::chrono::steady_clock::time_point> requestedAt_;

    NativeHandler requestModel_ = nullptr;
    NativeHandler hasModelLoaded_ = nullptr;
    NativeHandler modelNoLongerNeeded_ = nullptr;
    NativeHandler createVehicle_ = nullptr;
    NativeHandler deleteVehicle_ = nullptr;
    NativeHandler doesExist_ = nullptr;
    NativeHandler asMissionEntity_ = nullptr;
    NativeHandler lodDistance_ = nullptr;
    NativeHandler selectedWeapon_ = nullptr;
    NativeHandler freezePosition_ = nullptr;
    NativeHandler onGroundProperly_ = nullptr;
    NativeHandler engineOn_ = nullptr;
    NativeHandler isInAnyVehicle_ = nullptr;
    NativeHandler vehiclePedIsIn_ = nullptr;
    NativeHandler pedInSeat_ = nullptr;
    NativeHandler maxPassengers_ = nullptr;
    NativeHandler gameTimer_ = nullptr;

    NativeHandler setCoords_ = nullptr;
    NativeHandler setHeading_ = nullptr;
    NativeHandler setVelocity_ = nullptr;
    NativeHandler fix_ = nullptr;
    NativeHandler fixDeformation_ = nullptr;
    NativeHandler intoVehicle_ = nullptr;

    /// Когда шёл прошлый кадр, по игровому времени.
    ///
    /// Нужно, чтобы знать его длительность: расхождение машины со снимком
    /// закрывается понемногу, и «понемногу» обязано считаться от времени, а не
    /// от кадров. Читается один раз за кадр на все машины разом — их бывает
    /// десяток, а часы у игры одни.
    std::int32_t framedAt_ = 0;

    /// Машины сессии по их номеру в ней.
    std::unordered_map<shared::VehicleId, Entry> vehicles_;

    /// Замки машин, которые сюда ещё не доехали.
    ///
    /// Распоряжение о замке приходит всем и сразу, а машина — по расстоянию, и
    /// порядок здесь не обещан ничем. Потеряй мы такое распоряжение, машина
    /// приехала бы незапертой и осталась такой до следующей смены замка.
    std::unordered_map<shared::VehicleId, std::uint8_t> pendingLocks_;

    /// Двери, объявленные до появления машины. По той же причине, что и замки.
    std::unordered_map<shared::VehicleId, std::uint32_t> pendingDoors_;

    /// Последняя известная внешность каждой машины.
    ///
    /// Отдельно от самих машин, потому что переживает их появление: внешность
    /// приходит раньше, чем машину удаётся завести, если модель ещё грузится.
    std::unordered_map<shared::VehicleId, shared::VehicleAppearance> appearances_;
};

} // namespace oxymp::client::game
