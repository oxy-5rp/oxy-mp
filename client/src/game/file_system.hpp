#include "engine_addresses.hpp"

#include <cstdint>
#include <string>
#include <string_view>
#include <vector>

namespace oxymp::client::game {

/// Файловая система игры.
///
/// Игра не читает файлы с диска напрямую. Она разрешает пути своего вида —
/// `common:/data/…`, `platform:/…`, `update:/…` — в цепочку устройств, за
/// которыми стоят архивы `.rpf` с зашифрованным оглавлением. Всё, что игре
/// нужно из данных, приходит через них.
///
/// Отсюда и смысл этого класса. Своя машина или своя правка `settings.meta` не
/// требуют ни распаковки архива, ни пересборки: достаточно поставить поверх
/// нужного пути своё устройство, и игра прочтёт наши байты вместо тех, что
/// лежат в архиве. Так делает alt:V — в его журнале это видно построчно:
/// «Replaced x64/data/control/settings.meta», — и так же делает CitizenFX.
///
/// **Этим снимается тупик со своими машинами.** Работа по ним стояла на подборе
/// схемы шифрования оглавления RPF7: игра не принимает архив с открытым
/// оглавлением, а подобрать её счётом не вышло. Подбирать и не надо — архивы
/// вообще можно не трогать.
///
/// Пока здесь только чтение: спросить у игры, откуда берётся файл и какого он
/// размера. Это первая половина дела и та, на которой проверяется, что мы
/// разговариваем с её файловой системой правильно. Подмена — вторая половина,
/// и до неё нужно своё устройство с таблицей методов, совпадающей с игровой.
class FileSystem {
public:
    /// Заводится по разрешённому каталогу адресов.
    explicit FileSystem(const EngineAddresses& addresses) noexcept;

    /// Готова ли работа: нашлись ли оба адреса.
    [[nodiscard]] bool ready() const noexcept;

    /// Есть ли у игры такой путь и какого он размера.
    ///
    /// Путь — игрового вида, с двоеточием: `common:/data/control/settings.meta`.
    /// Обычный путь Windows здесь не подойдёт: устройства разрешаются по
    /// приставке, и её отсутствие означает, что обслуживать путь некому.
    ///
    /// Возвращает размер в байтах либо -1, если файла нет.
    [[nodiscard]] std::int64_t sizeOf(const char* path) const;

    /// Читает файл целиком средствами игры.
    ///
    /// Ради этого всё и заведено: прочесть можно и то, что лежит внутри архива с
    /// зашифрованным оглавлением, — расшифровывает его сама игра.
    ///
    /// Пустая строка означает, что прочесть не вышло.
    [[nodiscard]] std::string read(const char* path) const;

    /// Перечисляет файлы под путём, заходя во вложенные каталоги.
    ///
    /// Ради архивов. Открытый `.rpf` игра вешает на приставку целиком, и что
    /// внутри — знает только она: оглавление зашифровано, и прочесть его самим
    /// нечем. Обход спрашивает у неё же.
    ///
    /// `directory` — путь игрового вида с косой чертой на конце: `oxymp_pack0:/`.
    /// Возвращаются полные пути файлов, каталоги — только как ступени обхода.
    ///
    /// Глубина ограничена, и не из осторожности: устройство вправе отдать
    /// «каталог» с тем же именем, что и его родитель, — и обход пошёл бы по
    /// кругу до конца памяти.
    [[nodiscard]] std::vector<std::string> filesUnder(const std::string& directory) const;

private:
    /// rage::fiDevice::GetDevice — по пути отдаёт обслуживающее его устройство.
    using DeviceLookup = void*(*)(const char* path, bool allowRoot);

    DeviceLookup lookup_ = nullptr;

    /// rage::fiDevice::MountGlobal. Пока не зовётся: подмена — следующий шаг.
    /// Адрес разрешается здесь же, чтобы отказ обнаружился на старте, а не
    /// тогда, когда подмена понадобится.
    void* mount_ = nullptr;
};

} // namespace oxymp::client::game
