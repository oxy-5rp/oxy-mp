#pragma once

#include "native_table.hpp"

#include <oxymp/shared/protocol/messages.hpp>

#include <cstdint>
#include <string>

namespace oxymp::client::game {

/// Движение, заданное сервером, и вопрос «идёт ли оно ещё».
///
/// Одна на двоих, и это не борьба за краткость. Правило здесь тонкое —
/// отсрочка на начало задачи, разные нативы для движения и сценария, забвение
/// по концу, — а спрашивают его двое: кукла чужого игрока и наш собственный
/// персонаж. Разойдись эти двое хоть в отсрочке, и вышло бы худшее: у себя
/// движение считалось бы идущим, а у соседей уже кончившимся.
///
/// Работает нативами, поэтому спрашивать можно только изнутри скриптового тика.
class ScriptedMotion {
public:
    explicit ScriptedMotion(const NativeTable& table) noexcept;

    /// Запоминает начатое движение.
    void begin(const shared::PlayerAnimation& animation);

    /// Забывает движение, не спрашивая игру. Для тех случаев, когда его сняли
    /// мы сами: зачисткой задач, смертью, пересозданием тела.
    void forget() noexcept;

    /// Идёт ли оно ещё. Спрашивается у игры, а не считается по времени: у
    /// движения бывает и повтор без конца, и своя длительность, и досрочный
    /// конец от чужой задачи.
    ///
    /// Кончившееся забывается тут же: держать за телом движение, которого нет,
    /// значит не вести его вовсе.
    [[nodiscard]] bool playing(int ped);

    /// Набор и имя того, что играет. Пусто — не играет ничего.
    ///
    /// Спрашивать их можно и вне тика: они помнятся, а не читаются у игры.
    [[nodiscard]] const std::string& dictionary() const noexcept { return dictionary_; }
    [[nodiscard]] const std::string& name() const noexcept { return name_; }

    /// Задано ли хоть что-нибудь. Без вопроса игре и без забвения.
    [[nodiscard]] bool named() const noexcept { return !dictionary_.empty() || scenario_; }

private:
    /// Часы игры в миллисекундах.
    [[nodiscard]] std::int32_t now() const;

    NativeHandler playingAnim_ = nullptr;
    NativeHandler usingScenario_ = nullptr;

    /// Часы спрашиваются здесь, а не приходят доводом, и это не мелочь: отсрочку
    /// меряют двое, и разные часы у них означали бы разную отсрочку.
    NativeHandler gameTimer_ = nullptr;

    /// Пустой набор означает, что такого движения нет. Хранятся строками, а не
    /// взглядом на них: имя приходит в сообщении, которое кончится раньше, чем
    /// эта запись.
    std::string dictionary_;
    std::string name_;

    /// Сценарий это или движение. У сценария набора движений нет вовсе, и
    /// спрашивается он у игры другим нативом.
    bool scenario_ = false;

    /// Когда выдали. Нужно на отсрочку: задача начинается в ближайшем
    /// обновлении персонажа, а не в кадре выдачи, и всё это время игра честно
    /// отвечает, что такого движения она не играет. Поверив ей, мы сочли бы
    /// движение кончившимся и снесли бы его в том же кадре, в котором завели.
    std::int32_t startedAt = 0;
};

} // namespace oxymp::client::game
