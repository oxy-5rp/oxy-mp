namespace oxymp::client::game {

/// Убирает страницу выбора режима из загрузки игры.
///
/// Страница, которую игра показывает при запуске, — это новости GTA Online с
/// панелью вкладок внизу, где «Сюжетный режим» крайняя справа. Раньше её
/// проходил слой поверх игры: уводил настоящий указатель в выверенную точку,
/// щёлкал и подтверждал вводом. Работало, но оставалось тем, чем было —
/// подделкой ввода за игрока, с уехавшей мышью и отобранным фокусом.
///
/// Здесь страница не проходится, а не появляется. Игра решает её судьбу сама,
/// одной развилкой: спрашивает вызовом, показывать ли страницу, и при ответе
/// «да» уходит в состояние страницы, при «нет» — сразу к загрузке мира. Оба
/// пути её собственные и оба рабочие; мы лишь делаем выбор за неё, заменив
/// условный переход безусловным.
///
/// Правка ровно в один байт: `74` (переход, если равно) на `EB` (переход
/// всегда). Смещение перехода при этом не меняется, то есть ведёт он туда же,
/// куда вёл, — просто теперь всегда.
///
/// Применять нужно до того, как игра дойдёт до этой развилки. Времени с
/// избытком: развилка случается на исходе первой минуты, а клиент опознаёт
/// движок на третьей секунде.
[[nodiscard]] bool skipLandingPage(const EngineAddresses& addresses, std::string& error);

} // namespace oxymp::client::game
