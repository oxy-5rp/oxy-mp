#pragma once

#include "engine_addresses.hpp"

#include <cstddef>
#include <filesystem>
#include <memory>
#include <mutex>
#include <string>
#include <vector>

namespace oxymp::client::game {

class FileDevice;

/// Опись содержимого карты (`_manifest.ymf`), разобранная самой игрой.
///
/// **Это последнее звено подгрузки чужой карты, и без него не работает ничто.**
/// Модели, расстановка (`.ymap`) и архетипы (`.ytyp`) доезжают до игры и
/// объявляются ей — но расстановка в мир не встаёт. Игра не знает, что эти
/// `.ymap` вообще нужно ставить и от каких архетипов они зависят: про это
/// написано в описи, а описи она не видела.
///
/// Снаружи это выглядит хуже всего, что бывает: в журнале «загружено 3312
/// файлов», в игре — пустое место, и ни одной строки о том, чего не хватило.
///
/// Разбирать опись самим нельзя и не нужно: формат её внутренний, а разбор у
/// игры свой и работающий. Ему нужно ровно две вещи — кусок памяти под
/// результат и файл, лежащий там, где он его ищет.
///
/// Порядок взят у CitizenFX (`LoadStreamingFile.cpp`, `LoadManifest`) и повторён
/// дословно, включая последовательность из четырёх вызовов: приготовить кусок,
/// разобрать в него опись, применить разобранное, освободить кусок. Переставить
/// их местами нельзя — применение читает то, что записал разбор.
class Manifests {
public:
    [[nodiscard]] static std::unique_ptr<Manifests> create(const EngineAddresses& addresses,
                                                           std::string& error);

    ~Manifests() = default;

    Manifests(const Manifests&) = delete;
    Manifests& operator=(const Manifests&) = delete;

    /// Просит разобрать опись, лежащую на диске в кеше клиента.
    ///
    /// Путь дисковый, а не игровой: устройство подставит его само, и подставит
    /// на любое имя, какое игра спросит под своей приставкой.
    ///
    /// `tag` — имя, которым опись зовётся; игра принимает его доводом. Берётся
    /// имя ресурса: описей у карты бывает два десятка, и различать их в журнале
    /// иначе нечем.
    ///
    /// Не разбирает, а откладывает — см. pump. Просить можно откуда угодно.
    void add(std::filesystem::path file, std::string tag);

    /// Разбирает отложенное. **Только из потока с обработчиком скрипта.**
    ///
    /// Причина та же, что у монтирования устройства и у загрузчика описаний:
    /// внутри игра выделяет память своим потоковым аллокатором, а в чужих
    /// потоках его нет вовсе.
    ///
    /// Возвращает, сколько описей разобрано.
    std::size_t pump(FileDevice& device);

    /// Приставка, под которой игра ищет опись.
    ///
    /// Не наша выдумка и менять её нельзя: путь строится внутри кода игры, и
    /// ждёт она его именно здесь. Отсюда и подмена «на всё» у устройства —
    /// какое имя игра запросит под этой приставкой, снаружи неизвестно.
    static constexpr const char* kMountPoint = "localPack:/";

private:
    Manifests() = default;

    /// Разбор описи: кусок, признак (у CitizenFX — единица) и имя.
    using LoadManifest = void (*)(void* chunk, void* packfile, const char* tag);

    /// Приготовить, применить, освободить — все три принимают тот же кусок.
    using ChunkStep = void (*)(void* chunk);

    LoadManifest load_ = nullptr;
    ChunkStep init_ = nullptr;
    ChunkStep apply_ = nullptr;
    ChunkStep clear_ = nullptr;

    /// Кусок памяти под разобранное. Принадлежит игре, живёт сколько она.
    void* chunk_ = nullptr;

    /// Повешено ли уже наше устройство на приставку описей.
    ///
    /// Вешается по надобности, а не при запуске, и это осторожность, а не лень:
    /// приставка эта игры, и она сама вешает на неё свои дополнения. Пока карт
    /// нет, лезть туда незачем.
    bool mounted_ = false;

    /// Что просили разобрать: путь на диске и имя.
    std::vector<std::pair<std::filesystem::path, std::string>> pending_;

    /// Кладёт сеть, забирает кадр игры.
    std::mutex mutex_;
};

} // namespace oxymp::client::game
