#pragma once

#include "engine_addresses.hpp"

#include <memory>
#include <string>

namespace oxymp::client::game {

/// Снимает с игры навязанную раскладку en-US.
///
/// Заводя клавиатуру, игра сверяет раскладку потока со своей и, если та другая,
/// загружает американскую. Оттого при запущенной игре не работает смена
/// раскладки в самой Windows: игрок жмёт Alt+Shift, указатель языка меняется на
/// мгновение и возвращается обратно, а в чат нельзя написать ни слова
/// кириллицей — буквы приходят латинскими, какую бы раскладку ни выбрали.
///
/// Правка убирает сверку и делает безусловным тот переход, которым игра эту
/// загрузку и так пропускает, когда раскладка её устраивает. То есть не
/// придумывает игре нового поведения, а оставляет ей одну из двух её же ветвей.
///
/// Делается однажды и не снимается: раскладка нужна на всё время игры, а
/// возвращать байты на место при выгрузке некому — клиент уходит вместе с игрой.
[[nodiscard]] bool unlockKeyboardLayout(const EngineAddresses& addresses, std::string& error);

/// Переводит ввод на следующий язык — так, как это делает сама Windows.
///
/// Просит об этом службу текстового ввода (TSF, `msctf.dll`), а не переставляет
/// раскладку потоку, и это исправление, оплаченное двумя поломками. Раскладка
/// потока — не источник правды, а её отражение: поставленная напрямую, она
/// живёт доли секунды, после чего служба возвращает свою. Замер это показал
/// дословно — «было 0x419, просили 0x409, стало 0x409», а следующий замер снова
/// показывал 0x419. Попытка же не пустить службу к раскладке уронила игру
/// переполнением стека внутри неё самой.
///
/// Зовётся из потока игры: язык ввода в Windows свой у каждого потока, и
/// смененный в чужом до игры не дойдёт.
void switchInputLanguage();

/// Не даёт игре возвращать себе раскладку.
///
/// Переключить язык мало: игра возвращает свою раскладку раз за разом, и в
/// наблюдении это видно как метание — 0x419, 0x409, 0x419, 0x409, — пока игрок
/// жмёт сочетание. Причина простая: она зовёт `ActivateKeyboardLayout` сама.
///
/// Поэтому её вызовы отбрасываются. Только её: попытка отказать всем подряд
/// уронила игру переполнением стека внутри `MSCTF.dll` — раскладку у Windows
/// просит и сама служба текстового ввода, и на отказ она отвечает новой
/// попыткой. Свой от чужого отличается не догадкой, а адресом возврата: он либо
/// лежит в теле `GTA5.exe`, либо нет.
///
/// Игре от этого вреда нет: клавиатуру она читает кодами клавиш, то есть
/// местами на клавиатуре, а не буквами. Буквы нужны игроку — в чате.
class LayoutGuard {
public:
    [[nodiscard]] static std::unique_ptr<LayoutGuard> install(std::string& error);

    ~LayoutGuard();

    LayoutGuard(const LayoutGuard&) = delete;
    LayoutGuard& operator=(const LayoutGuard&) = delete;

private:
    LayoutGuard() = default;

    struct State;
    std::unique_ptr<State> state_;

    static State* active_;
};

} // namespace oxymp::client::game
