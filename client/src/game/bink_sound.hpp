#pragma once

#include <memory>
#include <string>

namespace oxymp::client::game {

/// Глушит звук роликов, которые игра проигрывает через Bink.
///
/// Ролик со знаком Rockstar и уличными сиренами убрать целиком нельзя: правка,
/// которая его убирала, останавливала загрузку мира намертво (см. intro.hpp).
/// Остаётся убрать хотя бы звук — и это как раз можно, потому что звук у ролика
/// свой и заводится отдельно.
///
/// Проигрывает ролики `bink2w64.dll`, и звук у неё включается тремя вызовами:
/// один задаёт звуковую подсистему на всю библиотеку, два других — звук
/// отдельного ролика. Перехватываются все три, и каждый пишет в журнал, что его
/// позвали: заранее не известно, каким из них пользуется именно эта сборка игры,
/// а по журналу это видно с первого запуска.
///
/// Ничего, кроме роликов, через Bink в GTA V не звучит: музыка, речь и мир идут
/// своим движком.
class BinkSound {
public:
    /// Глушит звук. Отказ означает, что ролик прозвучит как прежде.
    [[nodiscard]] static std::unique_ptr<BinkSound> mute(std::string& error);

    ~BinkSound();

    BinkSound(const BinkSound&) = delete;
    BinkSound& operator=(const BinkSound&) = delete;

private:
    BinkSound() = default;

    struct State;
    std::unique_ptr<State> state_;
};

} // namespace oxymp::client::game
