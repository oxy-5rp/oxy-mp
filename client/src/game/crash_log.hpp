#pragma once

#include <memory>

namespace oxymp::client::game {

/// Запись падений игры в наш журнал.
///
/// Заводится потому, что без неё крах не оставляет следа: журнал просто
/// обрывается на последней успевшей записи, и о причине известно ровно столько
/// же, сколько было бы известно без журнала вовсе. Разбирать это приходилось
/// сопоставлением времени — «упало сразу после вот этой строки», — а такой
/// разбор говорит, когда упало, но не где.
///
/// Ловушка ставится первой в очереди обработчиков и ничего не решает: она
/// записывает код исключения, адрес, модуль и смещение в нём — и передаёт
/// исключение дальше, тому, кому оно предназначалось. Игра при этом ведёт себя
/// ровно так же, как без неё.
///
/// Записываются только смертельные исключения. Обычных, которые игра ловит сама
/// и переживает, в ней за секунду проходят десятки, и записывать их значило бы
/// утопить журнал в шуме.
class CrashLog {
public:
    [[nodiscard]] static std::unique_ptr<CrashLog> install();

    ~CrashLog();

    CrashLog(const CrashLog&) = delete;
    CrashLog& operator=(const CrashLog&) = delete;

private:
    CrashLog() = default;

    void* handle_ = nullptr;
};

} // namespace oxymp::client::game
