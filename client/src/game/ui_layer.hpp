#include <windows.h>

namespace oxymp::client {
class UiFeed;
}

namespace oxymp::client::game {

/// Игровой интерфейс внутри кадра игры.
///
/// Раньше он был отдельным окном поверх игры, и это работало ровно до тех пор,
/// пока игра оставалась впереди: окно принадлежит рабочему столу, исчезает при
/// сворачивании, спорит с полноэкранным режимом и живёт по чужим правилам.
/// Правильно — как у RAGE MP и alt:V: интерфейс должен быть частью кадра.
///
/// Собирается он из трёх частей, и ни одна не заменяет другую:
///
/// 1. Страница на CEF, нарисованная в память. Окна у неё нет вовсе: готовые
///    точки приходят прямо в обработчик, с настоящей прозрачностью.
/// 2. Перехват показа кадра — единственное место, откуда можно рисовать в кадр
///    игры.
/// 3. Вывод точек на весь кадр поверх всего остального.
///
/// Так же устроен интерфейс у RAGE MP и alt:V, и по той же причине: другой
/// браузерный движок отдаёт страницу только в окно, а окно поверх игры
/// принадлежит рабочему столу и живёт по его правилам.
///
/// Всё это заводится разом и разом же снимается: живой перехват показа кадра без
/// того, что он рисует, — это переход в наш модуль из кода игры в никуда.
class UiLayer {
public:
    /// Поднимает интерфейс. Окно игры нужно, чтобы знать размер кадра.
    [[nodiscard]] static std::unique_ptr<UiLayer> create(UiFeed& feed, std::string& error);

    ~UiLayer();

    UiLayer(const UiLayer&) = delete;
    UiLayer& operator=(const UiLayer&) = delete;

    /// Отдаёт странице новое состояние и подгоняет её под размер кадра.
    ///
    /// Вызывать из потока, который не жаль задержать: страница обновляется
    /// двадцать раз в секунду, и чаще ей нечего показывать.
    void pump();

    /// Хозяйство слоя.
    ///
    /// Объявлено, но не раскрыто: определение живёт в исходнике вместе с
    /// Direct3D, WebView2 и половиной Windows, которых здесь быть не должно.
    /// Наружу торчит только имя — им пользуются свободные функции того же
    /// исходника, а больше никто.
    struct State;

private:
    UiLayer() = default;

    std::unique_ptr<State> state_;
};

} // namespace oxymp::client::game
