namespace oxymp::client::game {

/// Игровой интерфейс внутри кадра игры.
///
/// Раньше он был отдельным окном поверх игры, и это работало ровно до тех пор,
/// пока игра оставалась впереди: окно принадлежит рабочему столу, исчезает при
/// сворачивании, спорит с полноэкранным режимом и живёт по чужим правилам.
/// Правильно — как у RAGE MP и alt:V: интерфейс должен быть частью кадра.
///
/// Собирается он из трёх частей, и ни одна не заменяет другую:
///
/// 1. Страница на CEF, нарисованная в память. Окна у неё нет вовсе: готовые
///    точки приходят прямо в обработчик, с настоящей прозрачностью.
/// 2. Перехват показа кадра — единственное место, откуда можно рисовать в кадр
///    игры.
/// 3. Вывод точек на весь кадр поверх всего остального.
///
/// Так же устроен интерфейс у RAGE MP и alt:V, и по той же причине: другой
/// браузерный движок отдаёт страницу только в окно, а окно поверх игры
/// принадлежит рабочему столу и живёт по его правилам.
///
/// Всё это заводится разом и разом же снимается: живой перехват показа кадра без
/// того, что он рисует, — это переход в наш модуль из кода игры в никуда.
///
/// Состояние страница получает своим ходом, из собственного потока слоя, а не по
/// просьбе снаружи. Так было не всегда: раньше её обновлял сетевой цикл, и
/// страница жила ровно столько, сколько шёл он. А сетевой цикл начинается после
/// того, как клиент дождётся таблицы нативов, — то есть спустя минуту с лишним
/// после запуска игры. Всё это время на экране висел экран загрузки, застывший
/// на первой стадии: показывать его было кому, а обновлять — некому.
class UiLayer {
public:
    /// Поднимает интерфейс. Окно игры нужно, чтобы знать размер кадра.
    ///
    /// Направление одно: слой берёт из feed состояние и показывает его. Обратного
    /// пути от страницы к игре нет вовсе, и это не упущение — страница ничем не
    /// распоряжается. Он появится вместе с окнами ресурсов, которым мышь и
    /// нажатия нужны по делу.
    ///
    /// feed обязан пережить слой: читает его собственный поток слоя.
    ///
    /// actions — то, что меню вправе попросить сделать: подключиться,
    /// отключиться, выйти. Больше меню не просит ничего, и это не урезание:
    /// правила игры принадлежат серверу, а не странице.
    [[nodiscard]] static std::unique_ptr<UiLayer> create(UiFeed& feed, Menu::Actions actions,
                                                         std::string& error);

    ~UiLayer();

    UiLayer(const UiLayer&) = delete;
    UiLayer& operator=(const UiLayer&) = delete;

    /// Меню, если оно поднялось.
    ///
    /// Может не подняться, и это не смертельно: экран загрузки, чат и худ живут
    /// на другой странице и работают без него.
    [[nodiscard]] Menu* menu() const noexcept;

    // --- Окна ресурсов --------------------------------------------------------
    //
    // То, чем игровой режим рисует свой интерфейс: обычная веб-страница поверх
    // кадра, с которой ресурс говорит событиями. Ради этого клиентская
    // скриптовая машина и заводилась.
    //
    // Все действия ниже зовутся из игрового потока (там живёт машина), а
    // исполняются в потоке, ведущем страницы: заводить и трогать браузер CEF из
    // кадра игры нельзя — кадр не имеет права ждать чужой процесс. Поэтому они
    // не делают ничего сами, а кладут просьбу в очередь.

    /// Заводит окно по ссылке. Возвращает его номер; ноль — отказ.
    ///
    /// Номер выдаётся сразу, а само окно появляется через кадр-другой. Так
    /// сделано затем, чтобы ресурс мог подписаться на события окна той же
    /// строкой, что и завёл его, — не дожидаясь ничего.
    [[nodiscard]] std::uint32_t createView(std::string url);

    void destroyView(std::uint32_t view);

    /// Отдаёт странице событие: имя и доводы строкой JSON.
    void emitView(std::uint32_t view, std::string name, std::string arguments);

    /// Показывать окно или спрятать.
    void showView(std::uint32_t view, bool visible);

    /// Отдать окну ввод с клавиатуры и мышью или забрать.
    void focusView(std::uint32_t view, bool focused);

    /// Просьба показать указатель мыши.
    ///
    /// Не про окно: просить его может и режим, у которого окна нет вовсе, — у
    /// alt:V `alt.showCursor` объявлен сам по себе. Счётчиком, а не признаком:
    /// два окна просят независимо, и закрытие одного не отнимает указатель у
    /// второго.
    void showCursor(bool show);

    /// Что делать с событием от страницы ресурса.
    ///
    /// Зовётся из потока CEF, поэтому обработчик обязан только переложить
    /// сказанное и уйти.
    using ViewEventHandler = std::function<void(std::uint32_t view, std::string_view name,
                                                std::string_view arguments)>;

    void onViewEvent(ViewEventHandler handler);

    /// Что делать с клавишей, дошедшей до игры.
    ///
    /// Зовётся из потока перехвата ввода, поэтому обработчик обязан только
    /// переложить сказанное и уйти.
    using GameKeyHandler = std::function<void(unsigned key, bool down)>;

    void onGameKey(GameKeyHandler handler);

    /// Хозяйство слоя.
    ///
    /// Объявлено, но не раскрыто: определение живёт в исходнике вместе с
    /// Direct3D, WebView2 и половиной Windows, которых здесь быть не должно.
    /// Наружу торчит только имя — им пользуются свободные функции того же
    /// исходника, а больше никто.
    struct State;

private:
    UiLayer() = default;

    std::unique_ptr<State> state_;
};

} // namespace oxymp::client::game
