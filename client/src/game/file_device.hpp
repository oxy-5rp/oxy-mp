namespace oxymp::client::game {

/// Своё устройство в файловой системе игры.
///
/// Игра читает файлы не с диска, а через свои устройства: путь её вида —
/// `common:/data/…`, `platform:/…`, `update:/…` — разрешается в устройство, а за
/// устройством стоит архив `.rpf` с зашифрованным оглавлением. Повесив на путь
/// своё устройство, мы отдаём игре свои байты вместо тех, что лежат в архиве.
///
/// **Этим снимается тупик со своими машинами.** Работа по ним стояла на подборе
/// схемы шифрования оглавления RPF7: игра не принимает архив с открытым
/// оглавлением, а подобрать её счётом не вышло. Подбирать и не надо — архивы
/// вообще можно не трогать. Так делает alt:V (в его журнале это видно построчно:
/// «Replaced x64/data/control/settings.meta»), и так же делает CitizenFX.
///
/// Таблица методов у устройства чужая: её раскладку задаёт игра, и совпадать она
/// обязана до последней записи. Взята она из `rage::fiDevice` в исходниках
/// CitizenFX и сошлась с тем, что здесь уже было проверено чтением: места
/// `Open`, `Read`, `Close` и `GetFileLengthLong` совпали разряд в разряд с
/// номерами, по которым `FileSystem` читает файлы игры с самого начала.
///
/// Родительского устройства у нас нет, и это отличие от CitizenFX намеренное.
/// Они держат под рукой базовую таблицу игры и пересылают ей то, чего не умеют;
/// мы реализуем все записи сами. Цена — несколько заведомо пустых методов, а
/// выигрыш в том, что не нужен ещё один адрес в чужом коде: базовая таблица
/// ищется своей сигнатурой, и сигнатура эта могла бы не совпасть.
class FileDevice {
public:
    /// Путь и содержимое проверочного файла.
    ///
    /// Проверка живёт при устройстве, а не при том, кто его заводит: спрашивают
    /// её и заполняют её в разных местах и в разное время — файл кладётся при
    /// опознании движка, а сверяется первым кадром игры, — и договориться им
    /// проще всего здесь.
    ///
    /// Путь свой, а не игровой, и это не мелочь: подменять настоящий файл ради
    /// проверки значило бы оставить его подменённым до конца запуска. Своего у
    /// игры нет, и отдать его может только наше устройство — отдало, значит и
    /// таблица методов верна, и монтирование прошло, и чтение работает.
    static constexpr const char* kProbePath = "oxymp:/device-probe.bin";
    static constexpr const char* kProbeContents = "oxymp file device probe";

    /// Заводит устройство. Отказ означает, что адрес монтирования не разрешился.
    [[nodiscard]] static std::unique_ptr<FileDevice> create(const EngineAddresses& addresses,
                                                            std::string& error);

    ~FileDevice();

    FileDevice(const FileDevice&) = delete;
    FileDevice& operator=(const FileDevice&) = delete;

    /// Просит повесить устройство на приставку путей игры.
    ///
    /// Приставка — это корень пространства имён с косой чертой на конце:
    /// `oxymp:/`. Полным путём до файла монтировать не выходит: живая игра
    /// ответила на такую просьбу отказом, и все монтирования, какие делает
    /// CitizenFX, тоже кончаются косой чертой.
    ///
    /// Не монтирует, а откладывает — см. pump. Просить можно откуда угодно и
    /// сколько угодно раз: приставка, уже повешенная, второй раз не вешается.
    void mount(std::string prefix);

    /// Вешает то, о чём просили. **Только из потока с обработчиком скрипта.**
    ///
    /// Требование не из осторожности, а из вылета. Монтирование внутри игры
    /// выделяет память её собственным аллокатором, а аллокатор этот у неё
    /// потоковый: адрес его лежит в локальной памяти потока и заполняется
    /// только у тех потоков, которые завела она сама. В нашем его нет вовсе,
    /// и переходник, который его достаёт, разыменовывает ноль — игра падает
    /// внутри себя, на чтении по нулевому адресу, а не в нашем коде.
    ///
    /// Отсюда и разделение на просьбу и исполнение: просить о подмене будут
    /// ресурсы сервера, приходящие по сети в свой срок и в своём потоке, а
    /// вешать устройство вправе только кадр игры.
    ///
    /// Возвращает, сколько приставок повешено этим вызовом.
    std::size_t pump();

    /// Объявляет, что такой-то путь игры отдаём мы, а байты берём отсюда.
    ///
    /// Само по себе это ничего не подменяет: путь начнёт доходить до нас лишь
    /// тогда, когда его приставка смонтирована. Разделено потому, что приставок
    /// единицы, а файлов под ними бывают тысячи, и вешать устройство на каждый
    /// файл значило бы забить таблицу монтирования игры.
    void serve(const std::string& gamePath, const std::filesystem::path& source);

    /// Отдаёт один и тот же файл на **любой** запрос под этой приставкой.
    ///
    /// Заведено ради описи содержимого карты (`_manifest.ymf`). Разбирает её сама
    /// игра, и путь, по которому она за ней пойдёт, нам неизвестен: он строится
    /// внутри её же кода. Точного соответствия здесь поэтому не хватает — нужно
    /// отвечать на всё, что она спросит под приставкой.
    ///
    /// Так же поступает и CitizenFX: он оборачивает устройство «принудительным»,
    /// которое подменяет имя файла в каждом вызове. Разница лишь в том, что
    /// устройство здесь своё, и заводить обёртку незачем.
    ///
    /// Переставлять можно сколько угодно раз: описей у карты два десятка, и
    /// каждая разбирается своим заходом. Пустой `source` снимает подмену.
    void answerAllWith(const std::string& prefix, const std::filesystem::path& source);

    /// Сколько файлов мы взялись отдавать.
    [[nodiscard]] std::size_t count() const noexcept;

private:
    FileDevice() = default;

    struct Device;

    /// Устройство переживает нас намеренно: игра держит на него ссылку в своей
    /// таблице монтирования до конца процесса, а снять её нечем — обратного
    /// вызова у монтирования нет. Освобождённое, оно оставило бы игре указатель
    /// в никуда, и первое же чтение подменённого пути уронило бы её.
    Device* device_ = nullptr;

    /// rage::fiDevice::MountGlobal — вешает устройство на путь.
    using MountGlobal = bool (*)(const char* mountPoint, void* device, bool allowRoot);

    MountGlobal mount_ = nullptr;

    /// Приставки, на которые устройство уже повешено. Второй раз игра ту же
    /// приставку не примет, и просить её об этом незачем.
    ///
    /// Под той же блокировкой, что и очередь: пишет их кадр игры, а читает
    /// всякий, кто просит о монтировании.
    mutable std::mutex mutex_;
    std::vector<std::string> prefixes_;
    std::vector<std::string> pending_;
};

} // namespace oxymp::client::game
