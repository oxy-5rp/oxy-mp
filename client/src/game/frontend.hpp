#pragma once

#include "native_table.hpp"

#include <cstdint>
#include <optional>

namespace oxymp::client::game {

/// Меню игры поверх мира: страница выбора режима и меню паузы.
///
/// Нужно ровно для одного — знать, что игрок сейчас не в мире, и ничего с ним
/// не делать. Спрашивать вместо этого «играет ли игрок» нельзя: в меню игра уже
/// считает его играющим, хотя персонажа ещё нет либо он не готов. Именно на
/// этом клиент дважды пытался заменить персонажа прямо в меню и оба раза ронял
/// игру.
///
/// Вызывать можно только изнутри скриптового тика.
/// Меню игры и то, что оно с ней делает.
///
/// Остановить остановку мира отсюда нельзя, и это выяснено, а не предположено.
/// Паузы в GTA две: «от скрипта», которую ставит и снимает натив, и «от
/// игрока», которую ставит меню. Мир останавливает вторая, и снятие первой на
/// неё не влияет — проверено на живой игре, мир стоял.
///
/// Дело не в моменте вызова. Скриптовый тик, откуда работает клиент, идёт в
/// своей фазе кадра, а меню обновляется позже и в той же фазе перекрывает любую
/// нашу отмену. Проверено и это: снятие переносилось в конец кадра, ничего не
/// изменилось.
///
/// Остаётся править саму игру — не давать ей принимать решение, как это сделано
/// со страницей выбора режима. Но участок там обфусцирован: обработчик натива
/// уходит переходником в код с вычисляемыми переходами через стек, и признак за
/// один шаг не виден. Поэтому пауза относится к работе над сетевой сессией, а
/// не к мелким правкам: в настоящей сетевой игре меню мир не останавливает
/// вовсе.
class Frontend {
public:
    explicit Frontend(const NativeTable& table) noexcept;

    [[nodiscard]] bool ready() const noexcept;

    /// Показано ли меню прямо сейчас.
    ///
    /// Признак составной: загрузочный экран уже ушёл, а меню ещё на экране.
    [[nodiscard]] bool showing() const;

    /// Чем закончилось открытие меню паузы.
    ///
    /// Отвечает числом сразу на два вопроса, которые иначе неотличимы друг от
    /// друга: идёт ли наш тик при открытом меню и стоит ли при этом мир.
    ///
    /// Различать их обязательно. Пока пауза не снимается, причин ровно две, и
    /// починки у них разные: либо наш тик останавливается вместе с миром — и
    /// снимать паузу попросту некому, — либо тик идёт, а мир всё равно стоит, и
    /// значит меню останавливает его не тем способом, который мы отменяем.
    ///
    /// Игровое время выбрано мерилом мира потому, что идёт ровно пока мир
    /// живёт, и останавливается вместе с ним.
    struct PauseMeasurement {
        /// Сколько раз наш тик отработал, пока меню было открыто. Ноль означает,
        /// что тик стоял.
        std::int32_t frames = 0;

        /// На сколько миллисекунд продвинулось игровое время за это же время.
        /// Около нуля при работающем тике означает, что мир стоял.
        std::int32_t gameTime = 0;

        /// Доходил ли до нас тик, пока меню было открыто.
        [[nodiscard]] bool tickRan() const noexcept { return frames > 0; }

        /// Стоял ли мир. Осмысленно только когда тик доходил.
        [[nodiscard]] bool worldFroze() const noexcept { return gameTime <= 0; }
    };

    /// Ведёт замер открытия меню. Вызывать раз в кадр.
    ///
    /// Отдаёт результат ровно один раз — на кадре, когда меню закрылось. Пока
    /// оно открыто или пока его нет, отдавать нечего.
    [[nodiscard]] std::optional<PauseMeasurement> measurePause();

private:
    NativeHandler loadingScreenActive_ = nullptr;
    NativeHandler pauseMenuActive_ = nullptr;
    NativeHandler gameTimer_ = nullptr;

    /// Было ли меню открыто на прошлом кадре.
    bool wasShowing_ = false;

    /// Игровое время на кадре, когда меню открылось.
    std::int32_t openedAtGameTime_ = 0;

    /// Сколько наших кадров прошло с тех пор.
    std::int32_t framesWhileShowing_ = 0;
};

} // namespace oxymp::client::game
