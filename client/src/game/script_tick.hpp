#pragma once

#include "engine_addresses.hpp"
#include "hook.hpp"

#include <cstdint>
#include <memory>
#include <string>

namespace oxymp::client::game {

/// Управление каждый кадр внутри скриптового контекста игры.
///
/// Перехватывает штатный тик скриптового потока. Выбор именно этой точки
/// принципиален: рисование и работа с сущностями требуют не просто главного
/// потока, а действующего скриптового контекста — нативы читают активный поток
/// из TLS. Внутри тика игра его уже выставила, поэтому нам не нужно ни
/// подделывать структуру потока, ни регистрировать её в коллекции игры. Ошибка
/// в такой подделке стоила бы вылета, а здесь подделывать нечего.
///
/// Тик вызывается для каждого скриптового потока, то есть многократно за кадр.
/// Обработчик же должен отработать один раз за кадр, поэтому кадры считаются по
/// счётчику самой игры.
///
/// Потоки при этом неравноценны, и это важно. У части из них есть обработчик
/// скрипта — то, на чей счёт игра записывает заказанную модель или завершённый
/// скрипт. Нативы достают его из активного потока и разыменовывают не проверяя,
/// поэтому от потока без обработчика доступна лишь часть работы. Ждать же
/// подходящий поток всегда нельзя: на загрузке их вовсе нет, а рисовать нужно
/// именно тогда. Поэтому обработчику сообщается, с чем он имеет дело.
class ScriptTick {
public:
    /// Что выполнять раз в кадр.
    ///
    /// Довод говорит, есть ли у потока, от чьего имени мы выполняемся,
    /// обработчик скрипта. Без него нельзя ни заказывать модели, ни завершать
    /// чужие скрипты — только то, чему скриптовое хозяйство безразлично.
    using Callback = void (*)(bool ownsResources);

    /// Ставит перехват. Механизм перехвата должен быть подготовлен заранее.
    [[nodiscard]] static std::unique_ptr<ScriptTick> install(const EngineAddresses& addresses,
                                                             Callback callback,
                                                             std::string& error);

    ~ScriptTick();

    ScriptTick(const ScriptTick&) = delete;
    ScriptTick& operator=(const ScriptTick&) = delete;

    /// Сколько кадров обработчик отработал.
    [[nodiscard]] std::uint64_t frames() const noexcept;

    /// Сколько раз игра вызывала тик. Заметно больше числа кадров: потоков много.
    [[nodiscard]] std::uint64_t ticks() const noexcept;

    /// Номер потока игры, из которого приходит тик. Ноль, пока он не приходил.
    ///
    /// Наружу — ради отладочных регистров: они принадлежат потоку, а не
    /// процессу, и ставить их надо тому потоку, который работает с игрой. Узнать
    /// его иначе как изнутри тика неоткуда: игра своих потоков не объявляет.
    [[nodiscard]] static std::uint32_t gameThreadId() noexcept;

private:
    ScriptTick() = default;

    Hook hook_;
};

} // namespace oxymp::client::game
