#pragma once

#include "native_table.hpp"

#include <cstdint>

namespace oxymp::client::game {

/// Посадка местного игрока в машину.
///
/// Одна беда и одно правило. В одиночной игре занятое место означает «выдерни
/// того, кто там сидит»: игра поднимает водителя за шиворот, выбрасывает на
/// асфальт и садится сама. Так задумано, и в сюжете это верно — там за рулём
/// прохожий, которого игра же и придумала.
///
/// В сессии за рулём человек. Выдернуть его нельзя, и не потому, что невежливо,
/// а потому, что не получится: его персонаж у нас — кукла, а сам он у себя
/// продолжает сидеть и ехать. Наружу это выходит худшим из возможных способов:
/// у выдернувшего чужой водитель валяется на дороге, у выдернутого — ничего не
/// произошло, и оба видят разное.
///
/// Поэтому занятое место здесь означает «сядь на другое». Тем же правилом
/// живут RAGE MP и alt:V, и другого разумного нет: отказать в посадке совсем
/// значит запереть пассажиров снаружи собственной машины.
///
/// Правило это не игровое, и голого клиента оно не нарушает: игрок ничего им не
/// вызывает и ничего не получает сверх того, что и так может. Оно убирает у
/// игры поведение, которое в сессии заведомо ложно, — как это делает и снятие
/// паузы при потере фокуса.
///
/// Вызывать можно только изнутри скриптового тика.
class VehicleEntry {
public:
    explicit VehicleEntry(const NativeTable& table) noexcept;

    [[nodiscard]] bool ready() const noexcept;

    /// Разбирается с начатой посадкой. Зовётся раз в кадр.
    void sync(int ped);

private:
    /// Свободное место, ближайшее к тому, куда игрок метил.
    ///
    /// Возвращает kNoFreeSeat, если свободных нет вовсе.
    [[nodiscard]] int freeSeat(int vehicle, int wanted) const;

    NativeHandler gettingIn_ = nullptr;
    NativeHandler vehicleEntering_ = nullptr;
    NativeHandler seatEntering_ = nullptr;
    NativeHandler seatFree_ = nullptr;
    NativeHandler maxPassengers_ = nullptr;
    NativeHandler enterVehicle_ = nullptr;
    NativeHandler clearTasks_ = nullptr;
    NativeHandler gameTimer_ = nullptr;

    /// Куда мы уже пересадили игрока, чтобы не пересаживать его каждый кадр.
    ///
    /// Пересадка снимает задачи и выдаёт новую; сделанная заново в следующем же
    /// кадре, она не даёт задаче начаться вовсе, и персонаж топчется у двери,
    /// пока игрок не отпустит клавишу.
    int redirectedVehicle_ = 0;
    int redirectedSeat_ = 0;

    /// Когда пересадили в последний раз.
    ///
    /// Нужно на случай, когда место, на которое мы пересадили, тоже заняли —
    /// пока игрок шёл вокруг машины, туда сел кто-то ещё. Без срока пересадка
    /// не повторилась бы никогда, и игрок остался бы дёргать занятую дверь.
    std::int32_t redirectedAt_ = 0;
};

} // namespace oxymp::client::game
