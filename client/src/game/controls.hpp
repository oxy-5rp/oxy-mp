#pragma once

#include "native_table.hpp"

namespace oxymp::client::game {

/// Ввод игрока и то, что игра позволяет им делать.
///
/// Одиночная игра оставляет игроку возможности, которых в мультиплеере быть не
/// должно: ввод читкодов по клавише слева от единицы меняет мир только на этом
/// компьютере, и остальные игроки увидят что-то своё.
///
/// Вызывать можно только изнутри скриптового тика.
class Controls {
public:
    explicit Controls(const NativeTable& table) noexcept;

    [[nodiscard]] bool ready() const noexcept;

    /// Запрещает ввод читкодов. Вызывать каждый кадр.
    ///
    /// Каждый кадр, потому что запрет действует ровно один кадр: так устроены
    /// все запреты ввода в игре — их выставляют те, кому они нужны, и снимать
    /// их обратно не приходится.
    void suppressCheats() const;

    /// Запрещает колесо выбора персонажа. Вызывать каждый кадр.
    ///
    /// Колесо это — сюжетная возможность: по нему игра переключает Майкла,
    /// Франклина и Тревора. В мультиплеере переключать некого, а вреда от него
    /// два. Первый: пока колесо открыто, игра замедляет ход времени вдвое, и
    /// остальные игроки видят нас двигающимся рывками. Второй: сама попытка
    /// переключения тянется в сюжет, который мы гасим.
    void suppressCharacterWheel() const;

    /// Отбирает у игры весь ввод на этот кадр.
    ///
    /// Нужно, пока открыт чат: набранное игроком не должно заодно вести машину
    /// и стрелять. Перехват клавиатуры у нас свой, и игра о нём не знает —
    /// узнать она может только так.
    void suppressEverything() const;


private:
    NativeHandler disableAction_ = nullptr;
    NativeHandler disableAll_ = nullptr;
};

} // namespace oxymp::client::game
