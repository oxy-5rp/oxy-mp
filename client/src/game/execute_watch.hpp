#pragma once

#include <cstdint>
#include <memory>
#include <string>

namespace oxymp::client::game {

/// Ловушка на исполнение одной инструкции игры.
///
/// Отвечает на вопрос «кто её выполнил». Взять этот ответ больше неоткуда:
/// инструкция известна, а вызывающий — нет, и без него непонятно, по какой
/// причине игра делает то, что делает.
///
/// Отвечать на такие вопросы подменой кода уже пробовали, и дважды это вышло
/// дорого: подпись чужой функции — предположение, и неверное предположение
/// оборачивается вылетом или тринадцатью минутами сломанного мира. Здесь
/// подмены нет вовсе.
///
/// Ловушка ставится средствами процессора: адрес кладётся в отладочный регистр,
/// и при попытке его исполнить процессор поднимает исключение — до того, как
/// инструкция отработает. Мы записываем, откуда пришли, и отпускаем игру
/// дальше. Ни один её байт при этом не изменён.
///
/// Отладочные регистры принадлежат потоку, а не процессу: ловушка ставится на
/// тот поток, который эту инструкцию выполняет.
///
/// Сама себя снимает после нескольких срабатываний: нужен один ответ, а не
/// поток одинаковых, и исключение на каждое исполнение стоит дорого.
class ExecuteWatch {
public:
    /// Ставит ловушку на адрес в указанном потоке.
    [[nodiscard]] static std::unique_ptr<ExecuteWatch> install(void* address,
                                                               std::uint32_t threadId,
                                                               std::string label,
                                                               std::string& error);

    ~ExecuteWatch();

    ExecuteWatch(const ExecuteWatch&) = delete;
    ExecuteWatch& operator=(const ExecuteWatch&) = delete;

private:
    ExecuteWatch() = default;
};

} // namespace oxymp::client::game
