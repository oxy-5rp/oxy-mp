#pragma once

#include "native_table.hpp"

#include <cstddef>
#include <mutex>
#include <string>
#include <unordered_set>
#include <vector>

namespace oxymp::client::game {

/// Расстановка чужой карты: просьба игре её поставить.
///
/// **Последний шаг, и без него всё предыдущее не видно.** Модели объявлены
/// стримингу, архетипы загружены видом `DLC_ITYP_REQUEST`, опись содержимого
/// разобрана — но расстановка (`.ymap`) так и лежит зарегистрированным файлом.
/// Игра знает, что такой файл есть; она не знает, что его надо применить.
///
/// Просьба эта у неё родная — `REQUEST_IPL`. Тем же нативом расстановку грузят
/// в одиночной игре все, кто ставит карты руками; ничего изобретать не нужно.
///
/// Имя — без расширения и без пути: игра зовёт расстановку так же, как всё
/// прочее подгружаемое, — коротким именем.
///
/// Отдельным классом, а не строкой в сессии, потому что просить нужно из кадра
/// игры, а список приходит из сети: то же разделение, что у устройства, у
/// стриминга и у описаний.
class MapPlacements {
public:
    explicit MapPlacements(const NativeTable& table) noexcept;

    /// Готовы ли натив расстановки и натив проверки.
    [[nodiscard]] bool ready() const noexcept;

    /// Просит поставить расстановку с таким именем. Звать можно откуда угодно.
    ///
    /// Повторы отбрасываются: у карты, склеенной из двух десятков ресурсов, одно
    /// и то же имя встречается не раз, а просить игру дважды об одном незачем.
    void add(std::string name);

    /// Просит игру о том, что накопилось. **Только из потока с обработчиком
    /// скрипта.**
    ///
    /// Возвращает, сколько расстановок принято игрой — то есть сколько из них
    /// она после просьбы считает действующими. Это не то же, что «сколько
    /// попросили»: имя, которого игра не знает, она молча пропустит, и
    /// единственный способ отличить одно от другого — спросить её саму.
    std::size_t pump();

private:
    /// `REQUEST_IPL` — просьба поставить расстановку.
    NativeHandler request_ = nullptr;

    /// `IS_IPL_ACTIVE` — проверка, встала ли она.
    NativeHandler active_ = nullptr;

    /// Что просили поставить и о чём уже просили.
    std::vector<std::string> pending_;
    std::unordered_set<std::string> asked_;

    std::mutex mutex_;
};

} // namespace oxymp::client::game
