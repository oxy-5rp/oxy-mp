#pragma once

#include "engine_addresses.hpp"
#include "native_table.hpp"

#include <chrono>

#include <cstdint>

namespace oxymp::client::game {

/// Поднятие настоящей сетевой сессии силами самой игры.
///
/// То, чем RAGE MP, alt:V и FiveM добиваются сетевого поведения, и то, ради чего
/// затевалась вся разведка.
///
/// Разница с подделкой признака принципиальная, а не в степени. Подделка
/// выставляла признак снаружи — и игра падала, потому что за признаком должны
/// стоять объекты сессии, а их не было. Здесь признак выставляет сама игра, и
/// объекты она заводит сама же, своим обычным порядком. Мы только просим начать.
///
/// Это по-прежнему разведка. Функция вызывается вслепую: соглашение снято с
/// чужого разбора других сборок, а что игра сделает, не имея за спиной живого
/// слоя Rockstar Online, заранее не известно. Возможных исходов три, и все
/// полезны: сессия поднимется, игра откажется, игра повиснет или упадёт. Поэтому
/// включается ключом и по умолчанию выключено.
///
/// Вызывать можно только из игрового потока: поднятие сессии — это работа с
/// хозяйством игры, а не чтение памяти.
class NetSession {
public:
    /// Каким способом поднимать сессию.
    enum class Mode {
        /// Нативом «поднять сессию на одного».
        ///
        /// Ему не нужен ни подбор игроков, ни серверы Rockstar — а признак
        /// сетевой игры игра выставляет настоящий. Первый кандидат на то, чтобы
        /// сессия пережила первую секунду.
        Solo,

        /// Внутренней функцией игры, минуя нативы.
        ///
        /// Тот путь, которым идёт CitizenFX. Сессию поднимает, но через 286 мс
        /// игра сворачивает её сама.
        Raw,
    };

    NetSession(const EngineAddresses& addresses, const NativeTable& table) noexcept;

    /// Нашлось ли всё нужное, чтобы вообще пробовать.
    [[nodiscard]] bool ready() const noexcept;

    /// Просит игру поднять свою сессию. Возвращает ложь, если просить нечем.
    ///
    /// Просьба одна на запуск: повторная при уже поднятой сессии — это не
    /// повторная попытка, а другое действие с неизвестными последствиями.
    bool host(Mode mode);

    /// Поднимает сессию заново, если игра её свернула. Вызывать раз в кадр.
    ///
    /// «Свернула» и «ещё поднимает» — разные вещи, и различать их обязательно.
    /// Раньше здесь этой разницы не было: признак «сессии нет» считался
    /// признаком того, что игра её уронила, — и пока сессия поднималась свои
    /// шестьсот миллисекунд, мы просили поднять её ещё сорок раз. Игра этого не
    /// пережила: вызов поднятия, пришедший в уже поднимающуюся сессию, ломает её
    /// машину состояний. Крах случался ровно в тот миг, когда сессия наконец
    /// вставала.
    ///
    /// Теперь после просьбы даётся время. Пока оно идёт, сессии просто нет — и
    /// это нормально. Заново просят только если она успела встать и упасть либо
    /// если время вышло, а её так и нет.
    void rehostIfDropped(Mode mode, bool sessionStarted);

    /// Сколько раз поднимали.
    [[nodiscard]] std::uint32_t attempts() const noexcept { return attempts_; }

    /// Просили ли мы уже.
    [[nodiscard]] bool asked() const noexcept { return asked_; }

    /// Отказались ли мы от сессии совсем.
    ///
    /// Спрашивает удержание в сессии: держать имеет смысл ровно до тех пор, пока
    /// есть что держать. Сессия поднялась и легла, попытки кончились — держать
    /// больше нечего, и каждый следующий кадр удержание только запирает дверь,
    /// за которой уже никого нет. Чего это стоит, сказано у NetworkBail::hold.
    [[nodiscard]] bool gaveUp() const noexcept { return gaveUpReported_; }

    /// Числимся ли мы хозяином сессии. Признак того, что поднятие удалось.
    [[nodiscard]] bool isHost() const;

    /// Есть ли распорядитель сети. Пока его нет, сессии не будет ни при каких
    /// обстоятельствах, и это стоит знать до того, как звать поднятие.
    [[nodiscard]] bool managerReady() const;

private:
    /// Поднятие сессии: видимость, предел игроков, признаки.
    ///
    /// Соглашение снято с чужого разбора: три целых довода, ничего не
    /// возвращает. Проверить его иначе как вызовом нельзя, и в этом весь риск.
    using HostFunction = void (*)(int visibility, int maxPlayers, int flags);

    using IsHostFunction = bool (*)();

    HostFunction host_ = nullptr;
    IsHostFunction isHost_ = nullptr;

    NativeHandler hostSolo_ = nullptr;
    NativeHandler leaveSolo_ = nullptr;

    /// Указатель на указатель: сам распорядитель появляется позже переменной.
    void* const* manager_ = nullptr;

    bool asked_ = false;

    /// Когда просили в последний раз, по монотонным часам.
    std::chrono::steady_clock::time_point askedAt_{};

    /// Вставала ли сессия хоть раз. Пока не вставала, её отсутствие означает
    /// «ещё поднимается», а не «упала».
    bool everStarted_ = false;

    /// Сказали ли уже, что сессию удержать не вышло.
    bool gaveUpReported_ = false;

    /// Сколько раз просили поднять. Растёт при каждой попытке.
    std::uint32_t attempts_ = 0;
};

} // namespace oxymp::client::game
