#pragma once

#include <memory>
#include <string>

namespace oxymp::client::game {

/// Затыкает показ игры в Discord, оставляя наш.
///
/// Social Club, загруженная в процесс игры, объявляет в Discord своё: «играет в
/// GTA V». Для нашего игрока это неправда — он в сессии oxyMP, — и два показа
/// спорят между собой: человек видит то одно, то другое.
///
/// Довод `-scDiscordClientId` у неё уже отбирается лаунчером
/// (`launcher-patcher/src/battleye_link.cpp`), но этого мало: без номера приложения она
/// берёт свой, зашитый, и показ всё равно появляется.
///
/// Поэтому дверь закрывается ниже: Discord слушает именованный канал
/// `\\.\pipe\discord-ipc-N`, и другого пути к нему нет ни у кого. Открытие
/// такого канала перехватывается, и всякому, кроме нас, отвечается отказом.
/// Отказ этот для Social Club — обычное дело: он же приходит всякому, у кого
/// Discord просто не запущен.
///
/// «Кроме нас» решается не догадкой, а меткой: наш собственный показ ставит на
/// время вызова признак своего потока. Разбирать, кто позвал, по обратному
/// адресу было бы гаданием — вызов может прийти и через чужую обёртку.
///
/// Дверей заперто три, и это не перестраховка: заранее не известно, какой из
/// путей выберет именно эта сборка Social Club. Канал открывают двумя вызовами —
/// широким и однобайтовым, — а сам показ ведёт отдельная библиотека
/// `RockstarDiscordHelper.dll`, и ей просто не дают загрузиться. Каждый путь
/// пишет в журнал, что сработал именно он: без этого «показ всё равно виден»
/// означало бы сразу три разные беды.
class DiscordBlock {
public:
    [[nodiscard]] static std::unique_ptr<DiscordBlock> install(std::string& error);

    ~DiscordBlock();

    DiscordBlock(const DiscordBlock&) = delete;
    DiscordBlock& operator=(const DiscordBlock&) = delete;

    /// Метка «этот вызов наш» на время своей жизни.
    ///
    /// Заводится вокруг собственного открытия канала. Признак потоковый:
    /// показ живёт в сетевом потоке, а игра лезет в Discord из своих.
    class Ours {
    public:
        Ours() noexcept;
        ~Ours();

        Ours(const Ours&) = delete;
        Ours& operator=(const Ours&) = delete;
    };

    /// Сколько чужих попыток отклонено. Для журнала: по нулю видно, что игра
    /// ходит в Discord не через канал, и искать надо другое.
    [[nodiscard]] unsigned int refused() const noexcept;

private:
    DiscordBlock() = default;

    struct State;

    /// Единственный перехват на процесс.
    ///
    /// Статическим полем, а не как-нибудь иначе: подменённая CreateFileW —
    /// свободная функция, и Windows зовёт её без всякого нашего состояния.
    static State* active_;

    std::unique_ptr<State> state_;
};

} // namespace oxymp::client::game
