#pragma once

#include "engine_addresses.hpp"

#include <cstdint>

namespace oxymp::client::game {

/// Признак «идёт сетевая игра» — тот, по которому игра отличает сюжет от сети.
///
/// Заведено ради одного вопроса, на который иначе не ответить: сколько сюжетного
/// поведения держится на одном байте.
///
/// Вопрос не праздный. Пауза, останавливающая мир, неполная карта в Esc,
/// сюжетные самолёты, порядок смерти с потерей интерфейса — это не четыре
/// разные неприятности, а одна и та же развилка внутри игры, пройденная не в ту
/// сторону. Гасить их поимённо нативами можно бесконечно и всё равно не до
/// конца: паузу так не снять, это уже проверено и записано в frontend.hpp.
///
/// ВАЖНО: это подделка, а не сетевая сессия.
///
/// Настоящая игра выставляет признак сама, и вместе с ним у неё появляются
/// объекты сессии — список игроков, распорядитель сущностей, время. Мы
/// выставляем только признак. Значит любая ветка игры, которая, увидев его,
/// полезет к этим объектам, получит пустоту, и это будет вылет.
///
/// Поэтому:
///
/// * подделка выключается переменной окружения без пересборки — чтобы вылет на
///   старте не оставил игру незапускаемой;
/// * включается не раньше, чем игрок оказался в мире: на загрузке игра
///   распоряжается сессией сама, и вмешательство там — самый верный способ
///   упасть;
/// * каждая запись проверяется чтением: признак живёт в данных, а не в коде, и
///   молча не записаться он может только если страница защищена от записи —
///   лучше узнать об этом сразу, чем гадать, почему ничего не изменилось.
///
/// Признаков два. Один отвечает про установившуюся сетевую игру, другой
/// выставляется раньше и включает промежуточное «подключаемся». Заранее не
/// известно, от какого из них зависит нужное поведение, поэтому держатся оба, и
/// каждым можно распорядиться отдельно.
///
/// Читать можно откуда угодно, это обычная память. Держать признак положено из
/// скриптового тика, раз в кадр: игра вправе переписать его в любой момент.
class NetworkGame {
public:
    /// Какой признак имеется в виду.
    enum class Flag {
        /// Установившаяся сетевая игра.
        Established,

        /// Сетевая игра вместе с промежуточным «подключаемся».
        Connecting,
    };

    /// Что именно подделывать.
    ///
    /// Признаки разделены не для полноты, а потому что порознь они ведут себя
    /// по-разному, и мешать их в одну кучу значит не узнать, который из них что
    /// сделал. Установившаяся игра — признак поведения: от неё ветвятся пауза,
    /// карта, население. Промежуточное «подключаемся» ближе к самой машине
    /// состояний сессии, и с него спрос строже.
    enum class Fake {
        /// Не подделывать вовсе.
        None,

        /// Только признак установившейся сетевой игры.
        Established,

        /// Оба признака.
        Both,
    };

    explicit NetworkGame(const EngineAddresses& addresses) noexcept;

    /// Нашёлся ли признак. Разведочные сигнатуры необязательны, и на этой
    /// сборке игры их может не оказаться вовсе.
    [[nodiscard]] bool available(Flag flag) const noexcept;

    /// Есть ли хоть один признак, с которым можно работать.
    [[nodiscard]] bool ready() const noexcept;

    /// Что в признаке лежит прямо сейчас.
    [[nodiscard]] bool value(Flag flag) const noexcept;

    /// Где признак лежит. Пусто, если его не нашли.
    ///
    /// Наружу — чтобы за ним можно было поставить дозор: журнал значений говорит,
    /// когда признак изменился, но не говорит, кто его изменил.
    [[nodiscard]] const void* addressOf(Flag flag) const noexcept;

    /// Начинает держать выставленными указанные признаки.
    ///
    /// Само по себе ничего не пишет: запись идёт в hold, раз в кадр. Здесь
    /// только запоминается, что игра думала до нас, — чтобы было что вернуть.
    void beginHolding(Fake what) noexcept;

    /// Перестаёт держать и возвращает признакам прежние значения.
    void endHolding();

    [[nodiscard]] bool holding() const noexcept { return holding_; }

    /// Держит признаки выставленными. Вызывать раз в кадр.
    ///
    /// Раз в кадр, а не однажды: признак принадлежит игре, и она переписывает
    /// его на своих переходах между состояниями.
    void hold();

    /// Записывает в журнал каждое изменение признаков.
    ///
    /// Вызывать раз в кадр. Пишет только переходы: тридцать одинаковых строк в
    /// секунду не рассказывают ничего, а вот мгновение, когда игра сама
    /// выставила признак, — рассказывает всё.
    void reportChanges();

private:
    /// Один признак и всё, что мы о нём знаем.
    struct Byte {
        /// Где лежит. Пусто, если сигнатура не разрешилась.
        volatile std::uint8_t* address = nullptr;

        /// Что игра держала в нём до того, как мы начали вмешиваться.
        std::uint8_t original = 0;

        /// Записано ли уже прежнее значение. Отдельным полем, потому что нулевое
        /// прежнее значение — обычное дело и признаком «не записано» быть не может.
        bool originalKnown = false;

        /// Держим ли мы этот признак выставленным.
        bool held = false;

        /// Что мы видели в прошлый раз, когда сверяли изменения.
        std::uint8_t lastSeen = 0;
        bool lastSeenKnown = false;

        /// Отказала ли запись. Однажды отказав, больше не пробуем: если байт
        /// не пишется, он не станет писаться через кадр.
        bool writeFailed = false;
    };

    [[nodiscard]] Byte& byteFor(Flag flag) noexcept;
    [[nodiscard]] const Byte& byteFor(Flag flag) const noexcept;

    /// Записывает значение и тут же читает обратно. Ложь означает, что запись
    /// не удержалась, — тогда признак дальше не трогается.
    bool write(Byte& byte, std::uint8_t value, Flag flag);

    Byte established_;
    Byte connecting_;

    bool holding_ = false;
};

/// Имя признака для журнала.
[[nodiscard]] const char* describe(NetworkGame::Flag flag) noexcept;

} // namespace oxymp::client::game
