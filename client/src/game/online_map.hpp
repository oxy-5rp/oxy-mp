#pragma once

#include "native_table.hpp"

namespace oxymp::client::game {

/// Переключение мира на карту сетевого режима.
///
/// Карта у GTA V не одна. В одиночной игре часть мест попросту отсутствует —
/// казино, ночные клубы, склады и прочее, что Rockstar добавляла обновлениями
/// только для GTA Online. Мультиплееру нужна именно она: игроки ждут ту карту,
/// которую видели в Online.
///
/// Переключение делается нативом самой игры, а не подменой файлов: игра умеет
/// перезаряжать разметку мира и делает это сама при входе в сетевой режим. Тем
/// же способом пользуются RAGE MP и alt:V.
///
/// Побочное следствие оказывается кстати: сюжетные скрипты рассчитаны на
/// одиночную карту и на сетевой перестают находить то, за что цепляются.
///
/// Вызывать можно только изнутри скриптового тика и только от потока с
/// обработчиком скрипта: перезарядка разметки мира — как раз то, что игра
/// записывает на счёт вызвавшего.
class OnlineMap {
public:
    explicit OnlineMap(const NativeTable& table) noexcept;

    [[nodiscard]] bool ready() const noexcept;

    /// Считает ли игра, что идёт сетевая сессия.
    [[nodiscard]] bool active() const;

    /// Переключает мир на сетевую карту. Достаточно одного раза за запуск.
    void enable() const;

private:
    NativeHandler onEnterMp_ = nullptr;
    NativeHandler gameInProgress_ = nullptr;
};

} // namespace oxymp::client::game
