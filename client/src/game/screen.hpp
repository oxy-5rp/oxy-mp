#pragma once

#include "native_table.hpp"

namespace oxymp::client::game {

/// Загрузочный экран и затемнение.
///
/// Обычно ими распоряжаются стартовые скрипты игры: они же убирают заставку и
/// проявляют картинку, а заодно затемняют экран при загрузке и после смерти.
/// Всё это мультиплееру мешает, поэтому распоряжаемся ими мы.
///
/// Вызывать можно только изнутри скриптового тика.
class Screen {
public:
    explicit Screen(const NativeTable& table) noexcept;

    [[nodiscard]] bool ready() const noexcept;

    /// Убирает загрузочный экран игры.
    ///
    /// Вызывать можно сколько угодно раз: повторный вызов игра пропускает. Это
    /// важно, потому что заставка поднимается не мгновенно и одного вызова на
    /// старте не хватает.
    void hideLoadingScreen() const;

    /// Проявляет картинку из черноты за указанное время.
    void fadeIn(int milliseconds) const;

    /// Затемняет картинку за указанное время.
    void fadeOut(int milliseconds) const;

    /// Запрещает игре проявлять картинку самой.
    ///
    /// Нужно ровно потому, что моментом появления игрока распоряжаемся мы:
    /// проявленная игрой картинка показала бы недогруженный мир и чужого
    /// персонажа до того, как мы успеем заменить одно и перенести другое.
    void takeOverFades() const;

    /// Обрывает переход игры между персонажами, если он идёт.
    ///
    /// Это тот самый вид города сверху с плывущими облаками, которым игра
    /// показывает смену персонажа и вход в GTA Online. Он же вставал после
    /// пропущенного вызова выхода из сессии и не кончался ничем — ни снятием
    /// скриптовых камер, ни проявлением, ни `SHUTDOWN_LOADING_SCREEN`.
    ///
    /// Не кончался потому, что искали не то: у перехода своё имя и свои вопросы,
    /// а `GET_RENDERING_CAM` про него не знает ничего и не должен.
    ///
    /// Обрыв оставляет экран чёрным — сам переход кончается проявлением, а
    /// `STOP_PLAYER_SWITCH` только обрывает, — поэтому проявление здесь же.
    ///
    /// Отвечает, шёл ли переход: вызывающему это нужно ради одной строки в
    /// журнал, а не ради решения.
    [[nodiscard]] bool endPlayerSwitch() const;

    /// Держит игровой интерфейс и карту на месте. Вызывать каждый кадр.
    ///
    /// Игра убирает их на смерти и не возвращает: возвращать их положено тому
    /// порядку разбора смерти, который мы у неё отобрали. Без этого игрок встаёт
    /// без радара и не может открыть карту.
    ///
    /// Три разных вмешательства, и все три обязательны.
    ///
    /// Первое — сам показ интерфейса и радара: их игра гасит на смерти.
    ///
    /// Второе — разрешение показывать интерфейс, пока игрок числится мёртвым.
    /// Без него первые три секунды после смерти экран пуст, что бы мы ни
    /// включали: игра просто не рисует интерфейс мертвецу.
    ///
    /// Третье — открытая карта. В одиночной игре часть её закрыта: игра
    /// открывает её по мере того, как игрок туда доезжает, и на смерти
    /// возвращает закрытой. В сети закрытой карты не бывает — там все места
    /// известны всем с самого начала.
    void keepInterfaceUp() const;


private:
    NativeHandler shutdownLoading_ = nullptr;
    NativeHandler fadeIn_ = nullptr;
    NativeHandler fadeOut_ = nullptr;
    NativeHandler fadeInAfterLoad_ = nullptr;
    NativeHandler fadeInAfterDeath_ = nullptr;
    NativeHandler displayHud_ = nullptr;
    NativeHandler displayRadar_ = nullptr;
    NativeHandler revealMap_ = nullptr;
    NativeHandler hudWhenDead_ = nullptr;
    NativeHandler switchInProgress_ = nullptr;
    NativeHandler stopSwitch_ = nullptr;
};

} // namespace oxymp::client::game
