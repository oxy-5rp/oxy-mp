#pragma once

#include "native_table.hpp"

#include <oxymp/shared/protocol/messages.hpp>

#include <unordered_map>

namespace oxymp::client::game {

/// Маркеры: фигуры, нарисованные сервером в мире.
///
/// Игра их у себя не помнит вовсе, и в этом всё отличие от меток и контрольных
/// точек. Маркер — это не заведённая сущность, а вызов отрисовки: попросил
/// нарисовать в этом кадре — нарисовалось; не попросил — фигуры нет. Отсюда и
/// устройство: словарь состояний и обход по нему каждый кадр.
///
/// Отсюда же и то, чего маркер умеет, а прочие нет: качаться, вертеться и
/// поворачиваться к камере. Всё это игра делает не с фигурой, а с одним её
/// кадром, и помнить ей для этого нечего.
///
/// Вызывать можно только изнутри скриптового тика.
class Markers {
public:
    explicit Markers(const NativeTable& table) noexcept;

    [[nodiscard]] bool ready() const noexcept;

    /// Заводит маркер или поправляет уже заведённый.
    void apply(const shared::MarkerState& state);

    void remove(shared::MarkerId id);

    /// Убирает все разом. Нужно при разрыве: фигуры прежнего сервера в мире
    /// следующего — мусор.
    void clear();

    /// Рисует всё, что видно с этого места. Зовётся раз в кадр.
    ///
    /// Видно ли — решаем здесь, а не на сервере, и это решение. Отбирай маркеры
    /// сервер по расстоянию, каждый шаг игрока через границу видимости стоил бы
    /// сообщения «заведи» или «убери»; маркер же весит полсотни байт, и раздать
    /// их все разом дешевле, чем ходить туда-сюда.
    void draw(const shared::Vec3& viewer) const;

private:
    NativeHandler drawMarker_ = nullptr;

    std::unordered_map<shared::MarkerId, shared::MarkerState> markers_;
};

} // namespace oxymp::client::game
