#pragma once

namespace oxymp::cefui {
class Browser;
}

namespace oxymp::client::game {

/// Мышь, доведённая до страницы интерфейса.
///
/// Своей мыши у страницы нет и быть не может: окна у неё нет вовсе, а мышь
/// принадлежит окну. Всё, что она знает об указателе, приходит отсюда — из
/// положения системного курсора над окном игры, пересчитанного в точки
/// страницы.
///
/// Курсор при этом рисует сама страница. Системный над игрой не показать: игра
/// прячет его, а нарисованный поверх кадра курсор — это уже не курсор, а картинка
/// в кадре, и рисовать её умеет только та, что рисует всё остальное.
///
/// Ведётся указатель не всегда, а пока он нужен, — то есть пока открыто меню.
/// В остальное время мышь принадлежит игре: ею водят камерой, и подсматривать за
/// ней незачем.
class Pointer {
public:
    /// Доводит до страницы положение указателя и нажатия кнопок.
    ///
    /// Размер страницы нужен потому, что она может быть мельче кадра: кадр
    /// бывает и в 4K, а страница дальше 1920 точек не растёт.
    void follow(cefui::Browser& page, int pageWidth, int pageHeight);

    /// Уводит указатель со страницы и отпускает всё нажатое.
    ///
    /// Вызывается, когда меню закрылось: оставленная нажатой кнопка означала бы
    /// для страницы вечное перетаскивание, а оставленный указатель — вечно
    /// подсвеченный пункт под ним.
    void release(cefui::Browser& page);

private:
    /// Где указатель был в прошлый раз. Отрицательное — не был нигде.
    int x_ = -1;
    int y_ = -1;

    bool leftDown_ = false;
    bool rightDown_ = false;

    /// Ведём ли мы сейчас указатель. По этому признаку решается, нужно ли
    /// прощаться со страницей.
    bool following_ = false;
};

} // namespace oxymp::client::game
