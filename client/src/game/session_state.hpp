#pragma once

#include "engine_addresses.hpp"

namespace oxymp::client::game {

/// Что игра думает о своей сетевой сессии.
///
/// Только чтение и ничего больше. Заведено раньше всякой подмены намеренно:
/// два предыдущих вмешательства в загрузку — отказ от вступительного ролика и
/// подмена его имени — сломали игру именно потому, что делались вслепую, а
/// проверялись по тому, что видно на экране. Крутящийся значок GTA Online
/// одинаково выглядит и когда игра ждёт сессию, и когда она уже сдалась.
///
/// Отсюда правило для всей работы над сессией: сперва научиться спрашивать,
/// потом отвечать. Подставлять игре сессию, не умея прочитать её мнение о
/// происходящем, — это третий слепой заход после двух неудачных.
///
/// Функция игры доводов не принимает и работает от любого потока: скриптовый
/// контекст ей не нужен, это не натив.
class SessionState {
public:
    explicit SessionState(const EngineAddresses& addresses) noexcept;

    [[nodiscard]] bool ready() const noexcept { return started_ != nullptr; }

    /// Начата ли сетевая сессия. Ложь, если спросить не у кого.
    [[nodiscard]] bool started() const;

private:
    using StartedFunction = bool (*)();

    StartedFunction started_ = nullptr;
};

} // namespace oxymp::client::game
