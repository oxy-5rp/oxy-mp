#pragma once

#include <chrono>
#include <string>

#include <windows.h>

namespace oxymp::client::game {

/// Окно игры: заголовок и значок.
///
/// Игра называет своё окно сама и ставит свой значок. Для мультиплеера это
/// неверно вдвойне: в панели задач висит «Grand Theft Auto V» с логотипом
/// Rockstar, хотя запущен oxyMP, а при нескольких запущенных играх различить их
/// вовсе нельзя.
///
/// Меняется и то и другое обычными средствами Windows, без всякого вмешательства
/// в код игры: окно принадлежит нашему же процессу, а модуль в нём свой.
///
/// Значок берётся из ресурсов самого модуля, а не из файла на диске: файл рядом
/// с игрой не лежит и лежать не должен, а путь к каталогу проекта клиенту
/// неизвестен.
///
/// Заголовок ставится не однажды. Игра переписывает его на своих переходах —
/// например при входе в мир, — и однократной установки хватает ровно до первого
/// такого случая.
class Window {
public:
    /// Класс нашего собственного окна-холста, на котором рисуется интерфейс.
    ///
    /// Объявлен здесь, а не там, где заводится, и не ради удобства: поиск окна
    /// игры обязан его пропускать. Холст — видимое окно верхнего уровня без
    /// хозяина в том же процессе, то есть в точности то, что ищет запасной отбор,
    /// — и не знай о нём поиск, он однажды принял бы холст за окно игры и повесил
    /// бы на него и заголовок, и перехват клавиатуры.
    static constexpr const wchar_t* kSurfaceClass = L"oxyMPPageSurface";

    /// Разыскивает окно игры и запоминает значок из ресурсов модуля.
    ///
    /// Описатель модуля не спрашивается, а выясняется на месте: он нужен только
    /// здесь, и тянуть его через полпроекта от точки входа значит завести
    /// зависимость ради одной строки.
    Window() noexcept;

    [[nodiscard]] bool found() const noexcept { return window_ != nullptr; }

    /// Ставит окну наши заголовок и значок. Вызывать можно сколь угодно часто.
    ///
    /// Частота ограничивается здесь же: обход окон и чтение заголовка стоят
    /// заметно дороже, чем проверка часов, а меняется заголовок считаное число
    /// раз за запуск. Вызывающему следить за этим не нужно.
    void apply(const std::string& title);

    /// Ищет главное окно текущего процесса.
    ///
    /// Наружу — потому что окно игры нужно не только для заголовка: на нём же
    /// стоит перехват клавиатуры, а искать его вторым способом значило бы
    /// завести два разных представления о том, какое окно главное.
    [[nodiscard]] static HWND findOwnWindow() noexcept;

private:

    HWND window_ = nullptr;
    HICON icon_ = nullptr;

    /// Что мы поставили в прошлый раз. По нему видно, переписала ли игра
    /// заголовок и нужно ли ставить снова.
    std::wstring applied_;

    bool iconApplied_ = false;

    /// Жаловались ли уже, что окна нет.
    bool lostReported_ = false;

    /// Когда работали с окном в прошлый раз.
    std::chrono::steady_clock::time_point appliedAt_{};
};

} // namespace oxymp::client::game
