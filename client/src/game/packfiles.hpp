#pragma once

#include "engine_addresses.hpp"
#include "file_system.hpp"

#include <cstddef>
#include <filesystem>
#include <memory>
#include <mutex>
#include <string>
#include <vector>

namespace oxymp::client::game {

/// Архивы игры (`.rpf`), открытые её же средствами.
///
/// Оглавление у архивов зашифровано, и подбирать схему шифрования не нужно —
/// расшифровывает его сама игра. Мы лишь заводим её же `rage::fiPackfile`,
/// просим открыть файл и вешаем получившееся устройство на свою приставку;
/// дальше архив ничем не отличается от любого другого места её файловой
/// системы, и содержимое читается обычным `FileSystem`.
///
/// **Этим закрывается вторая половина подгрузки чужого добра.** Первая —
/// россыпь файлов рядом с ресурсом (`FileDevice`) — уже была; но чужие машины и
/// карты чаще раздают одним архивом, и до сих пор он доезжал до клиента и лежал
/// в кеше мёртвым грузом.
///
/// Объект архива — просто отведённая память нужного размера: таблицу методов
/// ставит ему сам переходник заведения, взятый у игры. Держать её отдельным
/// адресом, как делает CitizenFX, незачем — у них свой класс, которому таблицу
/// приходится подменять, а у нас класса нет вовсе.
class Packfiles {
public:
    /// Заводится по разрешённому каталогу адресов. Отказ — не нашлось адресов.
    [[nodiscard]] static std::unique_ptr<Packfiles> create(const EngineAddresses& addresses,
                                                           std::string& error);

    ~Packfiles() = default;

    Packfiles(const Packfiles&) = delete;
    Packfiles& operator=(const Packfiles&) = delete;

    /// Просит открыть архив и повесить его на приставку.
    ///
    /// Путей два, и оба нужны. `archive` — путь на диске: по нему мы сами
    /// смотрим заголовок, прежде чем отдать файл игре. `request` — путь её
    /// собственного вида, которым она этот же файл откроет: путь Windows она не
    /// принимает вовсе, потому что разрешает пути по приставке, а у буквы диска
    /// приставки нет. `prefix` — приставка, на которую вешается открытое, с
    /// косой чертой на конце.
    ///
    /// Не открывает, а откладывает — см. pump. Просить можно откуда угодно:
    /// архивы приезжают сетевым потоком, а открывать их вправе только кадр игры.
    void mount(std::filesystem::path archive, std::string request, std::string prefix);

    /// Открывает и вешает отложенное. **Только из потока с обработчиком скрипта.**
    ///
    /// Требование то же, что у монтирования своего устройства, и по той же
    /// причине: игра выделяет память своим потоковым аллокатором, а в чужих
    /// потоках его нет вовсе — переходник разыменовал бы ноль и уронил её
    /// внутри неё самой.
    ///
    /// Возвращает приставки, повешенные этим вызовом.
    ///
    /// Именно приставки, а не их число: содержимое открытого архива нужно ещё
    /// обойти и объявить игре, а сделать это может только тот, кто знает про
    /// стриминг и описания. Здесь такого знания нет и быть не должно — это
    /// работа с файловой системой, и ничего больше.
    ///
    /// `files` нужен для одной проверки, без которой нельзя: игра обязана
    /// видеть файл по названному ей пути **до** того, как мы попросим его
    /// открыть. Не увидев, она не отказывается — она читает заголовок из
    /// неинициализированной памяти и падает собой.
    std::vector<std::string> pump(const FileSystem& files);

    /// Сколько архивов открыто.
    [[nodiscard]] std::size_t count() const noexcept;

private:
    Packfiles() = default;

    /// Отложенная просьба.
    struct Wanted {
        std::filesystem::path archive;
        std::string request;
        std::string prefix;
    };

    /// rage::fiPackfile::fiPackfile — заводит объект на отведённой памяти.
    using Construct = void (*)(void* self);

    /// rage::fiPackfile::OpenPackfile.
    ///
    /// Доводы — от CitizenFX: путь, признак (у них всегда истина), вид архива и
    /// ещё одно поле, которое там всегда ноль. Вид 3 — обычный `.rpf` на диске.
    using Open = bool (*)(void* self, const char* archive, bool alwaysTrue, int type,
                          std::intptr_t alwaysZero);

    /// rage::fiPackfile::Mount.
    ///
    /// Зовётся именно он, а не MountGlobal напрямую, и это выяснено дорого.
    /// MountGlobal вешает устройство — и только; архив после этого стоит на
    /// приставке, отзывается на неё, но внутри себя не находит ничего. Причина в
    /// том, что `Mount` делает два дела: вешает и **запоминает приставку в самом
    /// архиве**, а без неё устройство не отрезает приставку от приходящих путей
    /// и ищет `dlcpacks:/имя/content.xml` среди имён, где лежит `content.xml`.
    ///
    /// Признак «пускать к корню» он при этом берёт не из довода, а из поля
    /// самого объекта — см. kAllowRootFlag.
    using MountAt = void (*)(void* self, const char* mountPoint);

    Construct construct_ = nullptr;
    Open open_ = nullptr;
    MountAt mountAt_ = nullptr;

    mutable std::mutex mutex_;
    std::vector<Wanted> pending_;

    /// Приставки, на которые архивы уже повешены. Второй раз ту же приставку
    /// игра не примет, и просить её об этом незачем.
    std::vector<std::string> mounted_;
};

} // namespace oxymp::client::game
