/// Записывает в журнал всё, что известно об окружении, в котором мы запустились.
///
/// Заведено ради разбора чужих поломок. Журнал присылают, когда что-то не
/// работает, и первое, что приходится выяснивать, — у кого он запущен: какая
/// сборка игры, откуда она, какая видеокарта, что ещё внедрено в процесс. Без
/// этого разбор начинается с переписки на три круга, а половина поломок в ней и
/// объясняется — чужой сборкой игры или чужим модулем в процессе.
///
/// Ровно то же и по той же причине пишет alt:V: `Game path`, `Client path`,
/// `Game version`, видеокарта и перечень загруженных DLL.
///
/// Зовётся один раз, сразу после того как журнал заведён. Ничего не решает и
/// ничему не мешает: только читает и пишет.
void reportEnvironment();

