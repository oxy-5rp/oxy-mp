#pragma once

#include "engine_addresses.hpp"

#include <cstdint>
#include <memory>
#include <mutex>
#include <string>
#include <unordered_set>
#include <vector>

namespace oxymp::client::game {

/// Объявление игре своих файлов: моделей и текстур.
///
/// Подмены файлов для своих машин мало, и это главное, что стоит понять про
/// потоковую подгрузку. Файл, лежащий в нашем устройстве, игра прочтёт — но
/// искать его не станет: она ищет не по путям, а по имени в своём списке
/// подгружаемого. Объявить файл этому списку и есть работа этого класса.
///
/// Дальше остаётся описание — `vehicles.meta` и её соседи, — по которому игра
/// узнаёт, что такая машина вообще бывает. Оно идёт другой дорогой, через
/// загрузчик данных, и здесь не делается.
///
/// **Звать можно только из потока с обработчиком скрипта.** Причина та же, что
/// и у монтирования устройства: внутри игра выделяет память своим потоковым
/// аллокатором, которого в чужих потоках нет.
class StreamingFiles {
public:
    /// Заводится по разрешённому каталогу адресов.
    [[nodiscard]] static std::unique_ptr<StreamingFiles> create(const EngineAddresses& addresses,
                                                                std::string& error);

    /// Просит объявить игре файл, лежащий по пути нашего устройства.
    ///
    /// `path` — путь игрового вида, который обслуживает наше устройство:
    /// `oxymp:/stream/amcj.yft`. `name` — имя, под которым игра будет его
    /// искать; для моделей это имя файла целиком, с расширением.
    ///
    /// Не объявляет, а откладывает — см. pump. Просить можно откуда угодно:
    /// файлы приходят с сервера сетевым потоком, а объявлять их вправе только
    /// кадр игры.
    void add(std::string path, std::string name);

    /// Объявляет то, о чём просили. **Только из потока с обработчиком скрипта.**
    ///
    /// Требование то же, что и у монтирования устройства, и по той же причине:
    /// внутри игра выделяет память своим потоковым аллокатором, а в чужих
    /// потоках его нет вовсе.
    ///
    /// Возвращает, сколько файлов игра взяла.
    ///
    /// Зовётся строго после того, как устройство повешено: объявляемый файл
    /// игра тут же и открывает, чтобы узнать его размер и раскладку страниц, —
    /// а открыть его может только через наше устройство.
    std::size_t pump();

    /// Чем игра отвечает, когда не взяла файл.
    static constexpr std::uint32_t kNoSlot = 0xFFFFFFFFU;

private:
    StreamingFiles() = default;

    /// Один отложенный файл: где лежит и под каким именем его искать.
    struct Wanted {
        std::string path;
        std::string name;
    };

    mutable std::mutex mutex_;
    std::vector<Wanted> pending_;

    /// Имена, о которых уже спрашивали: и объявленные, и стоящие в очереди.
    ///
    /// Второй раз объявлять то же самое незачем, а под нагрузкой ещё и вредно:
    /// игра выдаст новое место и потеряет прежнее.
    ///
    /// Множество, а не перечень, и это не вкусовщина. Прежде на каждый файл
    /// пересматривались оба списка целиком, и на карте в четыре с половиной
    /// тысячи файлов это оборачивалось десятью миллионами сравнений строк —
    /// в сетевом потоке, том самом, которым держится связь с сервером. Карта
    /// вдвое больше стоила бы вчетверо дороже.
    std::unordered_set<std::string> known_;

    /// streaming::RegisterRawStreamingFile.
    ///
    /// Доводы — от CitizenFX: номер выдаётся через первый, путь и имя идут
    /// строками, а два признака у них так и остались без имени. Второй из них
    /// («ругаться ли, если не вышло») мы держим выключенным: ругаться будем
    /// сами, своей строкой в журнал.
    using RegisterRawFile = std::uint32_t* (*)(std::uint32_t* slot, const char* path,
                                               bool unknownTrue, const char* registerAs,
                                               bool complainOnFailure);

    RegisterRawFile register_ = nullptr;
};

} // namespace oxymp::client::game
