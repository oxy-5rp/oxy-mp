#pragma once

#include "engine_addresses.hpp"

#include <cstdint>
#include <memory>
#include <string>

namespace oxymp::client::game {

/// Выход игры из сетевой сессии.
///
/// Это и есть причина, по которой поднятая сессия живёт доли секунды и ложится.
/// Сессия при этом настоящая: игра выставляет и признак сетевой игры, и все
/// объекты, которых не хватало подделке, — а затем сама же решает, что играть
/// дальше нельзя, и выходит.
///
/// Почему решает — вопрос, на который ответа не было: выход происходил молча.
/// Перехваченная функция сперва отвечает на него, записывая причину, а затем
/// перестаёт выпускать игру из сессии.
///
/// Заглушать выход целиком нельзя: тем же путём игра выходит из сессии и по
/// нашей воле — например при закрытии клиента. Поэтому заглушка снимаема, и
/// снимается она сама, когда сессия нам больше не нужна.
class NetworkBail {
public:
    /// Ставит перехват. Пусто, если адрес не разрешился.
    [[nodiscard]] static std::unique_ptr<NetworkBail> install(const EngineAddresses& addresses,
                                                              std::string& error);

    ~NetworkBail();

    NetworkBail(const NetworkBail&) = delete;
    NetworkBail& operator=(const NetworkBail&) = delete;

    /// Держать ли игру в сессии.
    ///
    /// Пока держим, попытки выйти записываются в журнал и отменяются. Отпустив,
    /// мы возвращаем игре право выйти — это нужно на выходе из клиента, иначе
    /// игра останется в сессии, которую некому закрыть.
    void hold(bool holding);

    /// Сколько раз игра пыталась выйти, пока мы её держали.
    [[nodiscard]] std::uint64_t attempts() const noexcept;

private:
    NetworkBail() = default;
};

} // namespace oxymp::client::game
