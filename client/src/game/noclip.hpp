#pragma once

#include "native_table.hpp"

#include <oxymp/shared/math/vec3.hpp>

#include <chrono>

namespace oxymp::client::game {

/// Свободный полёт: персонаж движется сквозь мир, не подчиняясь физике.
///
/// Нужен для отладки мультиплеера — быстро попасть в нужное место карты, не
/// подбирая дорогу, — и потому включается клавишей, а не сам по себе.
///
/// Устройство простое: пока режим включён, физика персонажа выключается, а его
/// положение каждый кадр переставляется вручную. Без выключенной физики игра
/// боролась бы с нами, возвращая персонажа на землю.
///
/// Вызывать можно только изнутри скриптового тика.
class Noclip {
public:
    explicit Noclip(const NativeTable& table) noexcept;

    [[nodiscard]] bool ready() const noexcept;
    [[nodiscard]] bool active() const noexcept { return active_; }

    /// Включает либо выключает режим для указанного персонажа.
    void setActive(int ped, bool active);

    /// Переставляет персонажа по нажатым клавишам. Вызывать раз в кадр.
    ///
    /// Вперёд и вбок — по горизонтали, туда, куда смотрит камера; вверх и вниз —
    /// пробелом и Ctrl. Наклон камеры в перемещение не входит намеренно: она
    /// висит выше персонажа и смотрит на него сверху, поэтому «вперёд» по её
    /// направлению всегда уводит в землю.
    void update(int ped);

private:
    using Clock = std::chrono::steady_clock;

    /// Куда смотрит камера, единичным вектором.
    ///
    /// Источников два, и это не перестраховка, а способ обойтись без знания,
    /// которого у нас нет.
    ///
    /// Первый — углы поворота камеры. Точный: это ровно то, чем камера
    /// повёрнута. Но игра отдаёт их безымянной тройкой чисел, и какое из них
    /// наклон, а какое поворот вокруг вертикали, приходится знать заранее.
    /// Ошибись порядком — и «смотрю вперёд, жму вперёд» уводит вверх.
    ///
    /// Второй — отрезок от камеры до груди персонажа. Ошибиться в нём нельзя:
    /// у отрезка нет ни порядка, ни знака, о которых надо договариваться. Зато
    /// он неточен — камера целится не строго в точку, которую мы взяли, и
    /// висит не строго за спиной.
    ///
    /// Поэтому берётся первый, а второй служит ему проверкой: сойдутся — значит
    /// углы разобраны верно; разойдутся на пол-оборота — значит нет, и тогда
    /// лучше неточное направление, чем уверенно неверное.
    [[nodiscard]] shared::Vec3 lookDirection(shared::Vec3 position);

    /// Направление, собранное из углов поворота камеры.
    [[nodiscard]] shared::Vec3 directionFromAngles() const;

    /// Направление, собранное из отрезка «камера — грудь персонажа».
    ///
    /// Пусто, если камера оказалась вплотную к персонажу: так бывает от первого
    /// лица, и тогда отрезка нет.
    [[nodiscard]] shared::Vec3 directionFromGeometry(shared::Vec3 position) const;

    [[nodiscard]] shared::Vec3 coordsOf(int entity) const;

    /// Где персонаж находится по нашему счёту.
    ///
    /// Заодно замечает, что его перенесли помимо нас — из меню или воскрешением,
    /// — и в этом случае принимает новое место за своё.
    [[nodiscard]] shared::Vec3 trackedPosition(int ped);

    /// Ставит персонажа ровно в указанную точку, без поправки на землю.
    void place(int ped, shared::Vec3 destination);

    /// Сколько времени прошло с прошлой перестановки, в секундах.
    [[nodiscard]] float elapsed();

    NativeHandler getCoords_ = nullptr;
    NativeHandler setCoords_ = nullptr;
    NativeHandler setHeading_ = nullptr;
    NativeHandler placeExactly_ = nullptr;
    NativeHandler freeze_ = nullptr;
    NativeHandler setCollision_ = nullptr;
    NativeHandler cameraCoords_ = nullptr;
    NativeHandler cameraRotation_ = nullptr;

    bool active_ = false;

    /// Записан ли в журнал разбор направления. Пишется один раз за включение:
    /// числа нужны, чтобы понять, какой источник взят и почему.
    bool reported_ = false;

    /// Куда смотрели в прошлый раз, когда это удавалось узнать.
    ///
    /// Нужно для вида от первого лица: там камера стоит в голове персонажа, и
    /// отрезок между ними вырождается в точку. Лететь при этом всё равно надо, и
    /// последнее известное направление — лучшее, что можно предложить.
    shared::Vec3 lastDirection{0.0F, 1.0F, 0.0F};

    /// Когда переставляли в прошлый раз. Обнуляется при включении: между
    /// выключением и включением проходят минуты, и первый шаг после них унёс бы
    /// персонажа за карту.
    Clock::time_point movedAt_{};

    /// Где мы держим персонажа по собственному счёту.
    ///
    /// Считается от самого себя, а не от того, что вернёт игра. Это и есть
    /// исправление подъёма: положение персонажа игра вправе поправить после
    /// каждой перестановки, и, читая его обратно, мы складывали свой шаг с её
    /// поправкой. Поправка эта всегда вверх — и полёт уходил вверх в любую
    /// сторону, даже когда шаг был строго горизонтальным.
    ///
    /// Со своим счётом такой обратной связи нет вовсе: сколько прошли, столько и
    /// прошли.
    shared::Vec3 position_{};
};

} // namespace oxymp::client::game
