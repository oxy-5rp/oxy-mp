#pragma once

#include <mutex>
#include <string>
#include <utility>
#include <vector>

namespace oxymp::client {

/// Что игрок сделал мышью на странице.
///
/// Меню целиком живёт на стороне игры: она знает, что можно выдать, куда
/// перенести и кто сейчас в сессии. Странице достаётся вид — и мышь, потому что
/// мышь есть только у неё: указатель ходит по разметке, а не по нативам игры.
///
/// Отсюда и это сообщение: страница называет пункт, а решает по-прежнему игра.
struct UiClick {
    enum class Kind {
        /// Указатель встал на пункт — подсветить его.
        Point,

        /// Пункт нажат.
        Press,

        /// Второе действие над пунктом: то же, что стрелка вправо.
        Alternate,

        /// Шаг назад по разделам.
        Back,

        /// Закрыть меню.
        Close,

        /// Нажато поле ввода: меню пора просить строку.
        Ask,
    };

    Kind kind = Kind::Point;

    /// Какого пункта касается. Для действий без пункта не значит ничего.
    int index = 0;
};

/// Почта от страницы в игру.
///
/// Обратная UiFeed и потому отдельная: туда уходит состояние, у которого важно
/// только последнее значение, а здесь идут события, каждое из которых обязано
/// дойти ровно один раз. Смешать их в одном объекте — значит либо терять
/// нажатия, либо повторять их.
///
/// Пишет поток, ведущий страницу, читает поток игры: применить нажатие можно
/// только изнутри скриптового тика, почти каждый пункт меню — это нативы.
class UiMail {
public:
    void post(UiClick click) {
        const std::lock_guard guard{mutex_};
        clicks_.push_back(click);
    }

    [[nodiscard]] std::vector<UiClick> take() {
        const std::lock_guard guard{mutex_};
        return std::exchange(clicks_, {});
    }

private:
    mutable std::mutex mutex_;
    std::vector<UiClick> clicks_;
};

} // namespace oxymp::client
