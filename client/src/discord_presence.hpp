#pragma once

#include <chrono>
#include <cstdint>
#include <string>

#include <windows.h>

namespace oxymp::client {

/// Что показывать в Discord.
struct Presence {
    /// Адрес сервера в виде «адрес:порт». Пусто — игрок ещё в меню.
    std::string server;

    /// Наш номер в сессии. Ноль означает «сервер ещё не принял».
    std::uint32_t playerId = 0;

    /// Сколько игроков на сервере, включая нас.
    std::size_t players = 0;

    /// Подключены ли мы прямо сейчас. Пока нет — Discord показывает подключение,
    /// а не игру: иначе выходит, что человек «играет» на сервере, до которого не
    /// достучался.
    bool connected = false;

    /// Выбирает ли игрок сервер прямо сейчас.
    ///
    /// Отдельно от «не подключены», и различать обязательно: «подключаемся» и
    /// «сидит в меню» — разные новости для того, кто смотрит на показ. Показ при
    /// этом идёт с первой секунды запуска, а не с первой попытки подключения:
    /// человек, открывший меню, уже запустил oxyMP, и Discord должен говорить
    /// именно это.
    bool inMenu = false;
};

/// Показ происходящего в Discord.
///
/// Discord не требует ни библиотеки, ни сети: он слушает именованный канал, и
/// весь обмен — это опознание и посылки с тем, что показывать. Поэтому здесь
/// нет ни одной внешней зависимости, а протокол умещается в один файл.
///
/// Живёт в сетевом потоке клиента, а не в игровом. Причина простая: кадр игры не
/// имеет права ждать чужой процесс, а Discord может быть занят, закрыт или не
/// установлен вовсе — и любой из этих случаев обязан пройти незаметно.
///
/// Отсутствие Discord — не ошибка. Соединение пробуется изредка и молча: игрок
/// без Discord не должен видеть ни жалоб, ни задержек.
class DiscordPresence {
public:
    /// clientId — номер приложения, выданный Discord.
    explicit DiscordPresence(std::string clientId);
    ~DiscordPresence();

    DiscordPresence(const DiscordPresence&) = delete;
    DiscordPresence& operator=(const DiscordPresence&) = delete;

    /// Сообщает, что показывать. Вызывать можно хоть каждый оборот.
    ///
    /// Отправляется не всё подряд: Discord ограничивает частоту посылок, а
    /// показывать одно и то же по десять раз в секунду незачем. Уходит только
    /// изменившееся и не чаще положенного.
    void update(const Presence& presence);

private:
    using Clock = std::chrono::steady_clock;

    /// Пробует подключиться к Discord. Ложь, если его нет, — это норма.
    bool connect();

    void disconnect();

    /// Шлёт посылку: заголовок из кода и длины, следом тело.
    bool send(std::uint32_t opcode, const std::string& payload);

    /// Разбирает то, что Discord прислал в ответ.
    ///
    /// Читать обязательно, и не только ради вежливости. Discord отвечает на
    /// каждую посылку — подтверждением либо отказом с причиной, — и не читая
    /// ответов, мы не отличаем «показано» от «отвергнуто». Именно так и вышло
    /// в первый раз: канал открылся, посылки ушли, а в Discord не появилось
    /// ничего, и сказать почему было нечем.
    ///
    /// Непрочитанное к тому же копится в канале, и однажды переполнит его.
    ///
    /// Чтение не ждёт: сперва спрашиваем, есть ли что читать. Ожидание здесь
    /// означало бы, что закрытый Discord останавливает сетевой поток клиента.
    void pump();

    /// Собирает тело посылки с тем, что показывать.
    [[nodiscard]] std::string describe(const Presence& presence) const;

    std::string clientId_;

    HANDLE pipe_ = INVALID_HANDLE_VALUE;

    /// Когда пробовать соединение в следующий раз.
    Clock::time_point nextAttemptAt_{};

    /// Когда разрешено отправить следующее изменение.
    Clock::time_point nextSendAt_{};

    /// Что отправлено в прошлый раз. По нему видно, изменилось ли что-нибудь.
    std::string sent_;

    /// Когда игрок вошёл. Discord по этому времени сам считает, сколько он
    /// играет, и обновлять его не нужно — важно не сбрасывать.
    std::int64_t startedAt_ = 0;

    /// Номер посылки. Discord помечает им ответ, и по нему видно, на что он
    /// отвечает. Растёт только при удачной отправке.
    std::uint64_t nonce_ = 1;

    /// Записано ли в журнал первое подтверждение. Остальные не пишутся: их
    /// столько же, сколько посылок, и они одинаковы.
    bool confirmed_ = false;
};

} // namespace oxymp::client
