#pragma once

#include <atomic>
#include <chrono>
#include <cstdint>
#include <stop_token>

namespace oxymp::client {

/// Сторож игрового кадра: замечает, что игра встала, и говорит, на чём.
///
/// Заведён потому, что зависшая игра не оставляет после себя ничего. Игра стоит,
/// журнал молчит, окно не перерисовывается — и человеку остаётся сказать только
/// «просто зависла». По такому не чинят: место обрыва в журнале — последняя
/// строка, которую успел написать кто-то другой, и к настоящей причине она
/// отношения не имеет.
///
/// **Ни одной блокировки, и это не аккуратность, а условие работы.** Сторож
/// сторожит ровно тот случай, когда поток игры за что-то держится и не
/// отпускает; возьми он ту же блокировку — замер бы вместе с ним и промолчал.
/// Поэтому отметка — это два атомарных слова, а сам он живёт отдельным потоком,
/// который не трогает ни очередь сообщений, ни ленту интерфейса.
///
/// Отметка стоит копейки: запись указателя на строковую постоянную и времени.
/// Строки поэтому обязаны быть постоянными — временную строку сторож прочёл бы
/// уже освобождённой.
class FrameWatch {
public:
    /// Отмечает, до какого места дошёл кадр. **Только строковые постоянные.**
    ///
    /// Зовётся из потока игры, по нескольку раз за кадр. Дешевле некуда: две
    /// записи в атомарные поля без всякого упорядочения между собой — сторожу
    /// довольно приблизительной картины, а точность стоила бы барьеров на
    /// каждом кадре.
    void mark(const char* phase) noexcept;

    /// Что кадр делал последним и как давно.
    struct Look {
        std::chrono::milliseconds silence{0};
        const char* phase = nullptr;
    };

    [[nodiscard]] Look look() const noexcept;

    /// Сколько кадру позволено молчать, прежде чем это назовут зависанием.
    ///
    /// Пять секунд — заведомо больше всего, что бывает при обычной работе:
    /// самая тяжёлая подгрузка занимает доли секунды, а объявление игре чужой
    /// карты разбито на порции именно затем, чтобы в этот срок укладываться.
    /// Меньше — и сторож ругался бы на живую игру.
    static constexpr auto kFreeze = std::chrono::seconds{5};

private:
    /// Указатель на строковую постоянную. Начальное значение — не «неизвестно»,
    /// а честное «кадров ещё не было»: до первого кадра игра и вправду молчит,
    /// и путать это с зависанием нельзя.
    std::atomic<const char*> phase_{"frames have not started"};

    /// Мгновение последней отметки в миллисекундах монотонных часов. Ноль —
    /// отметок ещё не было.
    std::atomic<std::int64_t> markedAt_{0};
};

/// Следит за кадром и пишет в журнал, когда тот встал и когда отошёл.
///
/// Отдельным потоком, а не заодно с сетевым циклом: сетевой поток и сам
/// упирается в те же блокировки, что и поток игры, и в настоящем зависании
/// молчит вместе с ним — а сторож обязан заговорить именно тогда.
///
/// Возвращается, когда поток просят остановиться.
///
/// Через stop_token, а не через свой признак: сторож заводится std::jthread, а
/// тот сам просит остановки и дожидается потока в своём разрушении. Один
/// забытый выход из функции иначе оставил бы поток жить дольше того, на что он
/// ссылается.
void watchFrames(const FrameWatch& watch, std::stop_token stop);

} // namespace oxymp::client
