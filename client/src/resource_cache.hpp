namespace oxymp::client {

/// Хранилище того, что клиент забрал у сервера.
///
/// Лежит рядом с клиентом, в `cache`. Внутри — по каталогу на сервер... нет, по
/// файлу на отпечаток: отпечаток и есть имя, а одинаковое содержимое у разных
/// серверов — это одно и то же содержимое, и качать его дважды незачем.
///
/// Что здесь происходит по шагам:
///
///   1. сервер прислал список: имя, отпечаток, размер;
///   2. чего нет в кеше — качается с его же мини-сайта;
///   3. скачанное сверяется с отпечатком: не сошлось — выбрасывается;
///   4. сошлось — расшифровывается тем же ключом, что и на сервере.
///
/// Расшифрованное кладётся рядом, под исходным именем: дальше его подхватывает
/// игра, а ей нужен обычный файл.
class ResourceCache {
public:
    /// Готовый к употреблению ресурс.
    struct Ready {
        /// Исходное имя, как у хозяина сервера: `amgone.rpf`.
        std::string name;

        /// Где лежит расшифрованный файл.
        std::filesystem::path path;
    };

    /// Как идут дела: сколько ресурсов разобрано из скольких и качаем ли мы
    /// прямо сейчас.
    ///
    /// Нужен затем, что закачка занимает столько, сколько занимает, а меню всё
    /// это время показывает одну строку. Различать сверку и закачку обязательно:
    /// первая проходит мгновенно, вторая — минутами, и одно слово на обе
    /// означало бы «зависло» ровно в том случае, когда всё идёт хорошо.
    using Progress = std::function<void(std::size_t done, std::size_t total, bool downloading)>;

    /// Заводит кеш в указанном каталоге. Каталог создаётся при надобности.
    explicit ResourceCache(std::filesystem::path directory);

    /// Приводит кеш в соответствие со списком сервера.
    ///
    /// Качает недостающее, проверяет и расшифровывает. Возвращает всё, что
    /// готово к употреблению, — включая то, что уже лежало здесь с прошлого
    /// раза.
    ///
    /// Неудача по одному ресурсу не отменяет остальные: пропавший файл — повод
    /// обойтись без него, а не отказаться играть.
    /// Скачивает свёрток и запоминает его на время разбора. Пусто — не вышло.
    ///
    /// Свёрток качается один раз на весь ресурс, а не по разу на файл внутри: на
    /// чужой карте это разница между одним запросом и тысячами.
    [[nodiscard]] const std::vector<std::uint8_t>* openBundle(
        const std::string& serverAddress, std::uint16_t serverPort, const std::string& hash,
        std::unordered_map<std::string, std::vector<std::uint8_t>>& opened,
        const std::vector<std::uint8_t>& key);

    /// Достаёт из свёртка один файл по его составному имени.
    [[nodiscard]] static bool takeFromBundle(const std::vector<std::uint8_t>& bundle,
                                             const std::string& name,
                                             const std::vector<std::uint8_t>& key,
                                             std::vector<std::uint8_t>& contents);

    [[nodiscard]] std::vector<Ready> sync(const std::string& serverAddress,
                                          std::uint16_t serverPort,
                                          const std::vector<shared::ResourceEntry>& wanted,
                                          const Progress& report);

    /// Корень, в котором лежат разложенные ресурсы сервера.
    ///
    /// По каталогу на ресурс, внутри — то же дерево файлов, что и у хозяина
    /// сервера. Именно отсюда клиентская скриптовая машина берёт точку входа и
    /// всё, что та тянет через require.
    [[nodiscard]] std::filesystem::path resourceRoot() const;

private:
    /// Качает один ресурс. Возвращает зашифрованное содержимое.
    [[nodiscard]] std::vector<std::uint8_t> download(const std::string& url,
                                                     std::uint64_t expectedSize,
                                                     std::string& error) const;

    /// Читает опись разложенного: составное имя файла в его отпечаток.
    void readIndex();

    /// Пишет опись обратно.
    void writeIndex() const;

    std::filesystem::path directory_;

    /// Что уже разложено и с каким содержимым.
    ///
    /// Опись нужна затем, что дерево ресурса лежит под настоящими именами, а не
    /// под отпечатками: иначе `require('./утилиты')` не нашёл бы соседний файл.
    /// Но имя не говорит о содержимом ничего — сервер мог пересобрать ресурс, и
    /// файл с тем же именем стал другим. Сверять же отпечаток пересчётом значило
    /// бы читать все полторы тысячи файлов при каждом входе в сессию.
    ///
    /// Опись отвечает на этот вопрос одним сравнением строк.
    std::map<std::string, std::string> laid_;
};

} // namespace oxymp::client
