#pragma once

#include <filesystem>
#include <string>

namespace oxymp::cefui {

/// Отдаёт страницу по ссылкам вида `http://ui/index.html`.
///
/// Заведено ради размера. Ссылка с данными, которой обходится экран загрузки,
/// на меню не годится: собранная страница весит четыре с половиной мегабайта, и
/// каждый показ означал бы шесть мегабайт base64 в памяти.
///
/// Сама страница приходит доводом, а не берётся с диска: она лежит ресурсом
/// внутри модуля клиента. Каталог остаётся вторым источником — для всего, что
/// страница попросит рядом с собой, — но у собранной страницы соседей нет: vite
/// складывает её в один файл.
///
/// Имя схемы то же, что у alt:V, и это не подражание: страница взята оттуда и
/// ссылается на свои файлы так, как её собрали. Своё имя означало бы правку
/// страницы при каждом её обновлении.
///
/// Ссылка ведёт в один-единственный каталог. Выйти из него нельзя ни точками, ни
/// корнем: страница получена от сервера, а сервер — чужой, и открывать ему диск
/// целиком незачем.
///
/// Зовётся один раз, после того как CEF поднят.
void registerUiScheme(std::string page, const std::filesystem::path& directory);

} // namespace oxymp::cefui
