#pragma once

#include <cstdint>

namespace oxymp::shared {

/// Тип сообщения. Занимает первый байт каждого пакета.
///
/// Числа заданы явно и не переиспользуются: значение, однажды присвоенное
/// сообщению, закрепляется за ним навсегда, даже если сообщение удалят.
enum class MessageId : std::uint8_t {
    /// Клиент представляется серверу. Всегда первое сообщение в соединении.
    ClientHello = 1,

    /// Сервер принял клиента и сообщил его идентификатор.
    ServerWelcome = 2,

    /// Сервер отказал в подключении.
    ServerReject = 3,

    /// Проверка связи, отправитель прикладывает свою отметку времени.
    Ping = 4,

    /// Ответ на Ping с той же отметкой — по ней отправитель считает задержку.
    Pong = 5,

    /// К серверу подключился ещё один игрок.
    PlayerJoined = 6,

    /// Игрок отключился.
    PlayerLeft = 7,

    /// Снимок состояния игрока: где он и куда смотрит.
    ///
    /// От клиента идёт его собственное состояние без идентификатора — сервер
    /// знает, чьё это соединение. Обратно другим клиентам сервер шлёт то же
    /// сообщение, проставив идентификатор владельца.
    PlayerState = 8,

    /// Снимок машины, за рулём которой сидит отправитель.
    ///
    /// Идёт отдельно от состояния игрока, потому что и отправляет его не всякий
    /// игрок, и получателю он нужен раньше, чем сам игрок: пассажира некуда
    /// сажать, пока машины нет.
    VehicleState = 9,

    /// Игрок написал в чат. Только от клиента.
    ChatSay = 10,

    /// Строка чата всем в сессии. Только от сервера.
    ///
    /// Ею же расходятся сообщения о входе и выходе: для получателя это одна и
    /// та же лента, и разделять её на два потока значило бы собирать её обратно
    /// на каждом клиенте.
    ChatLine = 11,

    /// Клиент сообщает, что попал по чужому игроку. Только от клиента.
    ///
    /// Урон считает тот, кто стрелял, а применяет тот, в кого попали. Иначе
    /// никак: персонаж чужого игрока у нас — обычный болванчик, и всё, что с ним
    /// происходит, для его хозяина не существует.
    DamageReport = 12,

    /// Сервер сообщает игроку, что по нему попали. Только от сервера.
    DamageTaken = 13,

    /// Сервер переносит игрока в точку. Только от сервера.
    ///
    /// Единственное, чего сервер не может сделать сам: персонаж живёт в игре у
    /// своего хозяина, и переставить его может только она. Всё остальное —
    /// здоровье, оружие, машины, погода — сервер меняет у себя и рассылает
    /// готовым.
    PlayerTeleport = 15,

    /// Что сервер раздаёт сверх самой игры. Только от сервера.
    ///
    /// Идёт сразу за приветствием, одним сообщением на весь список: клиенту надо
    /// знать всё, прежде чем начинать качать, — иначе он не отличит «список
    /// кончился» от «список ещё идёт».
    ResourceList = 17,

    /// Как выглядит машина: цвет, номер, тюнинг.
    ///
    /// Отдельно от снимка машины, потому что живёт по другим правилам: меняется
    /// редко и обязано дойти. Снимок, наоборот, устаревает через полсотни
    /// миллисекунд, и переотправлять его незачем.
    VehicleAppearance = 18,

    /// Сколько у игрока денег. Только от сервера.
    ///
    /// Деньги принадлежат серверу целиком, и это не прихоть. Своих денег у игры
    /// в нашей сессии нет: счётчик, который она показывает, читается из
    /// сохранения настоящего GTA Online — чужого, принадлежащего игроку и его
    /// покупкам. Ни показывать его, ни тем более писать в него мы не вправе.
    MoneyChanged = 16,

    /// В сессии появилась машина. Только от сервера.
    ///
    /// Приходит дважды в жизни каждого клиента: когда машину заводят при нём и
    /// когда он входит в сессию, где она уже есть. Второе не менее важно
    /// первого — без него вошедший не увидел бы ничего, кроме машин, заведённых
    /// после него.
    VehicleAdded = 20,

    /// Машины больше нет. Только от сервера.
    VehicleRemoved = 21,

    /// Кто отныне ведёт машину. Только от сервера.
    ///
    /// Ведущий — клиент, который считает физику машины и рассылает её снимки.
    /// Он ровно один, назначает его сервер, и меняется он по ходу игры: сел за
    /// руль — стал ведущим, ушёл из сессии — сервер передал машину другому.
    ///
    /// Отдельным сообщением, а не полем снимка, по двум причинам. Смена ведущего
    /// обязана дойти — потерянная, она оставила бы машину без хозяина или с
    /// двумя сразу, — а снимки идут по ненадёжному каналу. И меняется она
    /// считанные разы за поездку, тогда как снимков двадцать в секунду.
    VehicleAuthority = 22,

    /// Какая в сессии погода и который час. Только от сервера.
    ///
    /// Часы и погода принадлежат серверу целиком, и иначе быть не может. У себя
    /// их ставит каждый клиент сам, и предоставленные себе они разойдутся за
    /// минуты: у одного полдень и ясно, у другого ночь и гроза. Разойдутся не
    /// только на вид — ночью дальше вытянутой руки не видно, а в дождь машину
    /// несёт юзом.
    WorldState = 24,

    /// Чем игрок вооружён. Только от сервера и только ему самому.
    ///
    /// Только ему — потому что остальным незачем: они видят, что у него в руках,
    /// из его же снимка. Полный список нужен одному человеку — владельцу, чтобы
    /// выдать себе всё это в игре.
    PlayerLoadout = 26,

    /// Сколько у игрока здоровья и брони. Только от сервера и только ему самому.
    ///
    /// Здоровье принадлежит серверу целиком. Раньше его вёл сам игрок: стрелявший
    /// сообщал об уроне, а жертва применяла его к себе — и была единственным
    /// источником правды о собственной жизни. При потерянном пакете урона просто
    /// не случалось, а спорить об этом было некому.
    HealthChanged = 28,

    /// В сессии появился предмет. Только от сервера.
    ObjectAdded = 29,

    /// Предмета больше нет — или он ушёл из виду. Только от сервера.
    ObjectRemoved = 30,

    /// Именованное событие от клиента серверу.
    ///
    /// Этим сообщением клиент говорит всё, что не описано протоколом: нажат
    /// пункт меню, отправлена форма, случилось что-то в странице интерфейса.
    /// Имя и полезная нагрузка — строки, и разбирает их не клиент, а ресурс
    /// сервера.
    ///
    /// Так устроено потому, что клиент не должен знать правил игры. Раньше он
    /// просил сервер завести машину, выдать оружие, сменить погоду — то есть
    /// носил в себе перечень того, что в сессии бывает, и менялся всякий раз,
    /// когда менялся игровой режим. Теперь он передаёт нажатие, а что оно
    /// значит, знает сервер.
    ClientEvent = 33,

    /// Именованное событие от сервера клиенту.
    ///
    /// Обратная сторона того же: сервер отдаёт странице интерфейса то, что ей
    /// показывать. Клиент содержимое не толкует — он передаёт его дальше.
    ServerEvent = 34,
};

// Числа 14, 19, 23, 25, 27, 31 и 32 закреплены за упразднёнными сообщениями и
// повторно не выдаются.
//
// Ими клиент просил сервер завести машину, убрать её, выдать оружие, сменить
// погоду, поставить предмет — и распоряжался чужими игроками из админ-меню.
// Всё это переехало на сервер: меню живёт ресурсом, а клиент присылает нажатие
// через ClientEvent. Оставить старые номера свободными нельзя — клиент прежней
// сборки, столкнувшись с новым сервером, разобрал бы чужое сообщение как своё.

/// Причина отказа в подключении.
enum class RejectReason : std::uint8_t {
    /// Версии протокола у клиента и сервера разошлись.
    ProtocolMismatch = 1,

    /// Достигнут предел числа игроков.
    ServerFull = 2,

    /// Имя пустое или содержит недопустимые символы.
    ///
    /// Отказ окончательный: то же имя не станет допустимым само по себе.
    InvalidNickname = 3,

    /// Имя занято другим игроком.
    ///
    /// Отказ временный, и отделён от InvalidNickname именно поэтому. Самый
    /// частый случай — переподключение: игрок вернулся раньше, чем сервер успел
    /// похоронить его прошлое соединение, и имя ещё числится за покойником.
    /// Клиент, считающий такой отказ окончательным, не вернётся в игру никогда.
    NicknameTaken = 4,
};

/// Что за строка пришла в чат.
///
/// Вид отделён от текста намеренно: рисуются они по-разному, а собирать
/// оформление в текст на сервере значит навсегда закрепить его вид.
enum class ChatKind : std::uint8_t {
    /// Обычная реплика игрока.
    Say = 0,

    /// Игрок вошёл в сессию.
    Join = 1,

    /// Игрок вышел.
    Leave = 2,

    /// Сообщение сервера, автора у него нет.
    System = 3,
};

} // namespace oxymp::shared
