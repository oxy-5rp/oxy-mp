/// ходит, а новое сообщение стоило бы номера в протоколе ради одной строки.
/// Две приставки-подчёркивания говорят читающему, что имя не принадлежит
/// режиму и занимать его нельзя.
inline constexpr std::string_view kClientReadyEvent = "__oxymp:ready";

/// Сколько ресурсов сервер вправе объявить за раз.
///
/// Предел нужен разбору, а не хозяину сервера: без него испорченный пакет с
/// огромным числом в поле длины заставил бы клиент выделять память под список,
/// которого нет.
///
/// Прежде здесь стояло 512, и это оказалось мало по-настоящему. Раздаётся не
/// «ресурс», а каждый его файл: у живого игрового режима клиентская половина —
/// это собранная страница интерфейса, то есть полторы-две тысячи картинок,
/// шрифтов и кусков сборки. При 512 список обрезался молча, клиент скачивал
/// первую четверть и открывал страницу, которой нет: браузер показывал
/// «ERR_NAME_NOT_RESOLVED», и связать это с числом в протоколе было не по чему.
///
/// Восемь тысяч — с запасом вчетверо от виденного. Цена в байтах невелика:
/// запись весит около сотни, и полный список на две тысячи файлов — двести
/// килобайт одним надёжным пакетом, который ENet сам разобьёт на части.
inline constexpr std::uint16_t kMaxResources = 8192;

/// Один раздаваемый ресурс.
struct ResourceEntry {
    /// Исходное имя — то, как файл называется у хозяина сервера.
    std::string name;

    /// Отпечаток содержимого. По нему ресурс качается и им же называется в кеше.
    std::string hash;

    /// Размер, чтобы показать человеку, сколько качать.
    std::uint64_t size = 0;

    /// Этот файл — страница интерфейса, которую клиент грузит в CEF.
    ///
    /// Так альтв и рейджмп раздают интерфейс: страница живёт на сервере, а не в
    /// сборке клиента. Клиенту нужно знать, какой из скачанных файлов открыть, —
    /// по имени он этого не поймёт, а угадывать нельзя: сегодня страница
    /// называется panel.html, завтра иначе. Помечает её сервер по client-main из
    /// описания ресурса.
    bool page = false;

    /// Каким описанием игра обязана прочесть этот файл. Пусто — не описание.
    ///
    /// Имя вида у самой игры: `VEHICLE_METADATA_FILE`, `HANDLING_FILE`,
    /// `DLC_ITYP_REQUEST`. Говорит его сервер, а не угадывает клиент, и это
    /// существенно: клиент умеет узнавать четыре знакомых имени файла, а карты
    /// состоят из `.ymap`, `.ytyp` и `.ybn` — по имени вид у них не угадывается
    /// никак. Знает его только тот, кто ресурс собирал, и записывает он его в
    /// раздел `[meta]`, как у alt:V.
    std::string dataFile;

    /// Отпечаток свёртка, внутри которого лежит этот файл. Пусто — лежит сам по
    /// себе.
    ///
    /// Свёрток — весь каталог ресурса одним запечатанным файлом. Клиент качает
    /// его целиком и **не раскладывает на диск**: исходный код режима иначе
    /// лежал бы у игрока обычным текстом и открывался блокнотом. Так же делает
    /// alt:V.
    ///
    /// В свёрток попадает не всё: модели и текстуры (`stream/`) остаются
    /// отдельными файлами. Прятать их незачем — они и так расходятся по
    /// интернету, — а свёрток из них вышел бы в гигабайты и лёг бы в память
    /// целиком.
    std::string bundle;
};

/// Список того, что сервер раздаёт сверх самой игры.
struct ResourceList {
    static constexpr MessageId kId = MessageId::ResourceList;

    std::vector<ResourceEntry> entries;

    void write(ByteWriter& writer) const;
    [[nodiscard]] static ResourceList read(ByteReader& reader);
};

