/// Наибольший род взрыва, который знает игра.
///
/// Проверяется получателем: род приходит по сети числом, а натив принимает его
/// не глядя. Игре, которой велели устроить взрыв номер девять тысяч, деваться
/// некуда — она пойдёт за описанием по таблице и промахнётся мимо неё.
inline constexpr std::int32_t kMaxExplosionKind =
    static_cast<std::int32_t>(ExplosionKind::BirdCrap);

/// В мире рвануло.
///
/// Событие, а не состояние, и потому у него нет ни номера, ни уборки: взрыв
/// проигрывается и кончается. Вошедший позже не увидит ничего — так же, как и с
/// движением персонажа, и по той же причине.
///
/// Идёт по надёжному каналу, в отличие от снимков: потерянный снимок заменит
/// следующий, а потерянный взрыв не повторится никогда — и один из зрителей
/// останется с целой машиной там, где у остальных воронка.
struct Explosion {
    static constexpr MessageId kId = MessageId::Explosion;

    Vec3 position;

    /// Что рвануло, в нумерации игры.
    std::int32_t kind = static_cast<std::int32_t>(ExplosionKind::Grenade);

    /// Во сколько раз сильнее обычного. Единица — как у игры.
    float scale = 1.0F;

    /// Слышно ли и видно ли: беззвучный и невидимый взрыв — это чистый урон,
    /// и такие в режимах заводят наравне с обычными.
    bool audible = true;
    bool invisible = false;

    /// Насколько тряхнёт вид. Ноль — не трясти вовсе.
    float shake = 0.0F;

    // Признака «оставить огонь» здесь нет, и это не забывчивость. У натива игры
    // такого довода нет вовсе: горит после взрыва то, чему положено гореть по
    // его роду. Завести поле, которого клиенту нечем исполнить, значило бы
    // соврать тому, кто его выставит.

    void write(ByteWriter& writer) const;
    [[nodiscard]] static Explosion read(ByteReader& reader);
};

/// Игрок выстрелил.
///
/// От клиента идёт без идентификатора — сервер знает, с какого соединения пришёл
/// пакет, и проставляет его сам. Верить здесь клиенту нельзя: иначе он выстрелит
/// от чужого имени.
///
/// Откуда вылетела пуля, здесь не сказано, и это решение. Точку вылета считает
/// получатель — по руке той самой куклы, которая у него стоит: пуля обязана
/// вылететь из ствола, который видно, а не из точки, где ствол был у хозяина
/// шестьдесят миллисекунд назад. Заодно это двенадцать байт, которых нет в
/// сообщении, уходящем при стрельбе из автомата десять раз в секунду.
///
/// Идёт по надёжному каналу. Потерянный снимок заменит следующий, а потерянный
/// выстрел не повторится: у одного зрителя будет воронка от ракеты, у другого
/// целая машина.
struct WeaponFired {
    static constexpr MessageId kId = MessageId::WeaponFired;

    /// Кто выстрелил. В сообщении от клиента не заполняется.
    PlayerId playerId = kInvalidPlayerId;

    /// Хеш оружия. По нему получатель поймёт, пуля это, ракета или граната:
    /// игре довольно хеша, снаряд она заведёт сама.
    std::uint32_t weapon = 0;

    /// Куда ушёл выстрел.
    Vec3 target;

    void write(ByteWriter& writer) const;
    [[nodiscard]] static WeaponFired read(ByteReader& reader);
};

/// Как выглядит оружие в руках у игрока.
///
/// Только от сервера: снаряжение принадлежит ему целиком, и что на стволе
/// навинчено, знает он, а не тот, кто из него стреляет.
///
/// Описывает ровно одно оружие — то, что игрок держит. Всего его снаряжения
/// остальным знать незачем: они видят, что у него в руках, а что лежит в
/// карманах — не их дело. Этим сообщение и отличается от PlayerLoadout, который
/// уходит одному владельцу и несёт весь список.
struct PlayerWeapon {
    static constexpr MessageId kId = MessageId::PlayerWeapon;

    PlayerId playerId = kInvalidPlayerId;

    /// Хеш оружия. Ноль — в руках ничего, и тогда списка насадок нет.
    std::uint32_t weapon = 0;

    /// Расцветка ствола в нумерации игры. Ноль — заводская.
    std::uint8_t tint = 0;

    /// Хеши насадок: прицел, глушитель, магазин, фонарик.
    std::vector<std::uint32_t> components;

    /// Сравнение по всем полям.
    ///
    /// Нужно серверу: сообщение уходит по надёжному каналу и только при
    /// изменении, а узнать об изменении можно только сравнив с тем, что ушло.
    [[nodiscard]] bool operator==(const PlayerWeapon& other) const = default;

    void write(ByteWriter& writer) const;
    [[nodiscard]] static PlayerWeapon read(ByteReader& reader);
};

