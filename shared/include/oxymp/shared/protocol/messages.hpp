/// Какого рода сущность сессии.
///
/// Понадобился он привязке: та связывает две сущности, и род у них может быть
/// любым — предмет вешают на человека, человека сажают на предмет, предмет
/// цепляют к машине. Одного номера здесь мало: номера у разных родов свои, и
/// первый попавшийся предмет с номером три ничем не отличается от третьего
/// игрока.
///
/// None стоит нулём и означает «ни к кому». Без него признак «отвязано»
/// пришлось бы выражать пустым номером, а пустого номера, годного для всех
/// трёх родов, нет: у машин и предметов это ноль, а у игроков — единицы во всех
/// разрядах, и ноль у них законный номер первого вошедшего.
enum class EntityKind : std::uint8_t {
    None = 0,
    Player = 1,
    Vehicle = 2,
    Object = 3,
    Ped = 4,
};

/// Сущность привязана к другой — или отвязана.
///
/// Состояние, а не распоряжение: сервер помнит его и пересказывает вошедшим,
/// как внешность машины. Отвязка — то же сообщение с target рода None.
///
/// Поворот здесь в градусах, как и везде в протоколе. У alt:V он в радианах, и
/// переводит его слой совместимости — там же, где живут все прочие расхождения
/// в единицах.
struct EntityAttachment {
    static constexpr MessageId kId = MessageId::EntityAttachment;

    /// Кого привязывают.
    EntityKind kind = EntityKind::None;
    std::uint32_t id = 0;

    /// К кому. Род None — отвязать.
    EntityKind targetKind = EntityKind::None;
    std::uint32_t target = 0;

    /// К какой кости цели. Минус единица — к самой сущности, а не к кости.
    std::int32_t bone = -1;

    /// Имя кости, если её назвали именем, а не номером.
    ///
    /// Возится рядом с номером, а не вместо него, потому что перевести имя в
    /// номер может только игра: номера костей свои у каждой модели. Непустое
    /// имя старше номера — его и разрешает получатель.
    std::string boneName;

    /// Смещение и поворот относительно точки привязки.
    Vec3 position;
    Vec3 rotation;

    /// Сталкивается ли привязанное с миром.
    bool collision = false;

    /// Держать ли поворот привязанного намертво.
    ///
    /// У alt:V это поле названо наоборот — `noFixedRotation`, — и переворачивает
    /// его слой совместимости. Здесь оно названо так, как его понимает игра:
    /// последний довод ATTACH_ENTITY_TO_ENTITY.
    bool fixedRotation = true;

    [[nodiscard]] bool operator==(const EntityAttachment& other) const = default;

    void write(ByteWriter& writer) const;
    [[nodiscard]] static EntityAttachment read(ByteReader& reader);
};

