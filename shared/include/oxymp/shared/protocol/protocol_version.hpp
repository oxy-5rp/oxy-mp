#pragma once

#include <cstdint>

namespace oxymp::shared {

/// Версия протокола обмена.
///
/// Увеличивается при любом изменении состава или порядка полей в сообщениях.
/// Клиент присылает её первым же сообщением, и сервер отказывает при несовпадении:
/// молча разошедшиеся клиент и сервер дают ошибки, которые невозможно понять.
inline constexpr std::uint16_t kProtocolVersion = 51;

/// Порт сервера по умолчанию.
///
/// Тот же, что у alt:V. Прежде здесь стоял 22005 — порт RAGE MP, — и это была
/// единственная величина, по которой раскладка oxyMP расходилась с alt:V: игрок,
/// набравший адрес без порта, попадал не туда.
inline constexpr std::uint16_t kDefaultServerPort = 7788;

/// Сколько раз в секунду сервер обрабатывает состояние мира.
inline constexpr std::uint16_t kDefaultTickRate = 30;

/// Между какими значениями частота такта имеет смысл.
///
/// Общие для сервера и клиента, и это не порядок ради порядка: частоту называет
/// сервер в приветствии, а клиент по ней решает, как часто слать свои снимки.
/// Разойдись эти границы — и сервер принял бы число, по которому клиент считать
/// откажется.
///
/// Пять снизу: реже — и снимок приходит раз в пятую долю секунды, а показывать
/// между ними становится нечего даже с достраиванием. Сто сверху: чаще — и такт
/// короче десяти миллисекунд, то есть короче того, что сервер успевает сделать
/// при полной сессии, и он начинает опаздывать сам от себя.
inline constexpr std::uint16_t kMinTickRate = 5;
inline constexpr std::uint16_t kMaxTickRate = 100;

/// Каналы соединения.
///
/// Разделение принципиальное: управляющие сообщения обязаны дойти и в правильном
/// порядке, а состояние игроков устаревает быстрее, чем имеет смысл его
/// переотправлять — потерянный снимок дешевле заменить следующим.
enum class Channel : std::uint8_t {
    /// Надёжный упорядоченный канал: рукопожатие, вход и выход игроков.
    Control = 0,

    /// Ненадёжный канал: снимки состояния, отметки времени.
    State = 1,
};

/// Общее число каналов соединения.
inline constexpr std::uint8_t kChannelCount = 2;

} // namespace oxymp::shared
