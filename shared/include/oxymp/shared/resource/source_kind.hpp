#pragma once

#include <string_view>

namespace oxymp::shared {

/// Исходник ли это режима — то, что читает наш клиент, а не игра.
///
/// Знание общее для обеих сторон, и лежит оно здесь именно поэтому. Сервер
/// решает по нему, что запечатать в свёрток; клиент — что ни при каких условиях
/// не объявлять стримингу игры. Разойдись эти два ответа, и вышла бы одна из
/// двух бед: либо файл остался бы лежать у игрока обычным текстом, либо игре
/// пообещали бы модель, которой нет.
///
/// **Каталог `stream/` тут ничего не решает, и это исправление, а не
/// послабление.** Прежде сервер исключал из свёртка всё, что лежит под
/// `stream/`, — по уговору alt:V и FiveM, где там лежат модели. Но чужие режимы
/// кладут туда и свой интерфейс: у проверенного на живом режиме `flowerdm` под
/// `stream/browsers/` лежало 504 файла кода и разметки — три четверти всей его
/// клиентской логики, — и все они оказывались у игрока открытым текстом. Место
/// файла не говорит о его роде; род говорит расширение.
///
/// Список нарочно совпадает по смыслу с тем, что клиент отвергает у стриминга
/// (`worthStreaming`): там он и спрашивается первым, чтобы два списка не могли
/// разойтись.
[[nodiscard]] bool isSourceOrMarkup(std::string_view fileName);

/// Описание для игры ли это по имени — `vehicles.meta` и подобные.
///
/// Такие в свёрток не идут никогда: их читает загрузчик данных игры, а свёрток
/// ему не открыть. Отдельно от списка выше, потому что решается не расширением
/// исходника, а ровно одним окончанием.
[[nodiscard]] bool isGameDescription(std::string_view fileName);

} // namespace oxymp::shared
