#pragma once

#include <cstdint>
#include <optional>
#include <span>
#include <string>
#include <vector>

namespace oxymp::shared {

/// Свёрток ресурса: весь его каталог одним запечатанным файлом.
///
/// Зачем он нужен. Сегодня файлы ресурса приезжают к игроку поодиночке и
/// ложатся на диск деревом под настоящими именами — то есть исходный код режима
/// лежит у него обычным текстом, открывается блокнотом и уносится целиком. У
/// alt:V ресурс приезжает одним файлом и исходником на диске не становится
/// никогда; здесь то же самое.
///
/// **Читать можно с середины, и ради этого формат такой, а не «зашифрованный
/// zip».** Карта весит гигабайты: распаковать её в память нельзя, а игра читает
/// из неё кусками по смещению. Поточный шифр это позволяет — байт потока в любом
/// месте вычисляется сам по себе; сцепленный блочный не позволил бы, и выбор
/// шифра здесь условие задачи, а не вкусовщина.
///
/// Раскладка:
///
/// ```
/// 0   метка "OXRB"
/// 4   выпуск формата
/// 8   длина оглавления
/// 12  число записей
/// 16  длина тела
/// 24  разовая добавка, 12 байт
/// 36  оглавление, зашифровано с начала потока
/// ..  тело, зашифровано тем же потоком следом за оглавлением
/// ```
///
/// Поток один на весь файл и не начинается заново: повторно наложенный поток —
/// это тот же поток, а два разных куска, зашифрованных одним и тем же его
/// началом, выдают друг друга. Оглавление занимает начало потока, тело — всё,
/// что за ним.
///
/// Имена файлов лежат в зашифрованном оглавлении: по свёртку не видно даже того,
/// из чего он состоит.
class Bundle {
public:
    static constexpr std::uint32_t kMagic = 0x42525848U; // "HXRB" младшим байтом вперёд
    static constexpr std::uint32_t kVersion = 1;

    /// Сколько байт от начала файла нужно прочесть, чтобы разобрать заголовок.
    static constexpr std::size_t kHeaderLength = 36;

    /// Длина разовой добавки — та же, что у Vault: шифр один и тот же.
    static constexpr std::size_t kNonceLength = 12;

    /// Заголовок свёртка, разобранный.
    struct Header {
        std::uint32_t indexLength = 0;
        std::uint32_t entryCount = 0;
        std::uint64_t bodyLength = 0;
        std::uint8_t nonce[kNonceLength] = {};

        /// Где в файле начинается тело.
        [[nodiscard]] std::uint64_t bodyStart() const noexcept {
            return kHeaderLength + indexLength;
        }
    };

    /// Один файл внутри свёртка.
    struct Entry {
        /// Путь от корня ресурса, всегда через прямую косую черту.
        std::string path;

        /// Смещение в теле и длина.
        std::uint64_t offset = 0;
        std::uint64_t size = 0;
    };

    /// Что кладут в свёрток.
    struct File {
        std::string path;
        std::vector<std::uint8_t> contents;
    };

    /// Собирает свёрток.
    ///
    /// Разовая добавка берётся из отпечатка содержимого, а не из случайности, и
    /// это намеренно — ровно по той же причине, что и у Vault: одинаковый вход
    /// даёт одинаковый выход, а значит отпечаток свёртка не меняется от
    /// пересборки, и клиент не скачивает заново то, что у него уже есть.
    [[nodiscard]] static std::vector<std::uint8_t> pack(std::span<const File> files,
                                                        std::span<const std::uint8_t> key);

    /// Разбирает заголовок. Пусто — файл не наш или обрезан.
    [[nodiscard]] static std::optional<Header> readHeader(std::span<const std::uint8_t> head);

    /// Разбирает оглавление.
    ///
    /// `index` — ровно `header.indexLength` байт, прочитанных с `kHeaderLength`.
    /// Пустой перечень означает, что оглавление испорчено.
    [[nodiscard]] static std::vector<Entry> readIndex(const Header& header,
                                                      std::span<const std::uint8_t> index,
                                                      std::span<const std::uint8_t> key);

    /// Расшифровывает кусок тела на месте.
    ///
    /// `offsetInBody` — смещение куска от начала тела, а не от начала файла.
    /// Кусок может быть любым: хоть весь файл, хоть шестнадцать байт с середины.
    static void openBody(std::span<std::uint8_t> part, std::uint64_t offsetInBody,
                         const Header& header, std::span<const std::uint8_t> key);
};

} // namespace oxymp::shared
