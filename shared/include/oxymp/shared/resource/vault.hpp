#pragma once

#include <cstdint>
#include <span>
#include <string>
#include <vector>

namespace oxymp::shared {

/// Превращение файла ресурса в `.resource` и обратно.
///
/// Задача — чтобы содержимое не открывалось обычными средствами. Именно так, а не
/// «чтобы не открывалось никем»: ключ обязан быть в клиенте, иначе клиент не
/// прочтёт то, что скачал, — а значит тот, кто всерьёз возьмётся за клиент, ключ
/// достанет. Это свойство любой такой схемы, включая RAGE MP и alt:V, и врать о
/// нём не нужно.
///
/// От чего это действительно защищает: файл не открывается ни архиватором, ни
/// OpenIV, ни просмотром — по нему не видно ни имени, ни того, что это вообще
/// rpf. Случайный человек, забравший файл с сервера, не получит ничего.
///
/// Устроено на ChaCha20 — потоковом шифре Бернстайна. Выбран не за стойкость
/// (её здесь всё равно подрывает известный ключ), а за то, что он короткий,
/// проверяемый по RFC 8439 и не тянет за собой чужую библиотеку.
class Vault {
public:
    /// Длина ключа и разовой добавки, в байтах.
    static constexpr std::size_t kKeyLength = 32;
    static constexpr std::size_t kNonceLength = 12;

    /// Заголовок `.resource`.
    ///
    /// Нужен, чтобы клиент не пытался расшифровать чужой файл и не выдавал
    /// мусор за содержимое. Опознание, а не защита.
    static constexpr std::uint32_t kMagic = 0x5852584FU; // "OXRX"
    static constexpr std::uint32_t kVersion = 1;

    /// Шифрует содержимое в `.resource`.
    ///
    /// nonce берётся из хеша содержимого, а не из случайности, и это намеренно:
    /// одинаковый вход даёт одинаковый выход, а значит хеш ресурса не меняется
    /// от пересборки, и клиент не скачивает заново то, что у него уже есть.
    [[nodiscard]] static std::vector<std::uint8_t> pack(std::span<const std::uint8_t> plain,
                                                        std::span<const std::uint8_t> key);

    /// Восстанавливает содержимое из `.resource`.
    ///
    /// Пусто, если файл не наш, другой версии или испорчен по дороге.
    [[nodiscard]] static std::vector<std::uint8_t> unpack(std::span<const std::uint8_t> packed,
                                                          std::span<const std::uint8_t> key,
                                                          std::string& error);

    /// Ключ, которым пользуются обе стороны.
    ///
    /// Один на сборку. Хранится не строкой в открытом виде, а собирается из
    /// частей при обращении: строка целиком нашлась бы в файле поиском по нему,
    /// а так — нет. Это задерживает любопытного, но не того, кто взялся всерьёз.
    [[nodiscard]] static std::vector<std::uint8_t> builtInKey();
};

/// Отпечаток содержимого — SHA-256, шестнадцатеричной строкой.
///
/// Им ресурс и называется. Смысл двойной: по имени не видно, что внутри, а
/// клиент по нему же понимает, что скачанное дошло целым и что скачивать
/// повторно нечего.
[[nodiscard]] std::string fingerprint(std::span<const std::uint8_t> data);

} // namespace oxymp::shared
