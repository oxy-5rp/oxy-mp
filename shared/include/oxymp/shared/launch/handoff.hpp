#pragma once

#include <atomic>
#include <cstdint>

namespace oxymp::shared {

/// На чём стоит подмена звена BattlEye.
enum class LaunchState : std::uint32_t {
    /// Модуль в лаунчер ещё не попал или не успел взяться за дело.
    Idle = 0,

    /// Перехват стоит: запуск игры пойдёт мимо BattlEye.
    Hooked = 1,

    /// Игра запущена, её номер лежит в gameProcessId.
    GameStarted = 2,

    /// Взяться за дело не вышло. Причина — в error.
    Failed = 3,
};

/// Уговор между лаунчером oxyMP и модулем, который тот внедряет в Rockstar
/// Games Launcher.
///
/// Живёт в разделяемой памяти: это два разных процесса, и запущены они порознь.
/// Пишет модуль, читает лаунчер — за одним исключением: путь к журналу лаунчер
/// выставляет до внедрения, потому что изнутри чужого процесса взять его
/// неоткуда.
///
/// Всё, что нужно от модуля, — сказать, какой процесс получился вместо
/// GTA5_BE.exe. Внедрением занимается лаунчер: у него это уже написано, и
/// второй такой же код был бы вторым местом, где чинить одну ошибку.
struct LaunchHandoff {
    /// Растёт при каждой записи. По нему видно, жив ли пишущий вообще.
    std::atomic<std::uint32_t> generation{0};

    /// Значение LaunchState.
    std::atomic<std::uint32_t> state{0};

    /// Номер процесса игры. Ноль — игра ещё не запускалась.
    std::atomic<std::uint32_t> gameProcessId{0};

    /// Взведена ли подмена.
    ///
    /// Один запуск — один выстрел. Модуль остаётся в лаунчере Rockstar до конца
    /// его жизни, и без этого признака он подменял бы звено BattlEye при каждом
    /// запуске игры, включая те, которые игрок делает сам из окна лаунчера.
    /// Тогда после единственного захода в oxyMP переставал бы работать GTA
    /// Online: он требует BattlEye, а тот не поднимался бы вовсе.
    ///
    /// Взводит лаунчер oxyMP перед тем, как просить игру; снимает сама подмена,
    /// сработав.
    std::atomic<std::uint32_t> armed{0};

    /// Добавлять ли игре ключ входа сразу в сетевой свободный режим.
    ///
    /// Выставляется лаунчером до внедрения. Ключ уводит игру мимо сюжета —
    /// туда, где ей нужна сетевая сессия, — и пока подставить эту сессию нечем,
    /// игра остаётся на вечной загрузке GTA Online. Поэтому по умолчанию ноль:
    /// путь строится, но рабочую сборку не отменяет.
    std::atomic<std::uint32_t> straightIntoFreemode{0};

    /// На каком языке запускать игру: `ru-RU`, `en-US` и так далее.
    ///
    /// Пусто означает «не трогать»: язык останется тем, что назначил лаунчер
    /// Rockstar. Ставится на запуске, а не в самой игре, потому что внутри
    /// сессии игра сменить его не даёт — меню паузы там сетевое, и выбранную
    /// строку оно возвращает обратно.
    ///
    /// Выставляется лаунчером до внедрения и после этого не меняется, поэтому
    /// без атомарности.
    wchar_t gameLanguage[16]{};

    /// Куда модуль пишет свой журнал. Выставляется лаунчером до внедрения и
    /// после этого не меняется, поэтому без атомарности.
    wchar_t logDirectory[260]{};

    /// Почему не вышло. Пусто, пока не Failed.
    char error[192]{};
};

/// Имя разделяемой памяти.
///
/// Local, а не Global: лаунчер Rockstar и наш работают в одном сеансе
/// пользователя, а права на глобальное пространство имён есть не у всякого
/// процесса.
inline constexpr const wchar_t* kLaunchHandoffName = L"Local\\oxyMP-launch";

} // namespace oxymp::shared
