#pragma once

#include <cstdint>

namespace oxymp::shared {

/// Стадия входа игрока в мир.
///
/// Нужна экрану загрузки: он рисует ход входа в мир, а сам этот ход виден
/// только изнутри клиента.
/// Стадии перечислены так, чтобы каждая занимала заметное время: полоса
/// загрузки строится по ним, и стадия, которая держится минуту, выглядит
/// зависшей независимо от того, что происходит внутри.
enum class LoadStage : std::uint32_t {
    /// Модуль внедрён, игра поднимается.
    Booting = 0,

    /// Движок опознан: сигнатуры разрешены, адреса на руках.
    Engine = 1,

    /// Скриптовый движок готов, игра грузит мир.
    Scripts = 2,

    /// На экране страница выбора режима.
    Landing = 3,

    /// Игрок в мире, идёт подготовка персонажа.
    Preparing = 4,

    /// Персонаж готов и перенесён на место.
    Spawned = 5,
};

} // namespace oxymp::shared
