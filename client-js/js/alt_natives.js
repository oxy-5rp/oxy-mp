// Модуль `natives`: нативы игры по имени.
//
// Ресурс, написанный под alt:V, зовёт их так же, как звал бы там:
//
//     const natives = require('natives');
//     natives.setEntityCoords(натив.playerPedId(), 0, 0, 72, false, false, false, false);
//
// Таблица имён, хешей и подписей лежит рядом (`alt_natives_table.js`) и
// порождена из открытой базы. Здесь — только то, что превращает запись таблицы
// в вызываемую функцию.
//
// Файл исполняется после alt_natives_table.js и до alt_client.js.

'use strict';

(function build(alt) {
    const native = alt.native;
    const table = alt.nativeTable;

    /// Готовые функции, по имени.
    ///
    /// Собираются по требованию, а не все сразу, и это не преждевременная
    /// бережливость. Нативов пять тысяч; режим зовёт из них десятки. Собрать
    /// пять тысяч замыканий при запуске значило бы потратить память и время на
    /// то, к чему никто не обратится, — и потратить их в мгновение входа в
    /// сессию, когда игра и так занята загрузкой.
    const built = new Map();

    function make(name) {
        const entry = table[name];

        if (entry === undefined) {
            return undefined;
        }

        const split = entry.indexOf('|');

        // Хеш шестнадцатеричный и в double не помещается без потери старших
        // разрядов — отсюда BigInt.
        const hash = BigInt('0x' + entry.slice(0, split));
        const signature = entry.slice(split + 1);

        const call = (...args) => native.callNative(hash, signature, ...args);

        built.set(name, call);
        return call;
    }

    /// Имена, которые у alt:V есть, а у нас без хеша.
    ///
    /// Их три с половиной тысячи: открытая база CitizenFX знает 5180 нативов,
    /// alt:V объявляет около восьми с половиной тысяч. Список порождается
    /// (`tools/nativegen/missingnatives.py`) и лежит в `alt_natives_absent.js`.
    const отсутствующие = alt.nativesAbsent ?? new Set();

    /// Из них те, что у alt:V объявлены `void`, — распоряжения, а не вопросы.
    const молчащие = alt.nativesAbsentQuiet ?? new Set();

    /// Об одном имени — один раз за сессию.
    const пожаловались = new Set();

    /// Отказ вместо пустоты — для тех имён, которые у alt:V есть.
    ///
    /// Разница важная. Имя, которого нет **нигде**, — это опечатка режима, и
    /// пустота про неё говорит правду. Имя, которое есть у alt:V и нет у нас, —
    /// наша нехватка, и молчать о ней нельзя: режим её не проверяет, потому что
    /// на alt:V оно работает.
    ///
    /// Отказывает при этом по тому же правилу, что и весь слой alt:V, и правило
    /// это здесь однажды переступили.
    ///
    /// **Вопрос** без ответа бросает: натив зовут ради ответа, и сделанный вид
    /// хуже отказа. Зато отказ называет причину, а не «is not a function», и
    /// работает он в обе двери — и через `require`, и через `import * as`,
    /// потому что имя попадает в перечень.
    ///
    /// **Распоряжение** — то есть натив, объявленный у alt:V `void`, — говорит о
    /// себе один раз в журнал и возвращается. Бросать отсюда нельзя ровно по той
    /// же причине, по какой нельзя из `unperformed`: вызов стоит посреди чужого
    /// обработчика, и брошенное исключение уносит с собой всё, что шло следом.
    ///
    /// Нашёл это живой режим. Один `hudSuppressWeaponWheelResultsThisFrame`
    /// посреди его `everyTick` обрывал **весь** кадровый обработчик, каждый
    /// кадр, — и в журнале это выглядело как «ошибка в обработчике render»,
    /// повторённая шестнадцать раз, а не как нехватка одного натива. Из трёх с
    /// половиной тысяч недостающих имён распоряжений почти две трети.
    function отсутствующий(name) {
        const причина =
            `натив «${name}» у alt:V есть, а у нас нет: его имени нет в открытой базе ` +
            'CitizenFX, откуда взяты хеши, а выдумывать хеш нельзя — неверный роняет игру';

        const call = молчащие.has(name)
            ? () => {
                if (!пожаловались.has(name)) {
                    пожаловались.add(name);
                    native.logWarning(причина + ' (распоряжение: пропущено)');
                }
            }
            : () => {
                throw new Error(причина);
            };

        built.set(name, call);
        return call;
    }

    /// Сам модуль.
    ///
    /// Посредник, а не обычный объект: он и позволяет собирать функции по
    /// требованию. Ценой одного лишнего шага при первом обращении — дальше
    /// функция лежит в `built` и берётся оттуда.
    const natives = new Proxy({}, {
        get(_target, name) {
            if (typeof name !== 'string') {
                return undefined;
            }

            const ready = built.get(name);
            if (ready !== undefined) {
                return ready;
            }

            const made = make(name);
            if (made !== undefined) {
                return made;
            }

            // Нативы, которых нет в нашей таблице, отдаются пустотой, а не
            // заглушкой, и это не лень: выдумывать хеш нельзя — неверный даёт не
            // строку в журнале, а вылет игры в мгновение вызова. Пустота же
            // сломается сразу.
            //
            // Но одной пустоты мало, и это выяснил живой чужой режим: «native.X
            // is not a function» не говорит, чья тут вина — опечатка режима или
            // наша нехватка. Поэтому причина называется вслух, один раз на имя.
            //
            // Нехватка эта большая и известная: у открытой базы CitizenFX 5180
            // имён, у alt:V около восьми с половиной тысяч. Подробности и что для
            // её закрытия нужно — в `CLAUDE.md`.
            //
            // **Слышно это только тому, кто зовёт через `require`.** Запись
            // `import * as natives from 'natives'` — а её и пишут чаще — снимает
            // с модуля пространство имён по `ownKeys`, и до посредника дело
            // больше не доходит: недостающего имени в снимке просто нет, и
            // обращение к нему пусто без всякого нашего участия. Проверено живым
            // режимом: он зовёт `import * as`, и предупреждения не увидел ни
            // разу, хотя натива ему не хватало тысячу раз за минуту.
            if (отсутствующие.has(name)) {
                return отсутствующий(name);
            }

            return undefined;
        },

        has(_target, name) {
            return typeof name === 'string' &&
                (Object.hasOwn(table, name) || отсутствующие.has(name));
        },

        ownKeys() {
            // И недостающие тоже: `import * as natives` снимает перечень по этому
            // ответу, и не попавшее в него имя стало бы пустотой без объяснения.
            return [...Object.keys(table), ...отсутствующие];
        },

        getOwnPropertyDescriptor() {
            // Ключи обязаны выглядеть перечислимыми, иначе Object.keys по
            // посреднику бросает.
            return { enumerable: true, configurable: true };
        },
    });

    alt.natives = natives;
})(globalThis.__oxympAlt);
