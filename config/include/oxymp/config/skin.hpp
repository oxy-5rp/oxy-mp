#pragma once

#include <filesystem>
#include <optional>
#include <string>
#include <vector>

namespace oxymp::config {

/// Оформление, которым сервер подменяет вид клиента.
///
/// Файл `skin.bin` рядом с лаунчером — это объект JSON, и назван он так же, как
/// у alt:V, вплоть до имён полей. Своё имя означало бы, что оформление, сделанное
/// для одного мультиплеера, нельзя взять для другого, — а делают его художники,
/// а не программисты, и просить их о втором наборе файлов не за что.
///
/// Внутри лежат три разные вещи, и путать их не следует:
///
///   - вид страницы меню: цвет, фон, значок — уходит ей манифестом;
///   - вид лаунчера: своё имя, свой фон — до страницы не доходит вовсе;
///   - список серверов хозяина оформления — попадает и туда, и туда.
///
/// Картинки лежат строками base64 и здесь такими и остаются. Раскодировать их
/// незачем: странице они уходят в ссылке с данными, то есть тем же base64,
/// которым пришли.
struct Skin {
    /// Сервер из списка хозяина оформления.
    struct Server {
        std::string id;
        std::string name;

        /// Адрес с портом: `connect.example.com:443`.
        std::string address;
    };

    /// Имя, которым назовётся игра. Оно же — заголовок «Добро пожаловать в …».
    std::string gameName;

    /// Имя, которым назовётся лаунчер. Обычно то же самое, но не обязано.
    std::string launcherName;

    /// Значок окна: содержимое .ico строкой base64.
    std::string icon;

    /// Фоны. Первый — у страницы меню, второй — у лаунчера, третий — у
    /// установщика. Все три строками base64, в PNG.
    std::string uiBackground;
    std::string launcherBackground;
    std::string installerBackground;

    /// Знак сервера. base64, PNG.
    std::string logo;

    /// Основной цвет — шесть шестнадцатеричных знаков **без решётки**.
    ///
    /// В файле он записан с решёткой, а страница ждёт без неё и молча
    /// отказывается от цвета, если длина не равна шести. alt:V решётку снимает,
    /// и мы снимаем здесь же — чтобы не искать потом, почему цвет «не
    /// применился».
    std::string primaryColor;

    /// Лента новостей и признак того, что показывать её не надо.
    std::string rss;
    bool rssHidden = false;

    std::vector<Server> servers;

    /// Читает оформление. Пустое значение означает, что его нет или оно испорчено.
    [[nodiscard]] static std::optional<Skin> load(const std::filesystem::path& file);

    /// Собирает то, что страница ждёт в `version:setManifest`.
    ///
    /// Не весь skin.bin: странице нет дела ни до фона лаунчера, ни до значка
    /// окна. Отдавать ей лишние два мегабайта base64 при каждой загрузке — плата
    /// ни за что.
    [[nodiscard]] std::string toManifestJson() const;
};

} // namespace oxymp::config
