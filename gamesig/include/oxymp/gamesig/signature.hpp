#pragma once

#include <cstddef>
#include <string_view>

namespace oxymp::gamesig {

/// Что делать с адресом, который получился после применения смещения к месту совпадения.
enum class Resolution {
    /// Найденное место и есть искомый адрес — обычно начало функции.
    Address,

    /// По адресу лежит 32-битное относительное смещение (RIP-relative операнд
    /// инструкций вида `mov rax, [rip+X]`). Цель = конец инструкции + значение.
    ///
    /// Конец инструкции — не всегда конец смещения: у инструкций с
    /// непосредственным операндом за смещением идёт ещё и он. Сколько именно,
    /// говорит tailBytes.
    RipRelative,

    /// По адресу лежит обычная 32-битная константа, а не ссылка.
    Immediate32,
};

/// Одна сигнатура игрового движка.
///
/// Сигнатура — это байты машинного кода вокруг нужного нам места. Она привязана
/// к конкретной сборке игры: после обновления GTA байты сдвигаются и часть
/// сигнатур перестаёт совпадать. Поэтому все они собраны в одном каталоге —
/// при обновлении игры правится ровно один файл.
struct Signature {
    /// Стабильный идентификатор для кода. Не меняется при обновлениях игры,
    /// в отличие от самой сигнатуры.
    std::string_view id;

    /// Что это за адрес и зачем он нужен.
    std::string_view description;

    /// Байтовая сигнатура в текстовом виде.
    std::string_view pattern;

    /// Смещение от начала совпадения до интересующего нас места. Может быть
    /// отрицательным: часто сигнатура опознаёт середину функции, а нужно её начало.
    std::ptrdiff_t offset;

    Resolution resolution;

    /// Сколько байт инструкции идёт после четырёхбайтного RIP-смещения.
    ///
    /// Смысл имеет только для RipRelative и почти всегда равно нулю: у
    /// большинства инструкций смещение — последнее, что в них есть. Исключение —
    /// инструкции с непосредственным операндом: у `cmp byte ptr [rip+X], 0`
    /// (`80 3D X 00`) за смещением идёт ещё байт сравниваемого значения, и
    /// отсчитывать цель от конца смещения значит промахнуться на этот байт.
    std::ptrdiff_t tailBytes = 0;

    /// Сколько совпадений считается нормой.
    ///
    /// Почти всегда 1. Если совпадений больше — сигнатура неоднозначна и доверять
    /// ей нельзя: сегодня она указывает на нужную функцию, завтра на соседнюю.
    std::size_t expectedMatches;

    /// Обязана ли сигнатура разрешиться, чтобы клиент вообще запустился.
    ///
    /// По умолчанию да, и это главное правило каталога: работать с половиной
    /// адресов нельзя, честный отказ на старте лучше вылета в случайном месте.
    ///
    /// Ложь оставлена для разведки — сигнатур, которые ещё не выверены на этой
    /// сборке и проверяются прямо на живой игре. Такая сигнатура не должна
    /// уносить с собой весь клиент: не нашлась — значит просто нет той
    /// возможности, ради которой её заводили, а всё остальное работает как
    /// работало. Как только сигнатура выверена, признак снимается, и она
    /// переходит в общее правило.
    bool required = true;
};

} // namespace oxymp::gamesig
