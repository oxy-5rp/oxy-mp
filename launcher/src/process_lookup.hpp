#pragma once

#include <cstdint>

namespace oxymp::launcher {

/// Ищет процесс по имени исполняемого файла.
///
/// Ноль означает, что такого процесса нет. Если их несколько, возвращается
/// первый попавшийся: ни игра, ни лаунчер Rockstar второй копии о себе не
/// заводят, а разбирать чужие одноимённые процессы нам незачем.
///
/// Отдельный модуль, потому что искать так приходится дважды и по разным
/// поводам: игру — чтобы внедриться в неё, лаунчер Rockstar — чтобы подменить в
/// нём звено BattlEye.
[[nodiscard]] std::uint32_t findProcessByName(const wchar_t* name);

} // namespace oxymp::launcher
