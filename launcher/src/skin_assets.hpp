#pragma once

#include <filesystem>
#include <string>

#include <windows.h>

namespace oxymp::launcher {

/// Оформление окна лаунчера, взятое из `skin.bin`.
///
/// Отдельно от `config::Skin` потому, что отвечает на другой вопрос. Тот знает,
/// что лежит в файле; здесь — что из этого нужно окну: имя, значок, фон и его
/// размер. Значок при этом превращается в HICON, а картинка — в ссылку с
/// данными, и ни того ни другого в общем модуле настроек быть не должно: он
/// подключается и к клиенту, которому окна не нужны вовсе.
///
/// Так же устроен и alt:V: размер его окна равен размеру картинки из skin.bin —
/// 300 на 400 у образца, — а имя и значок берутся оттуда же. Оформление рисует
/// художник, и лаунчер не вправе решать за него, каким ему быть.
struct SkinAssets {
    /// Имя окна: `customUiLauncherAppName`. Пусто — значит оформления нет.
    std::string name;

    /// Фон окна лаунчера ссылкой с данными: `data:image/png;base64,…`.
    std::string background;

    /// Фон окна установки — того, в котором спрашивают каталог игры.
    ///
    /// Отдельная картинка, а не та же самая: у alt:V она своя и заметно крупнее
    /// — 800 на 600 против 300 на 400 у лаунчера, — потому что спрашивать в
    /// окне размером с открытку нечего.
    std::string installerBackground;

    /// Основной цвет с решёткой, как его ждёт CSS.
    std::string accent;

    /// Размер окна лаунчера — тот, под который нарисован его фон.
    int width = 0;
    int height = 0;

    /// Размер окна установки — тот, под который нарисован его фон.
    int installerWidth = 0;
    int installerHeight = 0;

    /// Значки окна: крупный для панели задач и мелкий для заголовка.
    ///
    /// Владение переходит к тому, кто получил: окно живёт весь запуск, и
    /// освобождать их некому и незачем — Windows уберёт их вместе с процессом.
    HICON largeIcon = nullptr;
    HICON smallIcon = nullptr;

    /// Читает оформление. Пустое имя означает, что его нет или оно испорчено.
    [[nodiscard]] static SkinAssets load(const std::filesystem::path& skinFile);
};

} // namespace oxymp::launcher
