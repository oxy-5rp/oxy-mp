#pragma once

#include <filesystem>
#include <string>
#include <vector>

namespace oxymp::launcher {

/// Что в каталоге игры мешает запуску.
///
/// **Перенесено из gtaMP, и перенесено ради знания, а не ради кода.** Список
/// того, что ломает запуск, набирается не рассуждением, а чужими жалобами: по
/// каждой строке здесь кто-то однажды потерял вечер, не понимая, почему у него
/// «просто не запускается».
///
/// Своего здесь нет ничего — только проверка наличия файлов и, где нужно, их
/// версии. Игру мы не чиним и чужие моды не трогаем: наше дело назвать причину
/// до запуска, а не после того, как игра мигнула окном и закрылась.
class GameConflicts {
public:
    /// Насколько это серьёзно.
    enum class Weight {
        /// Запускать нельзя: с этим игра не поднимется или поднимется битой.
        Blocking,

        /// Запустить можно, но человеку стоит знать.
        Warning,
    };

    /// Одна найденная помеха.
    struct Found {
        Weight weight = Weight::Warning;

        /// Чем это назвать человеку: `OpenIV`, `ReShade`.
        std::string name;

        /// Что именно нашлось и где.
        std::filesystem::path file;

        /// Что с этим делать. Строка уходит и в журнал, и в окно — как и всё
        /// остальное, чем лаунчер разговаривает с человеком.
        std::string advice;
    };

    /// Осматривает каталог игры. Пустой перечень — мешать нечему.
    [[nodiscard]] static std::vector<Found> inspect(const std::filesystem::path& gameDirectory);

    /// Есть ли среди найденного то, с чем запускать нельзя.
    [[nodiscard]] static bool blocked(const std::vector<Found>& found);
};

} // namespace oxymp::launcher
