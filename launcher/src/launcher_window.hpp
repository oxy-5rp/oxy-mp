#pragma once

#include "paths.hpp"
#include "session.hpp"

namespace oxymp::launcher {

/// Окно лаунчера: оформление из `skin.bin` и ход запуска игры.
///
/// Прежде здесь было окно подключения — со списком серверов, полем адреса и
/// именем игрока. Его больше нет, и это не упрощение, а устройство alt:V: сервер
/// выбирается в меню внутри игры, имя правится там же, а лаунчеру остаётся одно
/// дело — поднять игру и внедрить в неё модуль. Два места, где выбирают сервер,
/// неизбежно разошлись бы: то, что набрано в лаунчере, ничего не значило бы для
/// меню, а меню умеет больше — оно знает, подключены ли мы сейчас.
///
/// Отсюда и вид: небольшое вертикальное окно с картинкой во весь размер, строкой
/// состояния и бегущей полосой. Размер, картинка, имя и значок берутся из
/// `skin.bin` — ровно как у alt:V, вплоть до размера окна, равного размеру
/// картинки.
class LauncherWindow {
public:
    /// Показывает окно и не возвращает управление, пока его не закроют.
    ///
    /// Запуск игры начинается сам, без нажатий: нажимать больше нечего, а окно
    /// открывают затем, чтобы играть. Так же ведёт себя alt:V.
    ///
    /// Возвращает код завершения для main.
    [[nodiscard]] static int run(const Paths& paths, Session::Settings settings);
};

} // namespace oxymp::launcher
