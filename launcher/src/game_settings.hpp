#pragma once

#include <filesystem>
#include <string>

namespace oxymp::launcher {

/// Оконный режим игры.
///
/// Хранится в settings.xml игры, в поле <windowed>. Значения задаёт сама игра:
/// ноль — монопольный полноэкранный, единица — окно, двойка — окно без рамки.
enum class WindowMode {
    Fullscreen = 0,
    Windowed = 1,
    Borderless = 2,
};

/// Переводит игру в оконный режим без рамки.
///
/// Нужно ради слоя интерфейса, и это не косметика. В монопольном полноэкранном
/// режиме окно поверх игры не показывается вовсе: картинку рисует не рабочий
/// стол, а сама игра, забравшая экран у Windows. Отсюда и «у друга не отобразился
/// loading экран» — слой был жив, работал и висел ровно там, где надо, только
/// увидеть его было нельзя.
///
/// Режим без рамки выглядит для игрока так же, как полноэкранный, и стоит ему
/// нескольких кадров в секунду — плата за то, что интерфейс мультиплеера вообще
/// существует.
///
/// Прежнее значение сохраняется рядом с журналами, чтобы его можно было вернуть
/// вручную. Сам файл принадлежит игре и лежит в документах пользователя, а не в
/// папке игры: правило «в папку игры ничего не кладётся» не нарушено.
///
/// Возвращает false, только если файл найден, но изменить его не вышло.
/// Ненайденный файл неудачей не считается: игра создаёт его при первом запуске,
/// а до него настраивать нечего.
bool preferBorderlessWindow(const std::filesystem::path& backupDirectory, std::string& note);

} // namespace oxymp::launcher
