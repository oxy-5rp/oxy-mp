#pragma once

#include "game_locator.hpp"

#include <filesystem>
#include <optional>

namespace oxymp::launcher {

/// Игра, выбранная однажды и записанная в `oxymp.toml`.
///
/// Путь к игре — настройка, а не находка. Прежде лаунчер разыскивал её при
/// каждом запуске: перебирал список Rockstar Games Launcher, реестр, библиотеки
/// Steam и описи Epic — и делал это заново даже там, где вчера уже нашёл. Работа
/// эта не бесплатна, её исход зависит от чужих файлов, которые вправе смениться,
/// и человек не может ни поправить его, ни узнать заранее.
///
/// Поэтому путь спрашивается один раз — в окне установки — и ложится в
/// `gtapath`, а площадка в `gtaPlatform`. Имена полей не наши: так они названы у
/// alt:V, и файл настроек переносят с одного мультиплеера на другой руками.
///
/// Поиск от этого никуда не делся, но переехал туда, где ему место: в окно
/// установки, где он подсказывает человеку каталог, а решает всё равно человек.

/// Читает выбранную игру.
///
/// Пусто означает, что выбора ещё не было или что по записанному пути игры
/// больше нет: и то и другое ведёт в окно установки.
[[nodiscard]] std::optional<GameLocation> chosenGame(const std::filesystem::path& settingsFile);

/// Записывает выбор в настройки, оставляя всё остальное в них нетронутым.
bool rememberGame(const std::filesystem::path& settingsFile, const GameLocation& location);

} // namespace oxymp::launcher
