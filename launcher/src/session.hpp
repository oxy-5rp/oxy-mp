#pragma once

#include "game_process.hpp"

#include <filesystem>
#include <functional>
#include <string>
#include <string_view>

namespace oxymp::launcher {

/// Каким путём поднимается игра.
enum class LaunchMode {
    /// Через Rockstar Games Launcher, с подменой звена BattlEye внутри него.
    ///
    /// Штатный путь oxyMP. Игру создаёт лаунчер Rockstar — поэтому он и
    /// показывает её запущенной, — но вместо GTA5_BE.exe запускает сразу
    /// GTA5.exe, и защита сетевого режима не встаёт.
    ViaRockstarLauncher,

    /// Прямой запуск GTA5.exe. Запасной путь.
    ///
    /// Работает без всяких подмен, но лаунчер Rockstar об игре не знает: он
    /// следит за тем процессом, который создал сам.
    Direct,
};

/// Как идут дела у запуска. Отсюда берётся и цвет полосы в окне, и уровень
/// записи в журнал.
enum class Progress {
    /// Идёт работа: ищем игру, поднимаем лаунчер Rockstar, внедряем модуль.
    Working,

    /// Игра запущена и модуль в ней.
    Ready,

    /// Дальше идти некуда.
    Failed,
};

/// Запуск игры и внедрение модуля.
///
/// Вынесено из main потому, что запускать умеют двое: окно подключения и
/// командная строка. Разойдись эти два пути, чинить пришлось бы дважды.
class Session {
public:
    struct Settings {
        std::string server;
        std::string nickname;
        std::filesystem::path gameDirectory;
        std::filesystem::path clientModule;


        /// Подмена звена BattlEye, внедряемая в Rockstar Games Launcher.
        std::filesystem::path launcherPatch;

        /// Куда внедрённые модули пишут свои журналы.
        std::filesystem::path logDirectory;

        /// Куда класть копии чужих файлов, которые пришлось изменить.
        ///
        /// Пока такой файл один — settings.xml игры, и лежит он не в папке игры,
        /// а в документах пользователя. Правится он ради слоя интерфейса: поверх
        /// монопольного полноэкранного режима не показать ничего.
        std::filesystem::path backupDirectory;

        LaunchMode launchMode = LaunchMode::ViaRockstarLauncher;

        /// Вести игру сразу в сетевой свободный режим, минуя сюжет.
        ///
        /// Путь, которым oxyMP пойдёт, когда научится подставлять игре сессию.
        /// Пока не научился, игра по нему остаётся на вечной загрузке GTA
        /// Online, поэтому по умолчанию выключено.
        bool straightIntoFreemode = false;

        /// Не запускать игру, а внедриться в уже запущенную.
        bool attach = false;

        /// Какие признаки сетевой игры подделывать: пусто, `1` либо `full`.
        ///
        /// Разведка: признаки выставляются без объектов сессии, которые
        /// прилагаются к ним в настоящей сетевой игре, и вылет от этого —
        /// ожидаемый исход, а не неожиданность. Ключом, а не пересборкой,
        /// именно поэтому: выключать придётся ровно тогда, когда игра
        /// перестанет запускаться.
        ///
        /// Строкой, а не перечислением, потому что дальше она идёт в окружение
        /// как есть: заводить перечисление, чтобы тут же разобрать его обратно
        /// в ту же строку, значит держать один и тот же список в двух местах.
        std::string networkGameFake;

        /// Просить ли игру поднять настоящую сетевую сессию.
        ///
        /// Единственный правильный путь к сетевому поведению: признак «идёт
        /// сетевая игра» выставляет сама игра, вместе со всеми объектами
        /// сессии, которых не хватало подделке.
        ///
        /// По умолчанию да. Выключатель оставлен на случай, когда из-за него
        /// игра перестанет запускаться: выключать это придётся, не имея
        /// возможности запуститься.
        bool hostSession = true;

        /// Поднимать сессию внутренней функцией игры, а не нативом.
        ///
        /// Натив поднимает сессию на одного и обходится без подбора игроков;
        /// внутренняя функция — тот путь, которым идёт CitizenFX. Способы разные,
        /// и сравнивать их нужно по одному.
        bool sessionRaw = false;

    };

    /// Куда сообщать о ходе дел. Вызывается из того же потока, что и run.
    using Reporter = std::function<void(Progress, std::string_view)>;

    /// Запускает игру и внедряет модуль.
    ///
    /// Возвращает управление сразу после внедрения, не дожидаясь конца игры:
    /// ждать её — дело вызывающего, и в окне это делается иначе, чем в консоли.
    [[nodiscard]] static std::unique_ptr<GameProcess> run(const Settings& settings,
                                                          const Reporter& report);
};

} // namespace oxymp::launcher
