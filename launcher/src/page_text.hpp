#pragma once

#include <string>
#include <string_view>

namespace oxymp::launcher {

/// Мелочи, без которых не обходится ни одно наше окно со страницей внутри.
///
/// Окон таких два — лаунчер и установка, — и разговаривают они со своими
/// страницами одинаково: строкой JSON туда, строкой JSON обратно. Держать это в
/// каждом окне порознь значило бы чинить одну и ту же оплошность дважды; на
/// разборе поля здесь уже спотыкались — вид на временную строку переживал саму
/// строку, и не совпадало ничего.

/// Экранирует строку для вставки в JSON.
///
/// Своими силами, без библиотеки: наружу уходит несколько коротких полей, и
/// заводить ради них зависимость — это менять понятный десяток строк на
/// непонятную сотню килобайт.
[[nodiscard]] std::string escapeJson(std::string_view text);

/// Достаёт строковое поле из JSON.
///
/// Разбор нарочно поверхностный: сообщения приходят с нашей же страницы и
/// состоят из двух-трёх полей. Полноценный разбор здесь решал бы задачу,
/// которой нет.
///
/// Отдаёт строку по значению, и это не расточительность: вид на неё пережил бы
/// саму строку, и сравнение с ним сравнивало бы освобождённую память.
[[nodiscard]] std::string jsonField(std::string_view json, std::string_view name);

/// Подставляет в страницу то, что известно только на запуске.
///
/// Замена по месту, а не шаблонизатор: подстановок несколько, и каждая
/// встречается однажды.
[[nodiscard]] std::string fillPage(std::string page, std::string_view token,
                                   std::string_view value);

/// UTF-8 в UTF-16: Windows принимает только широкие строки.
[[nodiscard]] std::wstring widen(std::string_view text);

/// UTF-16 в UTF-8: обратно, для путей, пришедших от Windows.
[[nodiscard]] std::string narrow(std::wstring_view text);

} // namespace oxymp::launcher
