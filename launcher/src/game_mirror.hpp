namespace oxymp::launcher {

/// Своя копия игры, которую не трогает обновление Rockstar.
///
/// Зачем. oxyMP держится на сигнатурах — байтовых образцах кода GTA5.exe. Другая
/// сборка игры это другой GTA5.exe, и все они разъезжаются разом: мод перестаёт
/// работать в тот день, когда Rockstar что-нибудь обновит, и без предупреждения.
/// Своя копия делает этот день необязательным.
///
/// Как. В каталоге игры заводится подкаталог, а в нём:
///
///   * GTA5.exe — настоящая копия, побайтная. Это единственное, что копируется по
///     существу, и единственное, что действительно важно закрепить.
///
///   * всё остальное — жёсткие ссылки на файлы игры.
///
/// Жёсткая ссылка это второе имя того же файла. Места на диске она не занимает
/// вовсе: сто гигабайт игры остаются одними и теми же ста гигабайтами. И она
/// переживает обновление: обновление подменяет файл целиком — пишет новый и
/// занимает им имя, — а наше имя продолжает указывать на прежнее содержимое.
///
/// Два условия, и оба от файловой системы, а не от нас.
///
/// Первое: зеркало обязано лежать на том же диске, что и игра. Жёсткая ссылка не
/// пересекает границу тома.
///
/// Второе: заводить второе имя для чужого файла вправе тот, кто вправе этот файл
/// менять. Игра стоит в Program Files, где у обычного пользователя только чтение,
/// — значит зеркало собирается один раз с правами администратора. Дальше права не
/// нужны: играть по готовым ссылкам можно как угодно.
///
/// Чего это не даёт. Полной независимости от Rockstar: права на игру по-прежнему
/// выдаёт их лаунчер, и он должен быть запущен. Речь только о том, чтобы
/// обновление игры не превращало мод в неработающий.
class GameMirror {
public:
    /// Что получилось.
    struct Report {
        /// Куда запускаться. Здесь лежит закреплённый GTA5.exe.
        GameLocation location;

        /// Сколько ссылок сделано в этот раз. Ноль — зеркало уже было готово.
        std::size_t linked = 0;

        /// Разошлась ли закреплённая копия с установленной игрой.
        ///
        /// Разошлась — значит игра обновилась, а мы запускаем прежнюю. Ровно то,
        /// ради чего всё и заводилось, но сказать об этом надо вслух: человек
        /// должен понимать, что играет не в то, что у него установлено.
        bool gameUpdated = false;
    };

    /// Готовит зеркало и возвращает, откуда запускаться.
    ///
    /// preferred — где его хотелось бы видеть, обычно рядом с oxymp.exe. Если
    /// это другой диск, зеркало уходит к игре: выбор тут не между «удобно» и
    /// «неудобно», а между «работает» и «нет».
    ///
    /// Идемпотентно: готовое зеркало не переделывается, а дополняется тем, чего
    /// в нём не хватает. Первый раз занимает секунды, дальше — мгновение.
    ///
    /// needsAdministrator отделяет «не хватило прав» от прочих неудач. Отделять
    /// нужно потому, что лечится это по-разному: права спрашиваются у Windows и
    /// работа продолжается, а всё остальное требует человека.
    [[nodiscard]] static std::optional<Report> prepare(const GameLocation& game,
                                                       const std::filesystem::path& preferred,
                                                       std::string& error,
                                                       bool& needsAdministrator);

private:
    GameMirror() = delete;
};

} // namespace oxymp::launcher
