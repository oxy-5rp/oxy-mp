#pragma once

#include "game_locator.hpp"
#include "paths.hpp"

#include <optional>

namespace oxymp::launcher {

/// Окно установки: где лежит игра и через какую площадку она куплена.
///
/// Показывается один раз — пока в `oxymp.toml` нет `gtapath`, — и после этого не
/// показывается больше никогда. Так же ведёт себя alt:V, и по той же причине:
/// путь к игре не меняется от запуска к запуску, а разыскивать её заново значит
/// каждый раз заново же и ошибаться.
///
/// Оформление своё, но из того же `skin.bin`: фон — `installerBackground`, имя и
/// значок — те же, что у окна лаунчера. Размер окна равен размеру картинки, как
/// и там.
///
/// Поиск установленной игры отсюда никуда не делся: окно открывается и сразу
/// принимается искать, чтобы подставить найденное в поле. Но подставляет оно
/// подсказку, а решает человек — и решение записывается.
class SetupWindow {
public:
    /// Спрашивает каталог игры и площадку и записывает ответ в `oxymp.toml`.
    ///
    /// Возвращает выбранную игру. Пусто означает, что человек закрыл окно, не
    /// выбрав ничего: запускать в этом случае нечего.
    [[nodiscard]] static std::optional<GameLocation> ask(const Paths& paths);
};

} // namespace oxymp::launcher
