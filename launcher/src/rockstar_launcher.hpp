#pragma once

#include <chrono>
#include <string>

namespace oxymp::launcher {

/// Готовит Rockstar Games Launcher к запуску игры.
///
/// GTA5.exe при старте спрашивает у лаунчера права на игру по именованному
/// каналу. Не получив ответа, игра закрывается с ERR_NO_LAUNCHER — поэтому
/// лаунчер поднимается до игры, а не вместе с ней.
///
/// Если лаунчер уже работает, ничего не происходит. Иначе он запускается и
/// функция ждёт появления канала: это точный признак готовности, в отличие от
/// факта существования процесса, который поднимается заметно раньше, чем
/// начинает отвечать.
///
/// Вход в учётную запись при этом не проверяется и проверен быть не может:
/// об отсутствии прав на игру сообщает уже сама игра.
[[nodiscard]] bool ensureRockstarLauncherReady(std::chrono::seconds timeout, std::string& error);

} // namespace oxymp::launcher
