#pragma once

#include <chrono>
#include <string>

namespace oxymp::launcher {

/// Готовит Rockstar Games Launcher к запуску игры.
///
/// GTA5.exe при старте спрашивает у лаунчера права на игру по именованному
/// каналу. Не получив ответа, игра закрывается с ERR_NO_LAUNCHER — поэтому
/// лаунчер поднимается до игры, а не вместе с ней.
///
/// Если лаунчер уже работает, ничего не происходит. Иначе он запускается и
/// функция ждёт появления канала: это точный признак готовности, в отличие от
/// факта существования процесса, который поднимается заметно раньше, чем
/// начинает отвечать.
///
/// Вход в учётную запись при этом не проверяется и проверен быть не может:
/// об отсутствии прав на игру сообщает уже сама игра.
[[nodiscard]] bool ensureRockstarLauncherReady(std::chrono::seconds timeout, std::string& error);

/// Закрывает Rockstar Games Launcher.
///
/// Зовётся после удавшегося внедрения, и только тогда. Права на игру лаунчер
/// выдаёт один раз — при её запуске, по именованному каналу, — и к мгновению,
/// когда наш модуль оказался внутри GTA5.exe, своё дело он сделал. Дальше он
/// только занимает память и место в панели задач.
///
/// Есть и вторая причина, и она не про игрока. В лаунчере остаётся наша подмена
/// звена BattlEye: выгрузить её оттуда нельзя — снимать перехват на живом
/// лаунчере опаснее, чем оставить, — а `Launcher.exe` переживает и игру, и нас.
/// Пока он работает, `oxymp-launcher-patcher.dll` занят, и пересборка отвечает
/// `LNK1104`. Закрытый лаунчер снимает и это.
///
/// Закрывается один `Launcher.exe`. Ни `RockstarService.exe`, ни
/// `SocialClubHelper.exe` не трогаются: первый обслуживает не только игру, а
/// второй ведёт наложение Social Club внутри неё — и закрытый, он унёс бы с
/// собой то, чего мы не давали.
///
/// Возвращает false, если закрывать было нечего или не вышло. Беда из этого не
/// следует никакая: игра уже идёт, а лишний лаунчер человек закроет и сам.
bool closeRockstarLauncher(std::string& note);

} // namespace oxymp::launcher
