#pragma once

#include <oxymp/shared/protocol/messages.hpp>

#include <cstdint>

namespace oxymp::script::js {

/// Как называется место в машине у нас и как — у alt:V.
///
/// Нумерации две, и они разные. У игры, а значит и у нашего протокола, водитель
/// — это место `-1`, пассажиры идут с нуля, а `-2` означает «ни в какой машине»
/// (`shared::kDriverSeat`, `shared::kNoSeat`). У alt:V водитель — единица,
/// пассажиры идут с двойки, а ноль означает то же «нигде».
///
/// **Это стоило молчаливой поломки всякому режиму, написанному под alt:V.**
/// Числа обеих нумераций законны, и подмена одной на другую не даёт ни ошибки,
/// ни строки в журнале: `player.setIntoVehicle(car, 1)` — «за руль» у alt:V —
/// сажал человека на второе пассажирское место, а `player.seat === 1` не
/// совпадало никогда, потому что водитель отвечал `-1`. У проверенного режима
/// таких мест нашлось семь.
///
/// Перевод делается ровно на границе скриптового слоя и только там: по сети, в
/// клиенте и в реестрах сервера нумерация остаётся игровой. Иначе пришлось бы
/// переводить в каждом снимке, а ошибка в переводе стоила бы не чужого места в
/// машине, а разъехавшейся синхронизации.
///
/// Смещение оказалось одним и тем же для всех трёх случаев — `-2` → `0`,
/// `-1` → `1`, `0` → `2`, — и потому переводом занимается сложение, а не
/// таблица с тремя ветвями.
inline constexpr std::int32_t kSeatShift = 2;

/// Наше место — в число alt:V.
[[nodiscard]] constexpr std::int32_t toAltSeat(std::int8_t seat) noexcept {
    return static_cast<std::int32_t>(seat) + kSeatShift;
}

/// Число alt:V — в наше место.
///
/// Довод шире байта нарочно: приходит он из JavaScript, где числом бывает что
/// угодно, и обрезать его до байта раньше проверки значило бы принять `258` за
/// водителя.
[[nodiscard]] constexpr std::int8_t fromAltSeat(std::int64_t seat) noexcept {
    const std::int64_t shifted = seat - kSeatShift;

    // За границы байта не выпускаем: место в машине — маленькое число, а
    // пришедшее из скрипта могло быть каким угодно. Всё несуразное означает
    // «никуда»: это честнее, чем усадить человека на место, которого нет.
    if (shifted < shared::kNoSeat || shifted > 127) {
        return shared::kNoSeat;
    }

    return static_cast<std::int8_t>(shifted);
}

/// Что означает «место не названо» у alt:V.
///
/// `setIntoVehicle` без второго довода у alt:V сажает за руль, а не «никуда»:
/// так написана его подпись, и так поступают режимы. Прежде здесь стояло
/// `kNoSeat`, и просьба без места не сажала никуда вовсе.
inline constexpr std::int64_t kAltDriverSeat = 1;

} // namespace oxymp::script::js
