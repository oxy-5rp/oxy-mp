#pragma once

#include <string>

namespace oxymp::script::js {

/// Подгружает libnode.dll — саму библиотеку движка.
///
/// Обычно этим занимается Windows при запуске процесса, и заниматься этим
/// вручную не пришлось бы. Здесь иначе, и по двум причинам сразу.
///
/// **Node объявлен необязательным.** Сервер без него собирается и работает —
/// голый сервер не меняется вовсе. Обычная ссылка на библиотеку означала бы, что
/// Windows разрешает её до первой нашей строки: не найдя файла, она закрывает
/// процесс окном «не найден libnode.dll». Ни журнала, ни объяснения, ни чата —
/// сервер не поднялся бы вообще. С подгрузкой по требованию он поднимается как
/// всегда и жалуется ровно тому, кто перечислил ресурс на JS.
///
/// **Библиотеке место не в корне.** Сто мегабайт чужого движка рядом с
/// двухмегабайтным сервером и настройками сбивают с толку того, кто открыл
/// каталог впервые. Windows при запуске ищет только рядом с исполняемым файлом, а
/// загруженную вручную — там, где скажут; отсюда `modules/js`, как у alt:V.
///
/// Зовётся один раз, из Engine::create, и до первого обращения к чему-либо из
/// Node. Повторный вызов ничего не делает: библиотека уже в процессе.
///
/// false — с объяснением в error, где сказано и то, где её искали.
[[nodiscard]] bool ensureNodeLibrary(std::string& error);

} // namespace oxymp::script::js
