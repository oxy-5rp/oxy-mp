#pragma once

#include <cstdint>
#include <functional>
#include <memory>
#include <string>

namespace oxymp::patcher {

/// Звено BattlEye в цепочке запуска Rockstar Games Launcher.
///
/// Лаунчер поднимает игру не сам: он запускает GTA5_BE.exe, а тот уже
/// GTA5.exe. Промежуточное звено поднимает защиту сетевого режима, а она
/// срезает права у описателей процесса игры — проверено на живой игре:
/// ReadProcessMemory отказывает с ошибкой 5 даже в одиночной игре.
///
/// Убрать звено, минуя лаунчер, нельзя: тогда лаунчер не знает о запущенной
/// игре и не показывает её запущенной. Поэтому звено не обходится, а
/// подменяется — лаунчер запускает игру сам, своей же командной строкой, и
/// своим потомком видит настоящую GTA5.exe.
///
/// Ключа командной строки для этого у лаунчера нет. Проверено: `-nobattleye`
/// доходит до Launcher.exe (виден в его командной строке) и не меняет ничего —
/// такой ключ у лаунчера внутренний.
class BattlEyeLink {
public:
    ~BattlEyeLink();

    BattlEyeLink(const BattlEyeLink&) = delete;
    BattlEyeLink& operator=(const BattlEyeLink&) = delete;

    /// Кого известить о запущенной игре. Вызывается из потока лаунчера, в
    /// котором тот запускает игру.
    using Reporter = std::function<void(std::uint32_t processId)>;

    /// Что делать с очередным запуском игры.
    struct Order {
        /// Подменять ли звено BattlEye вообще.
        bool substitute = false;

        /// Добавлять ли ключ входа сразу в сетевой свободный режим.
        bool straightIntoFreemode = false;

        /// На каком языке запускать игру: `ru-RU`, `en-US` и так далее.
        ///
        /// Пусто означает «не трогать» — тогда язык остаётся тем, что назначил
        /// лаунчер Rockstar. Ставится здесь, а не в самой игре, потому что
        /// внутри сессии игра язык сменить не даёт: меню паузы там сетевое, и
        /// выбранную строку оно возвращает обратно.
        std::wstring language;
    };

    /// Спрашивает заказ и тут же его снимает: один запуск — один выстрел.
    ///
    /// Спрашивается в момент запуска игры, а не запоминается при постановке, и
    /// это принципиально дважды. Во-первых, модуль переживает игру — он остаётся
    /// в лаунчере Rockstar до конца его жизни, и второй раз его точка входа не
    /// выполняется; запомненный признак после этого врал бы весь остаток дня.
    /// Во-вторых, лаунчер запускает игру и сам, по кнопке игрока, — и такие
    /// запуски трогать нельзя: без BattlEye игрока не пустит GTA Online.
    using OrderQuery = std::function<Order()>;

    /// Ставит подмену. Перехват один на процесс, поэтому и подмена одна.
    ///
    /// Ключ входа в свободный режим добавляется здесь же: командную строку
    /// составляет лаунчер Rockstar, и подмена звена — единственное место, где её
    /// ещё можно дополнить, изнутри процесса она уже прочитана.
    [[nodiscard]] static std::unique_ptr<BattlEyeLink> install(Reporter report, OrderQuery order,
                                                               std::string& error);

private:
    BattlEyeLink() = default;
};

} // namespace oxymp::patcher
