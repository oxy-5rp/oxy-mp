#pragma once

#include "entity.hpp"

#include <oxymp/shared/protocol/messages.hpp>

#include <string>
#include <vector>

namespace oxymp::script {

/// Что произошло в сессии.
///
/// Номера закреплены навсегда, как и у сообщений протокола: значение, однажды
/// присвоенное событию, за ним и остаётся.
enum class EventKind : std::uint8_t {
    /// Игрок прошёл рукопожатие и числится в сессии.
    PlayerConnect = 0,

    /// Соединение закрыто.
    ///
    /// Объявляется до уборки, и это не мелочь: обработчик застаёт игрока ещё в
    /// реестре — с именем, положением и машиной, в которой он ехал. Именно это и
    /// нужно тому, кто сохраняет игрока перед выходом; объяви мы событие после,
    /// сохранять было бы нечего.
    ///
    /// Уйти от этого решения назад нельзя молча: скрипты будут на него
    /// опираться.
    PlayerDisconnect = 1,

    /// Игрок появился в мире.
    PlayerSpawn = 2,

    /// Игрока убили. killer недействителен, если убийцы не было: падение,
    /// утопление, взрыв собственной машины.
    PlayerDeath = 3,

    /// Игрок написал в чат. Единственное событие, которое можно отменить.
    PlayerChat = 4,

    VehicleCreate = 5,
    VehicleDestroy = 6,

    /// Такт сервера. Приходит чаще всего и потому первый кандидат на то, чтобы
    /// подвесить сервер тяжёлым обработчиком.
    Tick = 7,

    /// Клиент прислал именованное событие: нажат пункт меню, отправлена форма.
    ///
    /// Имя лежит в name, нагрузка — в text. Ни то ни другое сервером не
    /// проверено: пакет собрать может кто угодно, и обработчик обязан начинать с
    /// вопроса, вправе ли этот игрок просить о таком.
    ClientEvent = 8,

    /// По машине попали.
    ///
    /// Свидетельствует о попадании тот, кто попал: у него машина стоит в мире и
    /// принимает пули по-настоящему. Сервер попадание проверяет, передаёт
    /// ведущему машины и объявляет здесь — то есть в том же месте и в том же
    /// порядке, что и смерть от чужой руки.
    ///
    /// Машина лежит в vehicle, стрелявший — в killer, оружие — в weapon, а сама
    /// убыль прочности — в harm. Стрелявший назван killer, а не player, и это не
    /// натяжка: у обоих событий про урон второй участник — тот, кто его нанёс, и
    /// разводить его по двум полям значило бы завести два имени для одного.
    VehicleDamage = 9,

    /// Игрок полез в машину: открывает дверь, но ещё не сидит.
    ///
    /// Все четыре события про машины выводятся из снимка, а не приходят
    /// отдельным сообщением, и это не срезание угла: снимок и есть
    /// единственное, что о посадке известно. Клиент шлёт признак входа,
    /// признак «сижу», номер машины и место — больше сказать нечего, и слать
    /// отдельное сообщение значило бы пересказать уже сказанное.
    ///
    /// **Вывести это можно только сравнением с прошлым снимком, и потому
    /// сравнение живёт у сервера, а не у скрипта.** Скрипт сравнить не может:
    /// снимки до него не доходят, а спрошенное в такте состояние он застаёт
    /// уже переменившимся.
    PlayerEnteringVehicle = 10,

    /// Игрок сел: место назначено, дверь закрыта.
    PlayerEnteredVehicle = 11,

    /// Игрок вылез.
    ///
    /// Машина и место здесь — те, из которых он вылез: к мгновению, когда он
    /// перестаёт числиться сидящим, у него уже нет ни того ни другого, и взять
    /// их можно только из прошлого снимка.
    PlayerLeftVehicle = 12,

    /// Игрок пересел, не выходя: с пассажирского за руль и обратно.
    ///
    /// Отдельно от посадки, а не «вышел и сел»: у alt:V это своё событие, и
    /// режим, следящий за тем, кто за рулём, ждёт именно его. Прежнее место
    /// лежит в seatWas, новое — в seat.
    PlayerChangedVehicleSeat = 13,

    /// Игрок сменил оружие в руках.
    ///
    /// Прежний ствол в weaponWas, нынешний — в weapon. Выводится из снимка тем
    /// же сравнением, что и всё выше: оружие в руках ходит в каждом снимке, а
    /// событие о его смене не объявлялось никогда.
    PlayerWeaponChange = 14,

    /// Игроку нанесли урон.
    ///
    /// Объявляется там же, где урон и применяется, — иначе разошлись бы числа:
    /// броня принимает удар первой и целиком, и сколько досталось здоровью,
    /// известно только тому, кто их развёл.
    ///
    /// Жертва в player, ударивший — в killer (пусто, если его не было), оружие
    /// — в weapon, а убыль здоровья и брони — в healthHarm и armourHarm.
    PlayerDamage = 15,

    /// Сервер поднялся: все ресурсы стартовали, порт слушается.
    ///
    /// Объявляется один раз за жизнь сервера и до первого подключения. Тем оно и
    /// отличается от `resourceStart`, который слышит каждый ресурс о себе:
    /// здесь ресурс узнаёт, что поднялись и все соседи, — а значит можно
    /// обращаться к ним, а не только к себе.
    ///
    /// Доводов нет вовсе, и это тоже как у alt:V.
    ServerStarted = 16,

    /// По игроку попали, и урон ещё не применён.
    ///
    /// **Единственное событие про урон, которое можно отменить**, и в этом весь
    /// его смысл: на нём держатся зоны без стрельбы, неуязвимость по сюжету и
    /// проверка «а мог ли он вообще попасть отсюда». `playerDamage` объявляется
    /// после и отменять уже нечего — там урон применён.
    ///
    /// Отменяется возвратом `false`, как и реплика в чат. Числом урон здесь не
    /// правится, хотя alt:V это умеет: ядро возвращает признак, а не число, и
    /// притворяться, что число доходит, было бы хуже, чем сказать прямо.
    /// Обработчик, вернувший число, услышит об этом один раз в журнал.
    ///
    /// Жертва в player, стрелявший — в killer, оружие — в weapon, урон целиком
    /// (до того, как броня возьмёт своё) — в healthHarm.
    WeaponDamage = 17,

    /// Хозяин сервера набрал строку в его окне.
    ///
    /// Имя команды — в name, её доводы — в arguments. Сам сервер набранным не
    /// распоряжается: команд у голого сервера нет и не будет, как нет их и у
    /// клиента. Что делать со строкой, решает режим — так же, как у alt:V.
    ConsoleCommand = 18,

    /// Загудели или перестали гудеть.
    ///
    /// Машина в vehicle, её ведущий — в player, нажат ли гудок — в `on`.
    /// Выводится из снимка машины сравнением, как и события про посадку: гудок
    /// приходит признаком, а не сообщением.
    ///
    /// У alt:V это событие отменяемое, у нас нет: гудок уже прозвучал в игре у
    /// ведущего, и отменить его отсюда нечем. Обработчик, вернувший `false`,
    /// услышит об этом один раз.
    VehicleHorn = 19,

    /// Включили или выключили сирену. Машина в vehicle, признак — в `on`.
    VehicleSiren = 20,

    /// У машины сменился ведущий.
    ///
    /// Машина в vehicle, новый ведущий — в player, прежний — в killer. Имена
    /// полей общие на все события, и здесь они читаются не буквально; у alt:V
    /// доводы зовутся `entity, owner, oldOwner` и идут в том же порядке.
    ///
    /// Недействительный игрок с любой стороны — законное значение: машина без
    /// ведущего просто стоит, и это обычное дело.
    NetOwnerChange = 21,
};

/// Произошедшее, со всем, что к нему прилагается.
///
/// Одной структурой на все события, а не иерархией с приведением типов. Полей
/// немного, и незанятые ничего не стоят; иерархия же заставила бы каждого
/// обработчика начинаться с выяснения, что ему на самом деле пришло.
///
/// Ссылки на сущности здесь живые: разрешаются они при обращении, и обработчик,
/// придержавший событие до следующего кадра, получит честное «этого больше нет»,
/// а не мусор.
struct Event {
    EventKind kind = EventKind::Tick;

    /// Тот, о ком событие. Недействителен у событий про машины и про такт.
    Player player;

    /// Второй участник: убийца в PlayerDeath. Недействителен в остальных.
    Player killer;

    Vehicle vehicle;

    /// Имя события от клиента или команды из консоли. Имеет смысл при
    /// ClientEvent и ConsoleCommand.
    std::string name;

    /// Доводы команды из консоли, по одному на слово. Имеет смысл только там.
    std::vector<std::string> arguments;

    /// Текст: реплика в PlayerChat, причина в PlayerDisconnect, полезная
    /// нагрузка в ClientEvent.
    std::string text;

    /// Оружие, которым убили или попали по машине. Имеет смысл в PlayerDeath,
    /// VehicleDamage, PlayerDamage и PlayerWeaponChange.
    std::uint32_t weapon = 0;

    /// Чем он был вооружён до этого. Имеет смысл только в PlayerWeaponChange.
    std::uint32_t weaponWas = 0;

    /// Место в машине — то, которое стало. В нумерации игры: минус единица за
    /// руль, дальше по счёту. Перевод в нумерацию alt:V делает слой alt:V, а не
    /// ядро: у ядра нумерация одна, и она игровая.
    std::int8_t seat = shared::kNoSeat;

    /// Место, которое было. Имеет смысл только в PlayerChangedVehicleSeat.
    std::int8_t seatWas = shared::kNoSeat;

    /// Признак, о котором событие: нажат ли гудок, включена ли сирена.
    /// Имеет смысл в VehicleHorn и VehicleSiren.
    bool on = false;

    /// Сколько здоровья и брони отнял удар. Имеют смысл только в PlayerDamage.
    ///
    /// Двумя числами, а не одним, потому что двумя их считает и игра: броня
    /// принимает удар первой и целиком, и режим, решающий, спас ли бронежилет,
    /// по сумме не узнал бы ничего.
    std::uint16_t healthHarm = 0;
    std::uint16_t armourHarm = 0;

    /// Сколько прочности машина потеряла. Имеет смысл только в VehicleDamage.
    ///
    /// Тремя числами, а не одним: кузов, двигатель и бак ведут себя по-разному,
    /// и режиму, который решает, заглох ли двигатель или потёк ли бак, сумма не
    /// сказала бы ничего.
    shared::VehicleHarm harm;
};

/// Тот, кто слушает события.
///
/// Возвращаемый признак означает «пропустить дальше». Считается он у двоих —
/// PlayerChat и WeaponDamage, — и только у тех событий, которые имеет смысл
/// отменять: скрипту нужно уметь перехватить команду вида «/kick» и не пустить
/// её в общий чат, а зоне без стрельбы — не пустить попадание. Отменять вход
/// игрока или создание машины скрипту незачем, и делать вид, что он на это
/// влияет, было бы обманом.
class Listener {
public:
    virtual ~Listener() = default;

    [[nodiscard]] virtual bool handle(const Event& event) = 0;
};

/// Список слушателей и рассылка по нему.
///
/// Слушатели вызываются по порядку подписки, и порядок этот значим: первый
/// подписавшийся первым и получит возможность отменить реплику.
///
/// Отменившее событие останавливает рассылку: слушателю, стоящему следом,
/// сообщать о реплике, которой не будет, незачем.
class Events {
public:
    /// Подписывает слушателя. Он обязан пережить эту рассылку.
    ///
    /// Указатель, а не владение: слушателями будут ресурсы, а живут они дольше
    /// подписки и принадлежат не событиям.
    void subscribe(Listener* listener);

    /// Отписывает. Молча, если такого и не было.
    void unsubscribe(Listener* listener);

    /// Рассылает событие. false — кто-то из слушателей его отменил.
    bool dispatch(const Event& event);

    [[nodiscard]] std::size_t size() const noexcept { return listeners_.size(); }

private:
    std::vector<Listener*> listeners_;
};

} // namespace oxymp::script
