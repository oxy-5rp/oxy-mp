#pragma once

#include "entity.hpp"

#include <string>
#include <vector>

namespace oxymp::script {

/// Что произошло в сессии.
///
/// Номера закреплены навсегда, как и у сообщений протокола: значение, однажды
/// присвоенное событию, за ним и остаётся.
enum class EventKind : std::uint8_t {
    /// Игрок прошёл рукопожатие и числится в сессии.
    PlayerConnect = 0,

    /// Соединение закрыто.
    ///
    /// Объявляется до уборки, и это не мелочь: обработчик застаёт игрока ещё в
    /// реестре — с именем, положением и машиной, в которой он ехал. Именно это и
    /// нужно тому, кто сохраняет игрока перед выходом; объяви мы событие после,
    /// сохранять было бы нечего.
    ///
    /// Уйти от этого решения назад нельзя молча: скрипты будут на него
    /// опираться.
    PlayerDisconnect = 1,

    /// Игрок появился в мире.
    PlayerSpawn = 2,

    /// Игрока убили. killer недействителен, если убийцы не было: падение,
    /// утопление, взрыв собственной машины.
    PlayerDeath = 3,

    /// Игрок написал в чат. Единственное событие, которое можно отменить.
    PlayerChat = 4,

    VehicleCreate = 5,
    VehicleDestroy = 6,

    /// Такт сервера. Приходит чаще всего и потому первый кандидат на то, чтобы
    /// подвесить сервер тяжёлым обработчиком.
    Tick = 7,

    /// Клиент прислал именованное событие: нажат пункт меню, отправлена форма.
    ///
    /// Имя лежит в name, нагрузка — в text. Ни то ни другое сервером не
    /// проверено: пакет собрать может кто угодно, и обработчик обязан начинать с
    /// вопроса, вправе ли этот игрок просить о таком.
    ClientEvent = 8,
};

/// Произошедшее, со всем, что к нему прилагается.
///
/// Одной структурой на все события, а не иерархией с приведением типов. Полей
/// немного, и незанятые ничего не стоят; иерархия же заставила бы каждого
/// обработчика начинаться с выяснения, что ему на самом деле пришло.
///
/// Ссылки на сущности здесь живые: разрешаются они при обращении, и обработчик,
/// придержавший событие до следующего кадра, получит честное «этого больше нет»,
/// а не мусор.
struct Event {
    EventKind kind = EventKind::Tick;

    /// Тот, о ком событие. Недействителен у событий про машины и про такт.
    Player player;

    /// Второй участник: убийца в PlayerDeath. Недействителен в остальных.
    Player killer;

    Vehicle vehicle;

    /// Имя события от клиента. Имеет смысл только при ClientEvent.
    std::string name;

    /// Текст: реплика в PlayerChat, причина в PlayerDisconnect, полезная
    /// нагрузка в ClientEvent.
    std::string text;

    /// Оружие, которым убили. Имеет смысл только в PlayerDeath.
    std::uint32_t weapon = 0;
};

/// Тот, кто слушает события.
///
/// Возвращаемый признак означает «пропустить дальше». Считается он только у
/// PlayerChat — единственного события, которое имеет смысл отменять: скрипту
/// нужно уметь перехватить команду вида «/kick» и не пустить её в общий чат.
/// Отменять вход игрока или создание машины скрипту незачем, и делать вид, что
/// он на это влияет, было бы обманом.
class Listener {
public:
    virtual ~Listener() = default;

    [[nodiscard]] virtual bool handle(const Event& event) = 0;
};

/// Список слушателей и рассылка по нему.
///
/// Слушатели вызываются по порядку подписки, и порядок этот значим: первый
/// подписавшийся первым и получит возможность отменить реплику.
///
/// Отменившее событие останавливает рассылку: слушателю, стоящему следом,
/// сообщать о реплике, которой не будет, незачем.
class Events {
public:
    /// Подписывает слушателя. Он обязан пережить эту рассылку.
    ///
    /// Указатель, а не владение: слушателями будут ресурсы, а живут они дольше
    /// подписки и принадлежат не событиям.
    void subscribe(Listener* listener);

    /// Отписывает. Молча, если такого и не было.
    void unsubscribe(Listener* listener);

    /// Рассылает событие. false — кто-то из слушателей его отменил.
    bool dispatch(const Event& event);

    [[nodiscard]] std::size_t size() const noexcept { return listeners_.size(); }

private:
    std::vector<Listener*> listeners_;
};

} // namespace oxymp::script
