#pragma once

#include <cstdint>

namespace oxymp::script {

/// Измерение: в каком слое мира находится сущность.
///
/// Одно и то же место карты можно занять много раз, и находящиеся в разных
/// измерениях друг друга не видят вовсе. Этим делаются квартиры, интерьеры и
/// отдельные сцены: десять пар в десяти одинаковых квартирах, стоящих в одной
/// точке, и никто никому не мешает.
///
/// Числа взяты у alt:V разряд в разряд (`ICore.h`, `DEFAULT_DIMENSION` и
/// `GLOBAL_DIMENSION`): режим, написанный под него, пишет их прямо в коде, и
/// разойтись здесь значило бы сломать его молча.
///
/// Правило видимости живёт целиком на сервере, и клиент про измерения не знает
/// ничего. Так и должно быть: не рассказать клиенту о том, чего он не должен
/// видеть, — единственный способ не дать ему это увидеть. Расскажи мы, а
/// прятать поручи ему, — и первый же изменённый клиент увидел бы всех.
inline constexpr std::int32_t kDefaultDimension = 0;

/// Измерение, из которого видно всех и в котором видно всех.
///
/// Наименьшее возможное число: у alt:V это ровно оно, и совпадение не
/// случайно — так значение не пересекается ни с одним осмысленным номером.
inline constexpr std::int32_t kGlobalDimension = -2147483647 - 1;

/// Видят ли друг друга те, кто в этих измерениях.
///
/// Правило простое и симметричное: либо измерение одно, либо хоть один из двоих
/// в общем. Несимметричным его делать нельзя, и это не вкус: видимость,
/// работающая в одну сторону, означает игрока, который стреляет в того, кто его
/// не видит.
[[nodiscard]] constexpr bool dimensionsMeet(std::int32_t left, std::int32_t right) noexcept {
    return left == right || left == kGlobalDimension || right == kGlobalDimension;
}

} // namespace oxymp::script
